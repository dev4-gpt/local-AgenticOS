import { expect, test } from "@playwright/test";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { PGlite } from "@electric-sql/pglite";
import { pgcrypto } from "@electric-sql/pglite/contrib/pgcrypto";

// Real PostgreSQL (PGlite) tests for product-experience/supabase-client-adapter-budget.sql.
// PGlite has one connection, so these prove the arithmetic and the one-after-another behaviour. True simultaneous
// requests are covered by adapter-budget-concurrency.spec.ts when a real Postgres is configured.
// Users, tenants and tokens are created inside each test; nothing real is used.
const HOST_SQL = readFileSync("product-experience/supabase-client-adapter-host.sql", "utf8");
const BUDGET_SQL = readFileSync("product-experience/supabase-client-adapter-budget.sql", "utf8");
const OWNER = "00000000-0000-4000-8000-0000000000a1";
const WORKER = "test-worker-token-aaaaaaaaaaaaaaaaaaaa";
const sha = (text: string) => createHash("sha256").update(text).digest("hex");

async function freshDb() {
  const db = new PGlite({ extensions: { pgcrypto } });
  await db.exec(`
    create schema extensions; create extension pgcrypto with schema extensions;
    create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth;
    create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    create table auth.users(id uuid primary key);
    create table public.client_tenants(slug text primary key, status text not null default 'active', worker_token_hash text);
    create table public.client_memberships(
      tenant_slug text not null references public.client_tenants(slug) on delete cascade,
      user_id uuid not null references auth.users(id), role text not null, status text not null default 'active',
      primary key (tenant_slug, user_id));
    create function public.client_member(p_tenant_slug text) returns boolean language sql stable security definer set search_path = public as $$
      select exists (select 1 from public.client_memberships where tenant_slug = p_tenant_slug and user_id = auth.uid() and status = 'active') $$;
    create table public.client_runtime_budget_ledger (
      id bigint generated by default as identity primary key,
      tenant_slug text not null references public.client_tenants(slug) on delete cascade,
      job_id uuid, provider text not null, model text,
      amount_micros bigint not null check (amount_micros >= 0),
      usage_metadata jsonb not null default '{}'::jsonb,
      created_at timestamptz not null default now());
    grant usage on schema public, auth, extensions to anon, authenticated, service_role;
    grant execute on function public.client_member(text) to authenticated;
    insert into auth.users values ('${OWNER}');
    insert into public.client_tenants(slug, worker_token_hash) values ('tenant-a', '${sha(WORKER)}'), ('tenant-b', '${sha(WORKER)}');
    insert into public.client_memberships values ('tenant-a', '${OWNER}', 'owner', 'active'), ('tenant-b', '${OWNER}', 'owner', 'active');
  `);
  await db.exec(HOST_SQL);
  await db.exec(BUDGET_SQL);
  await db.exec(BUDGET_SQL); // safe to repeat
  await db.query("select set_config('request.jwt.claim.sub',$1,false)", [OWNER]);
  await db.exec("set role authenticated");
  for (const adapter of ["forge", "knowledge"]) {
    await db.query(
      "insert into public.client_adapter_registry (tenant_slug, adapter_id, display_name, contract_version, manifest_sha256) values ('tenant-a',$1,$1,'h1',$2)",
      [adapter, "a".repeat(64)],
    );
  }
  await db.exec("reset role");
  await db.exec("update public.client_adapter_registry set state = 'enabled'");
  return db;
}

const setCap = async (db: PGlite, adapter: string, cap: number | null, period: string | null) => {
  await db.exec("reset role");
  return db.query("update public.client_adapter_registry set budget_cap_micros = $2, budget_period = $3 where adapter_id = $1", [adapter, cap, period]);
};

async function reserve(db: PGlite, o: { adapter?: string; task: string; key?: string; amount: number; tenantCap?: number; token?: string; tenant?: string }) {
  await db.exec("reset role; set role anon");
  const r = await db.query<{ s: string }>(
    "select public.client_adapter_budget_reserve($1,$2,$3,$4,$5,$6,'provider-x','model-x',$7) as s",
    [o.tenant ?? "tenant-a", o.token ?? WORKER, o.adapter ?? "forge", o.task, o.key ?? `reserve-key-${o.task}`, o.amount, o.tenantCap ?? 1_000_000],
  );
  return r.rows[0].s;
}
async function settle(db: PGlite, task: string, amount: number, key = `settle-key-${task}`, adapter = "forge") {
  await db.exec("reset role; set role anon");
  return (await db.query<{ s: string }>("select public.client_adapter_budget_settle('tenant-a',$1,$2,$3,$4,$5) as s", [WORKER, adapter, task, key, amount])).rows[0].s;
}
async function release(db: PGlite, task: string, key = `release-key-${task}`, adapter = "forge") {
  await db.exec("reset role; set role anon");
  return (await db.query<{ s: string }>("select public.client_adapter_budget_release('tenant-a',$1,$2,$3,$4) as s", [WORKER, adapter, task, key])).rows[0].s;
}
async function ledger(db: PGlite) {
  await db.exec("reset role");
  return (await db.query<{ amount_micros: string }>("select amount_micros from public.client_runtime_budget_ledger order by id")).rows.map((r) => Number(r.amount_micros));
}
async function total(db: PGlite) {
  return (await ledger(db)).reduce((a, b) => a + b, 0);
}

test("reserve then settle: one central ledger row changes to the real cost and two events are logged", async () => {
  const db = await freshDb();
  try {
    expect(await reserve(db, { task: "task-1", amount: 500 })).toBe("reserved");
    expect(await ledger(db)).toEqual([500]);
    expect(await settle(db, "task-1", 320)).toBe("settled");
    expect(await ledger(db)).toEqual([320]);
    const events = await db.query<{ kind: string; amount_micros: string }>("select kind, amount_micros from public.client_adapter_budget_events order by created_at, kind desc");
    expect(events.rows.map((e) => `${e.kind}:${e.amount_micros}`).sort()).toEqual(["reserve:500", "settle:320"]);
    const row = await db.query<{ usage_metadata: Record<string, unknown>; job_id: string | null }>("select usage_metadata, job_id from public.client_runtime_budget_ledger");
    expect(row.rows[0].job_id).toBeNull();
    expect(row.rows[0].usage_metadata).toMatchObject({ adapter_id: "forge", task_id: "task-1", settled: true });
  } finally {
    await db.close();
  }
});

test("the adapter cap holds, and settling for less frees room under it", async () => {
  const db = await freshDb();
  try {
    await setCap(db, "forge", 1000, "total");
    expect(await reserve(db, { task: "t1", amount: 600 })).toBe("reserved");
    expect(await reserve(db, { task: "t2", amount: 600 })).toBe("adapter_cap_exceeded");
    expect(await reserve(db, { task: "t3", amount: 400 })).toBe("reserved");
    expect(await reserve(db, { task: "t4", amount: 1 })).toBe("adapter_cap_exceeded");
    expect(await settle(db, "t1", 100)).toBe("settled");
    expect(await reserve(db, { task: "t5", amount: 500 })).toBe("reserved");
    expect(await total(db)).toBe(1000);
  } finally {
    await db.close();
  }
});

test("one adapter's cap does not limit another, and no cap means only the tenant cap applies", async () => {
  const db = await freshDb();
  try {
    await setCap(db, "forge", 100, "total");
    expect(await reserve(db, { task: "t1", amount: 100 })).toBe("reserved");
    expect(await reserve(db, { task: "t2", amount: 1 })).toBe("adapter_cap_exceeded");
    expect(await reserve(db, { adapter: "knowledge", task: "k1", amount: 900 })).toBe("reserved");
  } finally {
    await db.close();
  }
});

test("the tenant monthly cap counts every ledger row, including spending that did not come from adapters", async () => {
  const db = await freshDb();
  try {
    await db.exec("insert into public.client_runtime_budget_ledger (tenant_slug, provider, amount_micros) values ('tenant-a','other',700)");
    expect(await reserve(db, { task: "t1", amount: 400, tenantCap: 1000 })).toBe("tenant_cap_exceeded");
    expect(await reserve(db, { task: "t1", amount: 300, tenantCap: 1000 })).toBe("reserved");
    expect(await reserve(db, { adapter: "knowledge", task: "k1", amount: 1, tenantCap: 1000 })).toBe("tenant_cap_exceeded");
    await db.exec("reset role");
    await db.exec("insert into public.client_runtime_budget_ledger (tenant_slug, provider, amount_micros) values ('tenant-b','other',999999)");
    expect(await reserve(db, { adapter: "knowledge", task: "k2", amount: 0, tenantCap: 1000 })).toBe("reserved");
  } finally {
    await db.close();
  }
});

test("the cap period is respected: old spending drops out of a day cap but not a total cap", async () => {
  const db = await freshDb();
  try {
    await db.exec(`insert into public.client_runtime_budget_ledger (tenant_slug, provider, amount_micros, usage_metadata, created_at)
      values ('tenant-a','p',900,'{"adapter_id":"forge"}'::jsonb, now() - interval '3 days')`);
    await setCap(db, "forge", 1000, "day");
    expect(await reserve(db, { task: "t1", amount: 900 })).toBe("reserved");
    await setCap(db, "forge", 1000, "total");
    expect(await reserve(db, { task: "t2", amount: 200 })).toBe("adapter_cap_exceeded");
  } finally {
    await db.close();
  }
});

test("a repeated key charges once; a reused key with different details, or a second key for the same task, is refused", async () => {
  const db = await freshDb();
  try {
    expect(await reserve(db, { task: "t1", key: "idem-key-1", amount: 500 })).toBe("reserved");
    expect(await reserve(db, { task: "t1", key: "idem-key-1", amount: 500 })).toBe("already_reserved");
    expect(await ledger(db)).toEqual([500]);
    expect(await reserve(db, { task: "t1", key: "idem-key-1", amount: 501 })).toBe("key_conflict");
    expect(await reserve(db, { task: "t2", key: "idem-key-1", amount: 500 })).toBe("key_conflict");
    expect(await reserve(db, { task: "t1", key: "idem-key-2", amount: 500 })).toBe("task_already_reserved");
    expect(await ledger(db)).toEqual([500]);
  } finally {
    await db.close();
  }
});

test("settle cannot exceed the reservation, replays are safe, and a task closes once", async () => {
  const db = await freshDb();
  try {
    await reserve(db, { task: "t1", amount: 500 });
    expect(await settle(db, "t1", 501)).toBe("over_reserved");
    expect(await settle(db, "missing-task", 1)).toBe("not_found");
    expect(await settle(db, "t1", 500, "settle-key-1")).toBe("settled");
    expect(await settle(db, "t1", 500, "settle-key-1")).toBe("already_applied");
    expect(await settle(db, "t1", 400, "settle-key-2")).toBe("already_closed");
    expect(await release(db, "t1", "release-key-1")).toBe("already_closed");
    expect(await settle(db, "t1", 499, "settle-key-1")).toBe("key_conflict");
    expect(await ledger(db)).toEqual([500]);
  } finally {
    await db.close();
  }
});

test("release returns the money to the cap and cannot be repeated for a new key", async () => {
  const db = await freshDb();
  try {
    await setCap(db, "forge", 500, "total");
    await reserve(db, { task: "t1", amount: 500 });
    expect(await reserve(db, { task: "t2", amount: 1 })).toBe("adapter_cap_exceeded");
    expect(await release(db, "t1", "release-key-1")).toBe("released");
    expect(await release(db, "t1", "release-key-1")).toBe("already_applied");
    expect(await release(db, "t1", "release-key-2")).toBe("already_closed");
    expect(await release(db, "nope", "release-key-3")).toBe("not_found");
    expect(await ledger(db)).toEqual([0]);
    expect(await reserve(db, { task: "t2", amount: 500 })).toBe("reserved");
  } finally {
    await db.close();
  }
});

test("fails closed: bad token, wrong tenant, unknown or not-ready adapter, and invalid values are all refused", async () => {
  const db = await freshDb();
  try {
    expect(await reserve(db, { task: "t1", amount: 1, token: "wrong-token-wrong-token-wrong-token" })).toBe("refused");
    expect(await reserve(db, { task: "t1", amount: 1, token: "short" })).toBe("refused");
    expect(await reserve(db, { task: "t1", amount: 1, tenant: "tenant-b" })).toBe("adapter_not_ready");
    expect(await reserve(db, { adapter: "unknown-adapter", task: "t1", amount: 1 })).toBe("adapter_not_ready");
    expect(await reserve(db, { task: "t1", amount: -1 })).toBe("refused");
    expect(await reserve(db, { task: "", amount: 1 })).toBe("refused");
    expect(await reserve(db, { task: "t1", key: "short", amount: 1 })).toBe("refused");
    await db.exec("reset role");
    for (const state of ["disabled", "suspended"]) {
      await db.query("update public.client_adapter_registry set state = $1 where adapter_id = 'forge'", [state]);
      expect(await reserve(db, { task: "t1", amount: 1 })).toBe("adapter_not_ready");
      await db.exec("reset role");
    }
    expect(await ledger(db)).toEqual([]);
  } finally {
    await db.close();
  }
});

test("many requests one after another never pass the cap", async () => {
  const db = await freshDb();
  try {
    await setCap(db, "forge", 1000, "total");
    const results: string[] = [];
    for (let i = 0; i < 10; i++) results.push(await reserve(db, { task: `t${i}`, amount: 300 }));
    expect(results.filter((r) => r === "reserved")).toHaveLength(3);
    expect(results.filter((r) => r === "adapter_cap_exceeded")).toHaveLength(7);
    expect(await total(db)).toBe(900);
  } finally {
    await db.close();
  }
});

test("only the worker role can call the budget functions; members cannot, and the token check helper is private", async () => {
  const db = await freshDb();
  try {
    await db.exec("reset role; set role authenticated");
    await expect(db.query("select public.client_adapter_budget_reserve('tenant-a',$1,'forge','t1','key-t1',1,'p',null,100)", [WORKER])).rejects.toThrow(/permission denied/);
    await expect(db.query("select public.client_adapter_budget_settle('tenant-a',$1,'forge','t1','key-t1',1)", [WORKER])).rejects.toThrow(/permission denied/);
    await expect(db.query("select public.client_adapter_budget_release('tenant-a',$1,'forge','t1','key-t1')", [WORKER])).rejects.toThrow(/permission denied/);
    await db.exec("reset role; set role anon");
    await expect(db.query("select public.client_adapter_worker_ok('tenant-a',$1)", [WORKER])).rejects.toThrow(/permission denied/);
  } finally {
    await db.close();
  }
});

test("the summary shows each adapter's cap, period spend, month spend and open reservations, to members only", async () => {
  const db = await freshDb();
  try {
    await setCap(db, "forge", 1000, "day");
    await reserve(db, { task: "t1", amount: 300 });
    await reserve(db, { task: "t2", amount: 200 });
    await settle(db, "t1", 250);
    await reserve(db, { adapter: "knowledge", task: "k1", amount: 120 });
    await db.exec("reset role");
    await db.exec(`insert into public.client_runtime_budget_ledger (tenant_slug, provider, amount_micros, usage_metadata, created_at)
      values ('tenant-a','p',900,'{"adapter_id":"forge"}'::jsonb, now() - interval '3 days')`);
    // An old charge from before this month: it must not count for an adapter with no cap (no period means this month).
    await db.exec(`insert into public.client_runtime_budget_ledger (tenant_slug, provider, amount_micros, usage_metadata, created_at)
      values ('tenant-a','p',777,'{"adapter_id":"knowledge"}'::jsonb, date_trunc('month', now() at time zone 'utc') at time zone 'utc' - interval '1 day')`);
    await db.query("select set_config('request.jwt.claim.sub',$1,false)", [OWNER]);
    await db.exec("set role authenticated");
    const rows = (await db.query<Record<string, unknown>>("select * from public.client_adapter_budget_summary('tenant-a')")).rows;
    expect(rows.map((r) => r.adapter_id)).toEqual(["forge", "knowledge"]);
    const forge = rows[0];
    expect(Number(forge.budget_cap_micros)).toBe(1000);
    expect(forge.budget_period).toBe("day");
    expect(Number(forge.spent_period_micros)).toBe(450); // 250 settled + 200 reserved today; the 3-day-old row is outside the day
    expect(forge.open_reservations).toBe(1);
    expect(rows[1].budget_cap_micros).toBeNull();
    expect(rows[1].budget_period).toBeNull();
    expect(Number(rows[1].spent_period_micros)).toBe(120); // no cap: "period" means this month, so last month's 777 is left out
    expect(Number(rows[1].spent_month_micros)).toBe(120);
    // someone who is not a member of the tenant, and the anonymous role, get nothing
    await db.exec("reset role");
    await db.exec("insert into auth.users values ('00000000-0000-4000-8000-0000000000ff')");
    await db.query("select set_config('request.jwt.claim.sub',$1,false)", ["00000000-0000-4000-8000-0000000000ff"]);
    await db.exec("set role authenticated");
    expect((await db.query("select * from public.client_adapter_budget_summary('tenant-a')")).rows).toHaveLength(0);
    await db.exec("reset role; set role anon");
    await expect(db.query("select * from public.client_adapter_budget_summary('tenant-a')")).rejects.toThrow(/permission denied/);
  } finally {
    await db.close();
  }
});
