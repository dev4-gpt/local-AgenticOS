import { expect, test } from "@playwright/test";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { PGlite } from "@electric-sql/pglite";
import { pgcrypto } from "@electric-sql/pglite/contrib/pgcrypto";

// Real PostgreSQL (PGlite) tests for product-experience/supabase-client-adapter-spend-rollup.sql (ADR-020, ADR-016):
// the host sets aside an adapter's own spend under its own task key when it starts the task, settles it from what the adapter
// reports when the task ends, and the spend check finds that row from the adapter's own task id. Everything here is made up.
const read = (file: string) => readFileSync(`product-experience/supabase-client-${file}.sql`, "utf8");
const FILES = ["adapter-host", "adapter-token-uses", "adapter-retention-28", "adapter-promotions", "adapter-proposals", "adapter-ingest", "adapter-tombstones", "adapter-budget", "adapter-budget-reconcile", "adapter-model-grants", "adapter-spend-rollup"];
const OWNER = "00000000-0000-4000-8000-0000000000a1";
const ADMIN = "00000000-0000-4000-8000-0000000000a2";
const WORKER = "worker-token-aaaaaaaaaaaaaaaaaaaaaaaa";
const GRANT = "11111111-1111-4111-8111-111111111111";
const KEY = "host-task-0001";
const ADAPTER_TASK = "ft-aaaaaaaaaaaaaaaaaaaaaaaa";
const sha = (text: string) => createHash("sha256").update(text, "utf8").digest("hex");

async function freshDb() {
  const db = new PGlite({ extensions: { pgcrypto } });
  await db.exec(`
    do $$ begin
      if not exists (select 1 from pg_roles where rolname='anon') then create role anon; end if;
      if not exists (select 1 from pg_roles where rolname='authenticated') then create role authenticated; end if;
      if not exists (select 1 from pg_roles where rolname='service_role') then create role service_role bypassrls; end if;
    end $$;
    create schema extensions; create extension pgcrypto with schema extensions;
    create schema auth;
    create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    create table auth.users(id uuid primary key);
    create table public.client_tenants(slug text primary key, status text not null default 'active', worker_token_hash text, retention_days integer not null default 28);
    create table public.client_memberships(
      tenant_slug text not null references public.client_tenants(slug) on delete cascade,
      user_id uuid not null references auth.users(id), role text not null, status text not null default 'active',
      primary key (tenant_slug, user_id));
    create function public.client_member(p_tenant_slug text) returns boolean language sql stable security definer set search_path = public as $$
      select exists (select 1 from public.client_memberships where tenant_slug = p_tenant_slug and user_id = auth.uid() and status = 'active') $$;
    create table public.client_runtime_budget_ledger (
      id bigint generated by default as identity primary key,
      tenant_slug text not null references public.client_tenants(slug) on delete cascade,
      job_id uuid, provider text not null, model text,
      amount_micros bigint not null check (amount_micros >= 0),
      usage_metadata jsonb not null default '{}'::jsonb,
      created_at timestamptz not null default now());
    grant usage on schema public, auth, extensions to anon, authenticated, service_role;
    grant execute on function public.client_member(text) to authenticated;
    insert into auth.users values ('${OWNER}'), ('${ADMIN}');
    insert into public.client_tenants(slug, worker_token_hash) values ('tenant-a', '${sha(WORKER)}'), ('tenant-b', '${sha(WORKER)}');
    insert into public.client_memberships values ('tenant-a', '${OWNER}', 'owner', 'active'), ('tenant-a', '${ADMIN}', 'admin', 'active');
  `);
  for (const file of FILES) await db.exec(read(file));
  await db.exec(read("adapter-spend-rollup")); // safe to apply twice
  await db.exec(`insert into public.client_adapter_registry (tenant_slug, adapter_id, display_name, contract_version, manifest_sha256, created_by, state)
    values ('tenant-a','veloce-proofmint','ProofMint','h1','${"a".repeat(64)}','${OWNER}','enabled'),
           ('tenant-a','creator-os','Creator OS','h1','${"a".repeat(64)}','${OWNER}','enabled'),
           ('tenant-b','veloce-proofmint','ProofMint','h1','${"a".repeat(64)}','${OWNER}','enabled')`);
  return db;
}

const asAnon = (db: PGlite) => db.exec("reset role; set role anon");
const asService = (db: PGlite) => db.exec("reset role; set role service_role");
const asOwner = (db: PGlite) => db.exec("reset role");
async function asUser(db: PGlite, id: string) {
  await db.exec("reset role");
  await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]);
  await db.exec("set role authenticated");
}

/** The starter's database steps for a task: open its grant, reserve the adapter's own spend, then bind the adapter's task id. */
async function startTask(db: PGlite, o: { adapter?: string; key?: string; grant?: string; adapterTask?: string; reserve?: number | null; tenant?: string } = {}) {
  const tenant = o.tenant ?? "tenant-a";
  const adapter = o.adapter ?? "veloce-proofmint";
  const key = o.key ?? KEY;
  await asAnon(db);
  const opened = (await db.query<{ s: string }>(
    "select public.client_adapter_model_grant_open($1,$2,$3,$4,$5::uuid,$6::text[],3,1000, now() + interval '10 minutes') as s",
    [tenant, WORKER, adapter, key, o.grant ?? GRANT, ["groq:openai/gpt-oss-120b"]],
  )).rows[0].s;
  expect(opened).toBe("opened");
  if (o.reserve !== null) {
    const reserved = (await db.query<{ s: string }>(
      "select public.client_adapter_budget_reserve($1,$2,$3,$4,$5,$6,'adapter',null,$7) as s",
      [tenant, WORKER, adapter, key, `own-reserve-${key}`, o.reserve ?? 250_000, 50_000_000],
    )).rows[0].s;
    expect(reserved).toBe("reserved");
  }
  const bound = (await db.query<{ s: string }>("select public.client_adapter_model_grant_bind($1,$2,$3::uuid,$4) as s", [tenant, WORKER, o.grant ?? GRANT, o.adapterTask ?? ADAPTER_TASK])).rows[0].s;
  expect(bound).toBe("bound");
}
async function settleOwn(db: PGlite, adapterTask: string, reported: number | null, o: { tenant?: string; adapter?: string } = {}) {
  await asService(db);
  return (await db.query<{ s: string }>("select public.client_adapter_own_spend_settle($1,$2,$3,$4) as s", [o.tenant ?? "tenant-a", o.adapter ?? "veloce-proofmint", adapterTask, reported])).rows[0].s;
}
async function ownRows(db: PGlite, key = KEY) {
  await asOwner(db);
  return (await db.query<{ kind: string; amount_micros: string; idempotency_key: string; ledger: string }>(
    `select e.kind, e.amount_micros::text, e.idempotency_key, l.amount_micros::text as ledger
       from public.client_adapter_budget_events e join public.client_runtime_budget_ledger l on l.id = e.runtime_budget_ref::bigint
      where e.task_id = $1 order by e.kind`,
    [key],
  )).rows;
}

test("the adapter's own spend is settled at what it reported, once, found from the adapter's own task id", async () => {
  const db = await freshDb();
  try {
    await startTask(db);
    expect(await settleOwn(db, ADAPTER_TASK, 20_010)).toBe("settled");
    const rows = await ownRows(db);
    expect(rows.map((r) => [r.kind, r.amount_micros])).toEqual([["reserve", "250000"], ["settle", "20010"]]);
    expect(rows.every((r) => r.ledger === "20010")).toBe(true); // the ledger now holds the real figure: the rest is free again
    expect(rows.find((r) => r.kind === "settle")!.idempotency_key).toMatch(/^own-settle-[0-9a-f]{32}$/);
    expect(await settleOwn(db, ADAPTER_TASK, 20_010)).toBe("already_closed");
    expect(await settleOwn(db, ADAPTER_TASK, 5)).toBe("already_closed");
    expect((await ownRows(db)).length).toBe(2);
  } finally {
    await db.close();
  }
});

test("a report above the reservation settles at the reservation; a missing report settles the full reservation", async () => {
  const db = await freshDb();
  try {
    await startTask(db, { reserve: 100_000 });
    expect(await settleOwn(db, ADAPTER_TASK, 999_999)).toBe("settled");
    expect((await ownRows(db)).find((r) => r.kind === "settle")!.amount_micros).toBe("100000");
    await startTask(db, { key: "host-task-0002", grant: "22222222-2222-4222-8222-222222222222", adapterTask: "ft-bbbbbbbbbbbbbbbbbbbbbbbb", reserve: 250_000 });
    expect(await settleOwn(db, "ft-bbbbbbbbbbbbbbbbbbbbbbbb", null)).toBe("settled_full");
    expect((await ownRows(db, "host-task-0002")).find((r) => r.kind === "settle")!.amount_micros).toBe("250000");
    expect(await settleOwn(db, "ft-bbbbbbbbbbbbbbbbbbbbbbbb", 0)).toBe("already_closed");
    // a report of zero is a real zero
    await startTask(db, { key: "host-task-0003", grant: "33333333-3333-4333-8333-333333333333", adapterTask: "ft-cccccccccccccccccccccccc" });
    expect(await settleOwn(db, "ft-cccccccccccccccccccccccc", 0)).toBe("settled");
    expect((await ownRows(db, "host-task-0003")).find((r) => r.kind === "settle")!.amount_micros).toBe("0");
  } finally {
    await db.close();
  }
});

test("a task with no own-spend reservation, an unknown task, a model-call row alone or another tenant's task is not touched", async () => {
  const db = await freshDb();
  try {
    await startTask(db, { reserve: null }); // grant only, like the content adapter
    expect(await settleOwn(db, ADAPTER_TASK, 5)).toBe("not_reserved");
    // a model call's own row (<key>/m1) is the host's, never the adapter's own spend
    await asAnon(db);
    expect((await db.query<{ s: string }>("select public.client_adapter_budget_reserve('tenant-a',$1,'veloce-proofmint',$2,'mcr-model-call-1',500,'groq','m',50000000) as s", [WORKER, `${KEY}/m1`])).rows[0].s).toBe("reserved");
    expect(await settleOwn(db, ADAPTER_TASK, 5)).toBe("not_reserved");
    expect(await settleOwn(db, "ft-unknown00000000000000000", 5)).toBe("not_reserved");
    expect(await settleOwn(db, ADAPTER_TASK, 5, { tenant: "tenant-b" })).toBe("not_reserved");
    expect(await settleOwn(db, ADAPTER_TASK, 5, { adapter: "creator-os" })).toBe("not_reserved");
    await asOwner(db);
    expect((await db.query("select 1 from public.client_adapter_budget_events where kind in ('settle','release')")).rows).toHaveLength(0);
  } finally {
    await db.close();
  }
});

test("one adapter can never settle another adapter's reservation, through its grant or through a shared key", async () => {
  const db = await freshDb();
  try {
    // ProofMint's grant points ADAPTER_TASK at KEY; another adapter has a reservation of its own under the same KEY
    await startTask(db, { reserve: null });
    await asAnon(db);
    expect((await db.query<{ s: string }>("select public.client_adapter_budget_reserve('tenant-a',$1,'creator-os',$2,'own-reserve-other-1',700,'adapter',null,50000000) as s", [WORKER, KEY])).rows[0].s).toBe("reserved");
    expect(await settleOwn(db, ADAPTER_TASK, 5, { adapter: "creator-os" })).toBe("not_reserved"); // it has no grant of its own for that id
    // the other adapter's own grant points at a key ProofMint has reserved under
    await asAnon(db);
    expect((await db.query<{ s: string }>("select public.client_adapter_budget_reserve('tenant-a',$1,'veloce-proofmint','host-task-0009','own-reserve-host-task-0009',900,'adapter',null,50000000) as s", [WORKER])).rows[0].s).toBe("reserved");
    await startTask(db, { adapter: "creator-os", key: "host-task-0009", grant: "44444444-4444-4444-8444-444444444444", adapterTask: "wf-other-1", reserve: null });
    expect(await settleOwn(db, "wf-other-1", 5, { adapter: "creator-os" })).toBe("not_reserved");
    await asOwner(db);
    expect((await db.query("select 1 from public.client_adapter_budget_events where kind in ('settle','release')")).rows).toHaveLength(0);
  } finally {
    await db.close();
  }
});

test("a released reservation is closed, and malformed input is refused before anything is read", async () => {
  const db = await freshDb();
  try {
    await startTask(db);
    await asAnon(db);
    expect((await db.query<{ s: string }>("select public.client_adapter_budget_release('tenant-a',$1,'veloce-proofmint',$2,$3) as s", [WORKER, KEY, `own-release-${KEY}`])).rows[0].s).toBe("released");
    expect(await settleOwn(db, ADAPTER_TASK, 5)).toBe("already_closed");
    for (const [tenant, adapter, task, reported] of [
      ["Bad Tenant", "veloce-proofmint", ADAPTER_TASK, 5], ["tenant-a", "BAD", ADAPTER_TASK, 5], ["tenant-a", "veloce-proofmint", "", 5],
      ["tenant-a", "veloce-proofmint", "x".repeat(129), 5], ["tenant-a", "veloce-proofmint", ADAPTER_TASK, -1], ["tenant-a", "veloce-proofmint", ADAPTER_TASK, 1_000_000_000_001],
    ] as [string, string, string, number][]) {
      await asService(db);
      expect((await db.query<{ s: string }>("select public.client_adapter_own_spend_settle($1,$2,$3,$4) as s", [tenant, adapter, task, reported])).rows[0].s, `${tenant} ${adapter} ${task.slice(0, 10)} ${reported}`).toBe("invalid");
    }
  } finally {
    await db.close();
  }
});

test("only the service role can settle an adapter's own spend", async () => {
  const db = await freshDb();
  try {
    await startTask(db);
    await asAnon(db);
    await expect(db.query(`select public.client_adapter_own_spend_settle('tenant-a','veloce-proofmint','${ADAPTER_TASK}',5)`)).rejects.toThrow(/permission denied/);
    await asUser(db, OWNER);
    await expect(db.query(`select public.client_adapter_own_spend_settle('tenant-a','veloce-proofmint','${ADAPTER_TASK}',5)`)).rejects.toThrow(/permission denied/);
    expect(await settleOwn(db, ADAPTER_TASK, 5)).toBe("settled");
  } finally {
    await db.close();
  }
});

test("the spend check finds the reservation from the adapter's own task id, and still matches exact ids as before", async () => {
  const db = await freshDb();
  try {
    await startTask(db);
    await asService(db);
    expect((await db.query<{ r: string }>("select public.client_adapter_budget_record_report('tenant-a','veloce-proofmint',$1,20010) as r", [ADAPTER_TASK])).rows[0].r).toBe("recorded");
    const rows = async () => {
      await asUser(db, ADMIN);
      return (await db.query<{ adapter_id: string; task_id: string; reported_micros: number; reserved_micros: number | null; settled_micros: number | null; status: string }>(
        "select * from public.client_adapter_budget_reconcile_tasks('tenant-a')",
      )).rows;
    };
    // reserved and not yet settled: open, under the adapter's own id, with the host's reservation beside it
    expect(await rows()).toEqual([{ adapter_id: "veloce-proofmint", task_id: ADAPTER_TASK, reported_micros: 20010, reserved_micros: 250000, settled_micros: null, status: "open" }]);
    // a model call under the same key does not change the comparison
    await asAnon(db);
    await db.query("select public.client_adapter_budget_reserve('tenant-a',$1,'veloce-proofmint',$2,'mcr-model-call-1',500,'groq','m',50000000)", [WORKER, `${KEY}/m1`]);
    expect((await rows())[0].reserved_micros).toBe(250000);
    expect(await settleOwn(db, ADAPTER_TASK, 20_010)).toBe("settled");
    expect(await rows()).toEqual([]); // matched rows are not listed
    await asUser(db, OWNER);
    const counts = (await db.query<{ adapter_id: string; status: string; task_count: number }>("select * from public.client_adapter_budget_reconcile_counts('tenant-a')")).rows;
    expect(counts).toEqual([{ adapter_id: "veloce-proofmint", status: "matched", task_count: 1 }]);

    // an adapter whose task id is the ledger's own key (no grant) is compared as before
    await asOwner(db);
    await db.query("insert into public.client_adapter_budget_events (tenant_slug, adapter_id, task_id, kind, amount_micros, provider, idempotency_key) values ('tenant-a','creator-os','h1-plain0000000000000000000','reserve',900,'p','key-plain-0001')");
    await asService(db);
    await db.query("select public.client_adapter_budget_record_report('tenant-a','creator-os','h1-plain0000000000000000000',900)");
    const plain = (await rows()).find((r) => r.task_id === "h1-plain0000000000000000000")!;
    expect(plain).toMatchObject({ reserved_micros: 900, status: "open" });
    // and a reported task with no reservation at all is still unreserved
    await asService(db);
    await db.query("select public.client_adapter_budget_record_report('tenant-a','creator-os','h1-none00000000000000000000',5)");
    expect((await rows()).find((r) => r.task_id === "h1-none00000000000000000000")!.status).toBe("unreserved");
  } finally {
    await db.close();
  }
});
