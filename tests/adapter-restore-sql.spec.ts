// Real PostgreSQL (PGlite) tests for restoring adapter data through restore_client_lifecycle_metadata.
// Users, tenants and rows are created inside each test; nothing real is used.
const read = (file: string) => readFileSync(`product-experience/supabase-${file}.sql`, "utf8");
const USER = {
  ownerA: "00000000-0000-4000-8000-0000000000a1",
  adminA: "00000000-0000-4000-8000-0000000000a2",
  memberA: "00000000-0000-4000-8000-0000000000a3",
};
const H = (c: string) => c.repeat(64);
const sha = (text: string) => createHash("sha256").update(text).digest("hex");
const ORDER = [
  "client_tenants", "client_memberships", "client_adapter_registry", "client_adapter_memory_items",
  "client_adapter_memory_promotions", "client_adapter_memory_provenance", "client_adapter_approvals", "client_adapter_budget_events",
];

async function freshDb() {
  const db = new PGlite({ extensions: { pgcrypto } });
  await db.exec(`
    do $$ begin
      if not exists (select 1 from pg_roles where rolname='anon') then create role anon; end if;
      if not exists (select 1 from pg_roles where rolname='authenticated') then create role authenticated; end if;
      if not exists (select 1 from pg_roles where rolname='service_role') then create role service_role bypassrls; end if;
    end $$;
    create schema extensions; create extension pgcrypto with schema extensions;
    create schema auth;
    create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    create table auth.users(id uuid primary key);
    create table public.client_tenants(slug text primary key, name text not null default '', status text not null default 'active',
      worker_token_hash text, retention_days integer not null default 28, created_at timestamptz not null default now(), updated_at timestamptz not null default now());
    create table public.client_memberships(
      tenant_slug text not null references public.client_tenants(slug) on delete cascade,
      user_id uuid not null references auth.users(id), role text not null, status text not null default 'active',
      created_at timestamptz not null default now(), primary key (tenant_slug, user_id));
    create function public.client_member(p_tenant_slug text) returns boolean language sql stable security definer set search_path = public as $$
      select exists (select 1 from public.client_memberships where tenant_slug = p_tenant_slug and user_id = auth.uid() and status = 'active') $$;
    create table public.client_runtime_audit_events(id bigint generated by default as identity primary key, tenant_slug text not null, event_type text not null, metadata jsonb not null default '{}'::jsonb, created_at timestamptz not null default now());
    grant usage on schema public, auth, extensions to anon, authenticated, service_role;
    grant execute on function public.client_member(text) to authenticated;
    insert into auth.users values ('${USER.ownerA}'), ('${USER.adminA}'), ('${USER.memberA}');
    insert into public.client_tenants(slug, retention_days, worker_token_hash) values ('tenant-a', 28, '${sha("w".repeat(30))}'), ('tenant-b', 28, null);
    insert into public.client_memberships(tenant_slug, user_id, role) values
      ('tenant-a', '${USER.ownerA}', 'owner'), ('tenant-a', '${USER.adminA}', 'admin'), ('tenant-a', '${USER.memberA}', 'member');
  `);
  for (const file of ["client-adapter-host", "client-adapter-token-uses", "client-adapter-retention-28", "client-lifecycle-restore"]) await db.exec(read(file));
  return db;
}

const asUser = async (db: PGlite, id: string) => {
  await db.exec("reset role");
  await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]);
  await db.exec("set role authenticated");
};
const asService = (db: PGlite) => db.exec("reset role; set role service_role");
const asOwner = (db: PGlite) => db.exec("reset role");

/** Source data for tenant-a: a registered, enabled adapter with a cap; a private note, a promotion, a shared note, provenance,
 *  a finished approval, and budget events. */
async function seed(db: PGlite) {
  await asOwner(db);
  await db.exec(`insert into public.client_adapter_registry (tenant_slug, adapter_id, display_name, contract_version, manifest_sha256, created_by, state, side_effect_ceiling, budget_cap_micros, budget_period)
    values ('tenant-a','forge','Forge','h1','${H("a")}','${USER.ownerA}','enabled','publish',5000000,'month')`);
  await asService(db);
  const priv = (await db.query<{ id: string }>(
    "insert into public.client_adapter_memory_items (tenant_slug, namespace, origin_adapter_id, content, content_sha256, idempotency_key) values ('tenant-a','adapter:forge','forge','a shared fact',$1,'idem-key-1') returning id", [sha("a shared fact")],
  )).rows[0].id;
  await db.query("insert into public.client_adapter_memory_provenance (tenant_slug, item_id, adapter_id, adapter_version, agent_principal, source_task_id, confidence) values ('tenant-a',$1,'forge','1','agent','task-0',0.5)", [priv]);
  const scan = JSON.stringify({ scanner: "memory-scan-h1", content_sha256: sha("a shared fact"), verdict: "clean", findings: [], scanned_chars: 13 });
  const promo = (await db.query<{ id: string }>(
    "insert into public.client_adapter_memory_promotions (tenant_slug, source_item_id, origin_adapter_id, content_sha256, requested_by, scan_result) values ('tenant-a',$1,'forge',$2,$3,$4::jsonb) returning id", [priv, sha("a shared fact"), USER.memberA, scan],
  )).rows[0].id;
  await asUser(db, USER.adminA);
  await db.query("update public.client_adapter_memory_promotions set status='approved', reviewed_by=auth.uid(), reviewed_at=now(), approved_content_sha256=$2, decision_note='fine' where id=$1", [promo, sha("a shared fact")]);
  await asService(db);
  const shared = (await db.query<{ id: string }>(
    "insert into public.client_adapter_memory_items (tenant_slug, namespace, origin_adapter_id, content, content_sha256, trust_level, promotion_id, idempotency_key) values ('tenant-a','shared','forge','a shared fact',$1,'reviewed',$2,'idem-key-2') returning id", [sha("a shared fact"), promo],
  )).rows[0].id;
  await db.query("insert into public.client_adapter_memory_provenance (tenant_slug, item_id, adapter_id, adapter_version, agent_principal, source_task_id, confidence) values ('tenant-a',$1,'forge','1','agent','task-1',0.5)", [shared]);
  const canonical = JSON.stringify({ adapterId: "forge", destination: "dest", kind: "publish", payload: { text: "post body" }, policyVersion: "p1", v: "approval-action-h1" });
  await db.query("insert into public.client_adapter_approvals (tenant_slug, adapter_id, action_kind, action_hash, action_canonical, destination, policy_version, requested_by, expires_at) values ('tenant-a','forge','publish',$1,$2,'dest','p1',$3, now() + interval '2 days')", [sha(canonical), canonical, USER.memberA]);
  await db.query("insert into public.client_adapter_budget_events (tenant_slug, adapter_id, task_id, kind, amount_micros, provider, idempotency_key) values ('tenant-a','forge','t1','reserve',250,'provider-x','idem-key-b1')");
  return { priv, promo, shared };
}

/** Rows as the backup holds them. By default they pass through the same row mapper the command line uses before restore. */
async function exportBatches(db: PGlite, tenant = "tenant-a", mapRows = true) {
  await asOwner(db);
  const columns = (await db.query<{ c: Record<string, string> }>("select public.client_lifecycle_restore_columns() as c")).rows[0].c;
  const batches: Array<{ table: string; rows: Record<string, unknown>[] }> = [];
  for (const table of ORDER) {
    const key = table === "client_tenants" ? "slug" : "tenant_slug";
    const order = table === "client_adapter_memory_items" ? "created_at, id" : "1";
    const rows = (await db.query<{ r: Record<string, unknown>[] }>(
      `select coalesce(jsonb_agg(to_jsonb(x) order by ${order === "1" ? "1" : "x.created_at, x.id"}), '[]'::jsonb) as r from (select ${columns[table]} from public.${table} where ${key} = $1) x`, [tenant],
    )).rows[0].r;
    if (rows.length) batches.push({ table, rows: mapRows ? rows.map((row) => clientLifecycleRestoreRow(table, row)) : rows });
  }
  return batches;
}
async function removeTenant(db: PGlite, tenant = "tenant-a") {
  await asOwner(db);
  await db.query("delete from public.client_tenants where slug = $1", [tenant]); // cascades; the append-only tables allow this
}
async function restore(db: PGlite, batches: unknown, tenant = "tenant-a") {
  await asService(db);
  return db.query<{ r: Record<string, any> }>("select public.restore_client_lifecycle_metadata($1,$2::jsonb) as r", [tenant, JSON.stringify(batches)]);
}
async function snapshotRows(db: PGlite, table: string) {
  await asOwner(db);
  return (await db.query(`select * from public.${table} where tenant_slug = 'tenant-a' order by id`)).rows;
}

test("a tenant's adapter data survives a backup and restore with its original dates, and adapters come back disabled", async () => {
  const db = await freshDb();
  try {
    await seed(db);
    const before: Record<string, unknown[]> = {};
    for (const table of ORDER.slice(3)) before[table] = await snapshotRows(db, table);
    const batches = await exportBatches(db, "tenant-a", false);
    expect(batches.map((b) => b.table)).toEqual(ORDER);
    const exportedState = batches.find((b) => b.table === "client_adapter_registry")!.rows[0].state;
    expect(exportedState).toBe("enabled");
    // approvals that could still be used are turned into expired evidence by the same mapper the command line uses
    const mapped = batches.map((b) => ({ table: b.table, rows: b.rows.map((row) => clientLifecycleRestoreRow(b.table, row)) }));

    await removeTenant(db);
    expect(await snapshotRows(db, "client_adapter_memory_items")).toHaveLength(0);

    const receipt = (await restore(db, mapped)).rows[0].r;
    expect(receipt.atomicMetadata).toBe(true);
    expect(receipt.tables).toMatchObject({ client_adapter_registry: 1, client_adapter_memory_items: 2, client_adapter_memory_promotions: 1, client_adapter_memory_provenance: 2, client_adapter_approvals: 1, client_adapter_budget_events: 1 });

    for (const table of ORDER.slice(3)) {
      const after = await snapshotRows(db, table);
      expect(after.length, table).toBe(before[table].length);
      for (let i = 0; i < after.length; i++) {
        const a = after[i] as Record<string, unknown>;
        const b = before[table][i] as Record<string, unknown>;
        for (const clock of ["created_at", "retention_expires_at"]) expect(String(a[clock]), `${table}.${clock}`).toBe(String(b[clock]));
        expect(a.id).toBe(b.id);
      }
    }
    await asOwner(db);
    const registry = (await db.query<{ state: string; budget_cap_micros: number; budget_period: string }>("select state, budget_cap_micros, budget_period from public.client_adapter_registry")).rows[0];
    expect(registry).toEqual({ state: "disabled", budget_cap_micros: 5000000, budget_period: "month" });
    const approval = (await db.query<{ status: string }>("select status from public.client_adapter_approvals")).rows[0];
    expect(approval.status).toBe("expired"); // it was still pending in the source, so it must not come back usable
    const kept = (await db.query<{ action_canonical: string; action_hash: string }>("select action_canonical, action_hash from public.client_adapter_approvals")).rows[0];
    expect(sha(kept.action_canonical)).toBe(kept.action_hash); // what the reviewer saw came back with it, and still matches its fingerprint
    expect(JSON.parse(kept.action_canonical).payload).toEqual({ text: "post body" });
    // members can read the restored shared note straight away, so the read barrier and memberships came back too
    await asUser(db, USER.memberA);
    expect((await db.query<{ content: string }>("select content from public.client_adapter_memory_items")).rows).toEqual([{ content: "a shared fact" }]);
  } finally {
    await db.close();
  }
});

test("an approval that could still be used is refused by the database even if the command line missed it", async () => {
  for (const status of ["pending", "approved"]) {
    const db = await freshDb();
    try {
      await seed(db);
      const batches = await exportBatches(db);
      await removeTenant(db);
      const approval = batches.find((b) => b.table === "client_adapter_approvals")!.rows[0];
      approval.status = status;
      if (status === "approved") Object.assign(approval, { decided_by: USER.adminA, decided_at: new Date().toISOString(), approved_action_hash: approval.action_hash });
      await expect(restore(db, batches), status).rejects.toThrow(/client_restore_adapter_requires_review/);
      await asOwner(db);
      expect(Number((await db.query<{ n: string }>("select count(*) as n from public.client_tenants where slug = 'tenant-a'")).rows[0].n), "nothing half restored").toBe(0);
    } finally {
      await db.close();
    }
  }
  // finished approvals are fine
  const db = await freshDb();
  try {
    await seed(db);
    const batches = await exportBatches(db);
    await removeTenant(db);
    batches.find((b) => b.table === "client_adapter_approvals")!.rows[0].status = "cancelled";
    expect((await restore(db, batches)).rows[0].r.atomicMetadata).toBe(true);
  } finally {
    await db.close();
  }
});

test("the command-line row mapper disables adapters and expires usable approvals, and leaves finished ones alone", () => {
  expect(clientLifecycleRestoreRow("client_adapter_registry", { id: "x", state: "enabled", display_name: "Forge" })).toEqual({ id: "x", state: "disabled", display_name: "Forge" });
  expect(clientLifecycleRestoreRow("client_adapter_approvals", { id: "x", status: "pending" }).status).toBe("expired");
  expect(clientLifecycleRestoreRow("client_adapter_approvals", { id: "x", status: "approved" }).status).toBe("expired");
  for (const status of ["rejected", "expired", "executed", "cancelled"]) expect(clientLifecycleRestoreRow("client_adapter_approvals", { id: "x", status }).status).toBe(status);
  expect(clientLifecycleRestoreRow("client_adapter_memory_items", { id: "x", status: "active" })).toEqual({ id: "x", status: "active" });
});

test("data that has already expired is not brought back to life", async () => {
  const db = await freshDb();
  try {
    await seed(db);
    const batches = await exportBatches(db);
    await removeTenant(db);
    const items = batches.find((b) => b.table === "client_adapter_memory_items")!;
    items.rows[0].retention_expires_at = new Date(Date.now() - 86_400_000).toISOString();
    await expect(restore(db, batches)).rejects.toThrow(/client_restore_active_window_invalid/);
    const events = batches.find((b) => b.table === "client_adapter_budget_events")!;
    items.rows[0].retention_expires_at = items.rows[1].retention_expires_at;
    events.rows[0].retention_expires_at = new Date(Date.now() + 90 * 86_400_000).toISOString(); // longer than the tenant's days
    await expect(restore(db, batches)).rejects.toThrow(/client_restore_active_window_invalid/);
  } finally {
    await db.close();
  }
});

test("a shared note without its approved promotion is refused, and nothing is left half restored", async () => {
  const db = await freshDb();
  try {
    await seed(db);
    const batches = await exportBatches(db);
    await removeTenant(db);
    const withoutPromotion = batches.filter((b) => b.table !== "client_adapter_memory_promotions");
    await expect(restore(db, withoutPromotion)).rejects.toThrow(/client_restore_adapter_graph_invalid|violates foreign key/);
    await asOwner(db);
    for (const table of ["client_tenants", "client_adapter_registry", "client_adapter_memory_items"]) {
      const where = table === "client_tenants" ? "slug = 'tenant-a'" : "tenant_slug = 'tenant-a'";
      expect(Number((await db.query<{ n: string }>(`select count(*) as n from public.${table} where ${where}`)).rows[0].n), table).toBe(0);
    }
    // a promotion that is not approved does not justify a shared note either
    const tampered = JSON.parse(JSON.stringify(batches)) as typeof batches;
    const promo = tampered.find((b) => b.table === "client_adapter_memory_promotions")!.rows[0];
    promo.status = "quarantined";
    promo.reviewed_by = null; promo.reviewed_at = null; promo.approved_content_sha256 = null;
    await expect(restore(db, tampered)).rejects.toThrow(/client_restore_adapter_graph_invalid/);
  } finally {
    await db.close();
  }
});

test("only the adapter tables in the backup can come back; the outbox and token rows cannot, and other tenants' rows are refused", async () => {
  const db = await freshDb();
  try {
    await seed(db);
    const batches = await exportBatches(db);
    await removeTenant(db);
    const tenantAndMemberships = batches.filter((b) => ["client_tenants", "client_memberships"].includes(b.table));
    for (const table of ["client_adapter_outbox", "client_adapter_token_uses"]) {
      await expect(restore(db, [...tenantAndMemberships, { table, rows: [{ tenant_slug: "tenant-a" }] }])).rejects.toThrow(/client_restore_invalid_batch/);
    }
    const foreign = JSON.parse(JSON.stringify(batches)) as typeof batches;
    foreign.find((b) => b.table === "client_adapter_registry")!.rows[0].tenant_slug = "tenant-b";
    await expect(restore(db, foreign)).rejects.toThrow(/client_restore_tenant_mismatch/);
    const unknownColumn = JSON.parse(JSON.stringify(batches)) as typeof batches;
    unknownColumn.find((b) => b.table === "client_adapter_registry")!.rows[0].worker_token = "x";
    await expect(restore(db, unknownColumn)).rejects.toThrow(/client_restore_column_not_allowed/);
  } finally {
    await db.close();
  }
});

test("the restore shortcuts are not available outside a protected restore", async () => {
  const db = await freshDb();
  try {
    const { priv, promo } = await seed(db);
    // the service role cannot insert an already-approved promotion or an already-approved approval directly
    await asService(db);
    await expect(db.query(
      "insert into public.client_adapter_memory_promotions (tenant_slug, source_item_id, origin_adapter_id, content_sha256, requested_by, status, reviewed_by, reviewed_at, approved_content_sha256) values ('tenant-a',$1,'forge',$2,$3,'approved',$4,now(),$2)",
      [priv, sha("a shared fact"), USER.memberA, USER.adminA],
    )).rejects.toThrow(/starts quarantined/);
    await expect(db.query(
      "insert into public.client_adapter_approvals (tenant_slug, adapter_id, action_kind, action_hash, destination, policy_version, requested_by, status, decided_by, decided_at, approved_action_hash, expires_at) values ('tenant-a','forge','publish',$1,'d2','p1',$2,'approved',$3,now(),$1, now() + interval '1 day')",
      [H("2"), USER.memberA, USER.adminA],
    )).rejects.toThrow(/starts pending/);
    // a forged restore context for the wrong table or tenant unlocks nothing
    await db.query("select set_config('app.client_lifecycle_restore', $1, false)", [JSON.stringify({ table: "client_adapter_memory_items", tenant: "tenant-a" })]);
    await expect(db.query(
      "insert into public.client_adapter_approvals (tenant_slug, adapter_id, action_kind, action_hash, destination, policy_version, requested_by, status, decided_by, decided_at, approved_action_hash, expires_at) values ('tenant-a','forge','publish',$1,'d3','p1',$2,'approved',$3,now(),$1, now() + interval '1 day')",
      [H("3"), USER.memberA, USER.adminA],
    )).rejects.toThrow(/starts pending/);
    await db.query("select set_config('app.client_lifecycle_restore', $1, false)", [JSON.stringify({ table: "client_adapter_approvals", tenant: "tenant-b" })]);
    await expect(db.query(
      "insert into public.client_adapter_approvals (tenant_slug, adapter_id, action_kind, action_hash, destination, policy_version, requested_by, status, decided_by, decided_at, approved_action_hash, expires_at) values ('tenant-a','forge','publish',$1,'d4','p1',$2,'approved',$3,now(),$1, now() + interval '1 day')",
      [H("4"), USER.memberA, USER.adminA],
    )).rejects.toThrow(/starts pending/);
    await db.query("select set_config('app.client_lifecycle_restore', '', false)");
    // signed-in users and the anonymous role cannot call the restore, the helper or the graph check
    for (const role of ["authenticated", "anon"]) {
      await db.exec(`reset role; set role ${role}`);
      await expect(db.query("select public.restore_client_lifecycle_metadata('tenant-a','[]'::jsonb)")).rejects.toThrow(/permission denied/);
      await expect(db.query("select public.client_adapter_restoring('client_adapter_approvals','tenant-a')")).rejects.toThrow(/permission denied/);
      await expect(db.query("select public.validate_client_adapter_restore_graph('tenant-a')")).rejects.toThrow(/permission denied/);
    }
    expect(promo).toBeTruthy();
  } finally {
    await db.close();
  }
});
