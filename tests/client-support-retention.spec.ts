import { readFileSync } from "node:fs";
import { PGlite } from "@electric-sql/pglite";
import { expect, test } from "@playwright/test";

async function database() {
  const db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated; create role service_role;
    create table client_tenants (slug text primary key, retention_days integer not null);
    create table client_runtime_audit_events (
      id bigint generated by default as identity primary key,
      tenant_slug text not null, event_type text not null, metadata jsonb not null
    );
    create table client_support_requests (
      id uuid primary key, tenant_slug text references client_tenants(slug) on delete set null,
      email text not null, subject text not null, message text not null,
      status text not null default 'open', created_at timestamptz not null default now(),
      updated_at timestamptz not null default now()
    );
    insert into client_tenants values ('tenant-a', 28), ('tenant-b', 14);
    insert into client_support_requests (id, tenant_slug, email, subject, message, created_at) values
      ('00000000-0000-4000-8000-000000000001', 'tenant-a', 'a@example.test', 'Old A', 'private old message', now() - interval '36 days'),
      ('00000000-0000-4000-8000-000000000002', 'tenant-a', 'a@example.test', 'Recent A', 'private recent message', now() - interval '2 days'),
      ('00000000-0000-4000-8000-000000000003', 'tenant-b', 'b@example.test', 'Old B', 'other tenant message', now() - interval '22 days'),
      ('00000000-0000-4000-8000-000000000004', null, 'public@example.test', 'Public', 'unlinked inquiry', now() - interval '100 days');
    alter table client_support_requests enable row level security;
    grant select, insert, update on client_support_requests to authenticated;
  `);
  await db.exec(readFileSync("product-experience/supabase-client-support-retention-28.sql", "utf8"));
  await db.exec(readFileSync("product-experience/supabase-client-support-retention-28.sql", "utf8"));
  return db;
}

const purge = "select public.purge_expired_client_support_requests($1, $2, $3) as result";

test("tenant support content purges per tenant while unlinked public inquiries stay out of scope", async () => {
  const db = await database();
  try {
    const preview = await db.query<{ result: Record<string, unknown> }>(purge, ["tenant-a", false, 1]);
    expect(preview.rows[0].result).toMatchObject({ candidates: 1, deleted: 0, remainingCandidates: 1, applied: false });
    expect((await db.query("select id from client_runtime_audit_events")).rows).toHaveLength(0);

    const applied = await db.query<{ result: Record<string, unknown> }>(purge, ["tenant-a", true, 1]);
    expect(applied.rows[0].result).toMatchObject({ candidates: 1, deleted: 1, remainingCandidates: 0, applied: true });
    expect((await db.query("select id from client_support_requests order by id")).rows.map((row) => row.id)).toEqual([
      "00000000-0000-4000-8000-000000000002",
      "00000000-0000-4000-8000-000000000003",
      "00000000-0000-4000-8000-000000000004",
    ]);
    expect((await db.query("select event_type, metadata from client_runtime_audit_events")).rows[0]).toMatchObject({
      event_type: "tenant.support_requests.retention_purged", metadata: { deleted: 1, retentionDays: 28 },
    });
  } finally { await db.close(); }
});

test("support retention clamps new timestamps, blocks timestamp or tenant reassignment, and limits purge to service role", async () => {
  const db = await database();
  try {
    await db.query(`insert into client_support_requests (id, tenant_slug, email, subject, message, created_at) values
      ('00000000-0000-4000-8000-000000000020', 'tenant-a', 'new@example.test', 'New', 'new message', now() - interval '90 days')`);
    const inserted = await db.query<{ recent: boolean }>("select created_at > now() - interval '1 minute' as recent from client_support_requests where id='00000000-0000-4000-8000-000000000020'");
    expect(inserted.rows[0].recent).toBe(true);
    await expect(db.query(`update client_support_requests set created_at = now() - interval '90 days' where id='00000000-0000-4000-8000-000000000020'`))
      .rejects.toThrow(/client_support_request_retention_immutable/);
    await expect(db.query(`update client_support_requests set tenant_slug = 'tenant-b' where id='00000000-0000-4000-8000-000000000020'`))
      .rejects.toThrow(/client_support_request_retention_immutable/);
    const privileges = await db.query<{ member: boolean; operator: boolean }>(`
      select has_function_privilege('authenticated', 'public.purge_expired_client_support_requests(text,boolean,integer)', 'EXECUTE') as member,
        has_function_privilege('service_role', 'public.purge_expired_client_support_requests(text,boolean,integer)', 'EXECUTE') as operator
    `);
    expect(privileges.rows[0]).toEqual({ member: false, operator: true });
  } finally { await db.close(); }
});

test("support cleanup rejects invalid tenants and rolls back deletion when audit recording fails", async () => {
  const db = await database();
  try {
    await expect(db.query(purge, ["missing-tenant", false, 10])).rejects.toThrow(/client_support_request_retention_tenant_not_found/);
    await expect(db.query(purge, ["tenant-a", false, 501])).rejects.toThrow(/client_support_request_retention_invalid_input/);
    await db.exec(`
      create function reject_support_retention_audit() returns trigger language plpgsql as $$
      begin raise exception 'audit_unavailable'; end; $$;
      create trigger reject_support_retention_audit before insert on client_runtime_audit_events
        for each row execute function reject_support_retention_audit();
    `);
    await expect(db.query(purge, ["tenant-a", true, 100])).rejects.toThrow(/audit_unavailable/);
    expect((await db.query("select id from client_support_requests where tenant_slug='tenant-a' and created_at <= now() - interval '28 days'")).rows)
      .toHaveLength(1);
  } finally { await db.close(); }
});
