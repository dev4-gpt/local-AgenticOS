import { readFileSync } from "node:fs";
import { PGlite } from "@electric-sql/pglite";
import { expect, test } from "@playwright/test";

async function database() {
  const db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated; create role service_role;
    create schema auth; create schema extensions;
    create function auth.uid() returns uuid language sql stable as $$
      select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
    $$;
    create table client_tenants (slug text primary key, retention_days integer not null);
    create table client_runtime_audit_events (
      id bigint generated by default as identity primary key,
      tenant_slug text not null, event_type text not null, metadata jsonb not null
    );
    create table client_runtime_requests (
      id uuid primary key, tenant_slug text not null references client_tenants(slug) on delete cascade,
      submitted_by uuid not null, request_type text not null, title text not null,
      details text not null, fields jsonb not null default '{}'::jsonb,
      status text not null default 'pending_approval', created_at timestamptz not null default now(),
      updated_at timestamptz not null default now()
    );
    create table client_runtime_delivery_actions (
      id uuid primary key, tenant_slug text not null references client_tenants(slug) on delete cascade,
      request_id uuid not null references client_runtime_requests(id) on delete cascade,
      requested_by uuid not null, action text not null, destination text,
      artifact_ids jsonb not null default '[]'::jsonb, status text not null default 'pending_approval',
      error_code text, idempotency_key text not null, created_at timestamptz not null default now(),
      updated_at timestamptz not null default now(), unique (tenant_slug, idempotency_key)
    );
    insert into client_tenants values ('tenant-a', 28), ('tenant-b', 28), ('tenant-short', 14);
    insert into client_runtime_requests (id, tenant_slug, submitted_by, request_type, title, details, created_at) values
      ('00000000-0000-4000-8000-000000000001', 'tenant-a', '00000000-0000-4000-8000-000000000101', 'deliver', 'Expired parent', 'Expired request details', now() - interval '36 days'),
      ('00000000-0000-4000-8000-000000000002', 'tenant-a', '00000000-0000-4000-8000-000000000101', 'deliver', 'Young child parent', 'Parent with recent action', now() - interval '36 days'),
      ('00000000-0000-4000-8000-000000000003', 'tenant-a', '00000000-0000-4000-8000-000000000101', 'command', 'Recent request', 'Recent request details', now() - interval '2 days'),
      ('00000000-0000-4000-8000-000000000004', 'tenant-b', '00000000-0000-4000-8000-000000000102', 'command', 'Other tenant', 'Other tenant request', now() - interval '40 days'),
      ('00000000-0000-4000-8000-000000000005', 'tenant-short', '00000000-0000-4000-8000-000000000103', 'command', 'Short policy', 'Short policy request', now() - interval '22 days');
    insert into client_runtime_delivery_actions (id, tenant_slug, request_id, requested_by, action, idempotency_key, created_at) values
      ('00000000-0000-4000-8000-000000000011', 'tenant-a', '00000000-0000-4000-8000-000000000001', '00000000-0000-4000-8000-000000000101', 'record', 'expired-action-1', now() - interval '36 days'),
      ('00000000-0000-4000-8000-000000000012', 'tenant-a', '00000000-0000-4000-8000-000000000002', '00000000-0000-4000-8000-000000000101', 'record', 'young-action', now() - interval '2 days'),
      ('00000000-0000-4000-8000-000000000013', 'tenant-b', '00000000-0000-4000-8000-000000000004', '00000000-0000-4000-8000-000000000102', 'record', 'other-action', now() - interval '40 days');
    create function client_member(text) returns boolean language sql stable as $$
      select $1 in ('tenant-a', 'tenant-b', 'tenant-short')
    $$;
    create function client_tenant_retention_days(text) returns integer language sql stable security definer as $$
      select retention_days from client_tenants where slug = $1 and client_member($1)
    $$;
    grant execute on function client_tenant_retention_days(text) to authenticated, service_role;
    grant select, insert, update on client_runtime_requests, client_runtime_delivery_actions to authenticated;
    alter table client_runtime_requests enable row level security;
    alter table client_runtime_delivery_actions enable row level security;
    create policy client_requests_member_insert on client_runtime_requests
      for insert to authenticated with check (client_member(tenant_slug) and submitted_by = auth.uid());
    create policy client_delivery_actions_member_insert on client_runtime_delivery_actions
      for insert to authenticated with check (client_member(tenant_slug) and requested_by = auth.uid());
  `);
  await db.exec(readFileSync("product-experience/supabase-client-runtime-request-retention-28.sql", "utf8"));
  await db.exec(readFileSync("product-experience/supabase-client-runtime-request-retention-28.sql", "utf8"));
  return db;
}

const purge = "select public.purge_expired_client_runtime_requests($1, $2, $3) as result";

test("runtime request and delivery content becomes unreadable at each tenant's age boundary", async () => {
  const db = await database();
  try {
    await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub', '00000000-0000-4000-8000-000000000101', false);`);
    expect((await db.query("select id from client_runtime_requests where tenant_slug='tenant-a'")).rows.map((row) => row.id))
      .toEqual(["00000000-0000-4000-8000-000000000003"]);
    expect((await db.query("select id from client_runtime_delivery_actions where tenant_slug='tenant-a'")).rows.map((row) => row.id))
      .toEqual(["00000000-0000-4000-8000-000000000012"]);
    expect((await db.query("select id from client_runtime_requests where tenant_slug='tenant-b'")).rows).toHaveLength(0);
    expect((await db.query("select id from client_runtime_requests where tenant_slug='tenant-short'")).rows).toHaveLength(0);
  } finally {
    await db.close();
  }
});

test("bounded purge removes expired actions first and defers a request with a younger child", async () => {
  const db = await database();
  try {
    const preview = await db.query<{ result: Record<string, unknown> }>(purge, ["tenant-a", false, 1]);
    expect(preview.rows[0].result).toMatchObject({
      candidates: { requests: 2, deliveryActions: 1 },
      deleted: { requests: 0, deliveryActions: 0 }, applied: false,
    });
    expect((await db.query("select id from client_runtime_audit_events")).rows).toHaveLength(0);

    const first = await db.query<{ result: Record<string, unknown> }>(purge, ["tenant-a", true, 1]);
    expect(first.rows[0].result.deleted).toEqual({ requests: 1, deliveryActions: 1 });
    expect(first.rows[0].result.remaining).toEqual({ requests: 1, deliveryActions: 0 });
    expect((await db.query("select id from client_runtime_requests where id='00000000-0000-4000-8000-000000000002'")).rows).toHaveLength(1);
    expect((await db.query("select id from client_runtime_requests where tenant_slug='tenant-b'")).rows).toHaveLength(1);

    await db.exec(`
      drop trigger guard_client_runtime_delivery_retention on client_runtime_delivery_actions;
      update client_runtime_delivery_actions set created_at = now() - interval '36 days'
      where id='00000000-0000-4000-8000-000000000012';
    `);
    const second = await db.query<{ result: Record<string, unknown> }>(purge, ["tenant-a", true, 1]);
    expect(second.rows[0].result.deleted).toEqual({ requests: 1, deliveryActions: 1 });
    expect((await db.query("select id from client_runtime_requests where tenant_slug='tenant-a'")).rows).toHaveLength(1);
    expect((await db.query("select event_type from client_runtime_audit_events")).rows).toEqual([
      { event_type: "tenant.runtime_requests.retention_purged" },
      { event_type: "tenant.runtime_requests.retention_purged" },
    ]);
  } finally {
    await db.close();
  }
});

test("member inserts cannot backdate requests or create delivery actions from expired requests", async () => {
  const db = await database();
  try {
    await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub', '00000000-0000-4000-8000-000000000101', false);`);
    await db.query(`insert into client_runtime_requests (id, tenant_slug, submitted_by, request_type, title, details, created_at) values
      ('00000000-0000-4000-8000-000000000020', 'tenant-a', '00000000-0000-4000-8000-000000000101', 'command', 'New request', 'New request details', now() - interval '90 days')`);
    const inserted = await db.query<{ recent: boolean }>("select created_at > now() - interval '1 minute' as recent from client_runtime_requests where id='00000000-0000-4000-8000-000000000020'");
    expect(inserted.rows[0].recent).toBe(true);
    await db.exec("reset role");
    await expect(db.query(`update client_runtime_requests set created_at = now() - interval '90 days' where id='00000000-0000-4000-8000-000000000020'`))
      .rejects.toThrow(/client_runtime_request_retention_immutable/);
    await db.exec("set role authenticated");
    await expect(db.query(`insert into client_runtime_delivery_actions (id, tenant_slug, request_id, requested_by, action, idempotency_key) values
      ('00000000-0000-4000-8000-000000000021', 'tenant-a', '00000000-0000-4000-8000-000000000001', '00000000-0000-4000-8000-000000000101', 'record', 'expired-request')`))
      .rejects.toThrow(/client_runtime_delivery_request_expired_or_foreign/);
  } finally {
    await db.close();
  }
});

test("runtime request purge is service-role-only and rolls back if audit evidence cannot be recorded", async () => {
  const db = await database();
  try {
    const privileges = await db.query<{ member: boolean; operator: boolean }>(`
      select has_function_privilege('authenticated', 'public.purge_expired_client_runtime_requests(text,boolean,integer)', 'EXECUTE') as member,
        has_function_privilege('service_role', 'public.purge_expired_client_runtime_requests(text,boolean,integer)', 'EXECUTE') as operator
    `);
    expect(privileges.rows[0]).toEqual({ member: false, operator: true });
    await expect(db.query(purge, ["tenant-a", false, 1001])).rejects.toThrow(/client_runtime_request_retention_invalid_input/);
    await expect(db.query(purge, ["missing-tenant", false, 10])).rejects.toThrow(/client_runtime_request_retention_tenant_not_found/);
    await db.exec(`
      create function reject_runtime_request_retention_audit() returns trigger language plpgsql as $$
      begin raise exception 'audit_unavailable'; end; $$;
      create trigger reject_runtime_request_retention_audit before insert on client_runtime_audit_events
        for each row execute function reject_runtime_request_retention_audit();
    `);
    await expect(db.query(purge, ["tenant-a", true, 100])).rejects.toThrow(/audit_unavailable/);
    expect((await db.query("select id from client_runtime_requests where tenant_slug='tenant-a' and created_at <= now() - interval '28 days'")).rows).toHaveLength(2);
    expect((await db.query("select id from client_runtime_delivery_actions where tenant_slug='tenant-a' and created_at <= now() - interval '28 days'")).rows).toHaveLength(1);
  } finally {
    await db.close();
  }
});
