import { readFileSync } from "node:fs";
import { PGlite } from "@electric-sql/pglite";
import { expect, test } from "@playwright/test";

async function database() {
  const db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated; create role service_role;
    create table client_tenants (slug text primary key, retention_days integer not null);
    create table client_runtime_audit_events (
      id bigint generated by default as identity primary key,
      tenant_slug text not null, event_type text not null, metadata jsonb not null
    );
    create table client_runtime_artifacts (
      id uuid primary key, tenant_slug text not null references client_tenants(slug) on delete cascade,
      created_at timestamptz not null default now(), retention_expires_at timestamptz
    );
    create table client_visual_qa_reports (
      id uuid primary key, tenant_slug text not null references client_tenants(slug) on delete cascade,
      artifact_id uuid not null references client_runtime_artifacts(id) on delete cascade,
      job_id uuid, status text not null, created_at timestamptz not null default now()
    );
    create table client_visual_qa_findings (
      id bigint generated by default as identity primary key,
      tenant_slug text not null references client_tenants(slug) on delete cascade,
      report_id uuid not null references client_visual_qa_reports(id) on delete cascade,
      message text not null
    );
    insert into client_tenants values ('tenant-a', 28), ('tenant-b', 14), ('tenant-invalid', 0);
    insert into client_runtime_artifacts (id, tenant_slug, created_at, retention_expires_at) values
      ('00000000-0000-4000-8000-000000000001', 'tenant-a', now() - interval '2 days', now() + interval '26 days'),
      ('00000000-0000-4000-8000-000000000002', 'tenant-a', now() - interval '40 days', now() - interval '12 days'),
      ('00000000-0000-4000-8000-000000000003', 'tenant-b', now() - interval '2 days', now() + interval '12 days');
    insert into client_visual_qa_reports (id, tenant_slug, artifact_id, status, created_at) values
      ('00000000-0000-4000-8000-000000000010', 'tenant-a', '00000000-0000-4000-8000-000000000001', 'failed', now() - interval '36 days'),
      ('00000000-0000-4000-8000-000000000020', 'tenant-a', '00000000-0000-4000-8000-000000000001', 'failed', now() - interval '40 days'),
      ('00000000-0000-4000-8000-000000000030', 'tenant-a', '00000000-0000-4000-8000-000000000001', 'passed', now() - interval '2 days'),
      ('00000000-0000-4000-8000-000000000040', 'tenant-b', '00000000-0000-4000-8000-000000000003', 'review', now() - interval '16 days');
    insert into client_visual_qa_findings (id, tenant_slug, report_id, message) values
      (1, 'tenant-a', '00000000-0000-4000-8000-000000000010', 'expired one'),
      (2, 'tenant-a', '00000000-0000-4000-8000-000000000010', 'expired two'),
      (3, 'tenant-a', '00000000-0000-4000-8000-000000000030', 'active finding'),
      (4, 'tenant-b', '00000000-0000-4000-8000-000000000040', 'recovery finding');
    create function client_member(text) returns boolean language sql stable as $$
      select $1 in ('tenant-a', 'tenant-b', 'tenant-invalid')
    $$;
    create function client_tenant_retention_days(text) returns integer
      language sql stable security definer as $$
        select retention_days from client_tenants where slug = $1 and client_member($1)
      $$;
    grant execute on function client_tenant_retention_days(text) to authenticated, service_role;
    alter table client_visual_qa_reports enable row level security;
    alter table client_visual_qa_findings enable row level security;
    create policy client_visual_qa_reports_member_select on client_visual_qa_reports
      for select to authenticated using (client_member(tenant_slug));
    create policy client_visual_qa_findings_member_select on client_visual_qa_findings
      for select to authenticated using (client_member(tenant_slug));
    grant select on client_visual_qa_reports, client_visual_qa_findings to authenticated;
  `);
  await db.exec(readFileSync("product-experience/supabase-client-visual-qa-retention-28.sql", "utf8"));
  await db.exec(readFileSync("product-experience/supabase-client-visual-qa-retention-28.sql", "utf8"));
  return db;
}

const purge = "select public.purge_expired_client_visual_qa($1, $2, $3) as result";

test("visual-QA reports and findings become unreadable by tenant and report age", async () => {
  const db = await database();
  try {
    await db.exec("set role authenticated");
    expect((await db.query("select id from client_visual_qa_reports where tenant_slug='tenant-a'")).rows)
      .toEqual([{ id: "00000000-0000-4000-8000-000000000030" }]);
    expect((await db.query("select id from client_visual_qa_findings where tenant_slug='tenant-a'")).rows)
      .toEqual([{ id: 3 }]);
    expect((await db.query("select id from client_visual_qa_reports where tenant_slug='tenant-b'")).rows).toHaveLength(0);
    expect((await db.query("select id from client_visual_qa_findings where tenant_slug='tenant-b'")).rows).toHaveLength(0);
  } finally { await db.close(); }
});

test("reports cannot be backdated, refreshed after expiry, or created from expired artifacts", async () => {
  const db = await database();
  try {
    await db.query(`insert into client_visual_qa_reports (id, tenant_slug, artifact_id, status, created_at) values
      ('00000000-0000-4000-8000-000000000050', 'tenant-a', '00000000-0000-4000-8000-000000000001', 'passed', now() - interval '90 days')`);
    const created = await db.query<{ recent: boolean }>("select created_at > now() - interval '1 minute' as recent from client_visual_qa_reports where id='00000000-0000-4000-8000-000000000050'");
    expect(created.rows[0].recent).toBe(true);
    await expect(db.query("update client_visual_qa_reports set status='passed' where id='00000000-0000-4000-8000-000000000010'"))
      .rejects.toThrow(/client_visual_qa_report_expired/);
    await expect(db.query(`insert into client_visual_qa_reports (id, tenant_slug, artifact_id, status) values
      ('00000000-0000-4000-8000-000000000051', 'tenant-a', '00000000-0000-4000-8000-000000000002', 'passed')`))
      .rejects.toThrow(/client_visual_qa_artifact_expired_or_foreign/);
  } finally { await db.close(); }
});

test("visual-QA purge deletes findings first in bounded batches and preserves active or recovery rows", async () => {
  const db = await database();
  try {
    const preview = await db.query<{ result: Record<string, any> }>(purge, ["tenant-a", false, 1]);
    expect(preview.rows[0].result).toMatchObject({
      candidates: { reports: 2, findings: 2 }, deleted: { findings: 0, reports: 0 }, applied: false,
    });
    const first = await db.query<{ result: Record<string, any> }>(purge, ["tenant-a", true, 1]);
    expect(first.rows[0].result.deleted).toEqual({ findings: 1, reports: 1 });
    expect((await db.query("select id from client_visual_qa_reports where id='00000000-0000-4000-8000-000000000010'")).rows).toHaveLength(1);
    const second = await db.query<{ result: Record<string, any> }>(purge, ["tenant-a", true, 1]);
    expect(second.rows[0].result.deleted).toEqual({ findings: 1, reports: 1 });
    expect((await db.query("select id from client_visual_qa_reports where id='00000000-0000-4000-8000-000000000030'")).rows).toHaveLength(1);
    expect((await db.query("select id from client_visual_qa_reports where id='00000000-0000-4000-8000-000000000040'")).rows).toHaveLength(1);
    expect((await db.query("select event_type from client_runtime_audit_events")).rows).toHaveLength(2);
  } finally { await db.close(); }
});

test("visual-QA purge is service-role-only and audit failure rolls back content deletion", async () => {
  const db = await database();
  try {
    const privileges = await db.query<{ member: boolean; operator: boolean }>(`
      select has_function_privilege('authenticated', 'public.purge_expired_client_visual_qa(text,boolean,integer)', 'EXECUTE') as member,
        has_function_privilege('service_role', 'public.purge_expired_client_visual_qa(text,boolean,integer)', 'EXECUTE') as operator
    `);
    expect(privileges.rows[0]).toEqual({ member: false, operator: true });
    await expect(db.query(purge, ["tenant-a", false, 501])).rejects.toThrow(/client_visual_qa_retention_invalid_input/);
    await expect(db.query(purge, ["tenant-invalid", false, 10])).rejects.toThrow(/client_visual_qa_retention_tenant_not_configured/);
    await db.exec(`
      create function reject_visual_qa_retention_audit() returns trigger language plpgsql as $$
      begin raise exception 'audit_unavailable'; end; $$;
      create trigger reject_visual_qa_retention_audit before insert on client_runtime_audit_events
        for each row execute function reject_visual_qa_retention_audit();
    `);
    await expect(db.query(purge, ["tenant-a", true, 100])).rejects.toThrow(/audit_unavailable/);
    expect((await db.query("select id from client_visual_qa_reports where id='00000000-0000-4000-8000-000000000010'")).rows).toHaveLength(1);
    expect((await db.query("select id from client_visual_qa_findings where id=1")).rows).toHaveLength(1);
  } finally { await db.close(); }
});
