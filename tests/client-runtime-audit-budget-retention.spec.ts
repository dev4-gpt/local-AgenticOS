import { readFileSync } from "node:fs";
import { expect, test } from "@playwright/test";
import { PGlite } from "@electric-sql/pglite";

async function database() {
  const db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated; create role service_role;
    create schema auth;
    create function auth.uid() returns uuid language sql stable as $$ select '00000000-0000-4000-8000-000000000010'::uuid $$;
    create table client_tenants (slug text primary key, retention_days integer not null);
    insert into client_tenants values ('tenant-a',28),('tenant-b',28),('tenant-short',14);
    create function client_member(text) returns boolean language sql stable security definer as $$
      select exists(select 1 from client_tenants where slug=$1)
    $$;
    create function client_tenant_retention_days(text) returns integer language sql stable security definer as $$
      select retention_days from client_tenants where slug=$1
    $$;
    grant execute on function client_member(text), client_tenant_retention_days(text) to authenticated,service_role;
    create table client_runtime_audit_events (
      id bigint generated by default as identity primary key, tenant_slug text not null,
      actor_id uuid, event_type text not null, request_id text, metadata jsonb not null default '{}',
      created_at timestamptz not null default now()
    );
    create table client_runtime_budget_ledger (
      id bigint generated by default as identity primary key, tenant_slug text not null,
      job_id uuid, provider text not null, model text, amount_micros bigint not null,
      usage_metadata jsonb not null default '{}', created_at timestamptz not null default now()
    );
    insert into client_runtime_audit_events(tenant_slug,event_type,created_at) values
      ('tenant-a','tenant.audit.old',now()-interval '36 days'),
      ('tenant-a','tenant.audit.recovery',now()-interval '34 days'),
      ('tenant-a','tenant.audit.active',now()-interval '20 days'),
      ('tenant-b','tenant.audit.other-tenant',now()-interval '50 days'),
      ('tenant-short','tenant.audit.short-recovery',now()-interval '20 days');
    insert into client_runtime_budget_ledger(tenant_slug,provider,amount_micros,created_at) values
      ('tenant-a','test',100,now()-interval '36 days'),
      ('tenant-a','test',200,now()-interval '34 days'),
      ('tenant-a','test',300,now()-interval '27 days'),
      ('tenant-b','test',400,now()-interval '50 days');
    alter table client_runtime_audit_events enable row level security;
    alter table client_runtime_budget_ledger enable row level security;
    create policy client_audit_member_select on client_runtime_audit_events for select to authenticated using(client_member(tenant_slug));
    create policy client_budget_member_select on client_runtime_budget_ledger for select to authenticated using(client_member(tenant_slug));
    grant select,insert,update,delete on client_runtime_audit_events,client_runtime_budget_ledger to authenticated,service_role;
    grant usage,select on all sequences in schema public to authenticated,service_role;
  `);
  const migration = readFileSync("product-experience/supabase-client-runtime-audit-budget-retention.sql", "utf8");
  await db.exec(migration);
  await db.exec(migration);
  return db;
}

const purge = "select public.purge_expired_client_runtime_audit_and_budget($1,$2,$3) as result";

test("audit and budget details stop being tenant-readable at active expiry", async () => {
  const db = await database();
  try {
    await db.exec("set role authenticated");
    const audit = await db.query<{ event_type: string }>("select event_type from client_runtime_audit_events where tenant_slug='tenant-a' order by event_type");
    expect(audit.rows.map((row) => row.event_type)).toEqual(["tenant.audit.active"]);
    const budget = await db.query<{ amount_micros: number }>("select amount_micros from client_runtime_budget_ledger where tenant_slug='tenant-a' order by amount_micros");
    expect(budget.rows.map((row) => row.amount_micros)).toEqual([300]);
    const shortTenantAudit = await db.query<{ event_type: string }>("select event_type from client_runtime_audit_events where tenant_slug='tenant-short'");
    expect(shortTenantAudit.rows).toHaveLength(0);
    await db.exec("reset role");
    expect((await db.query("select id from client_runtime_budget_ledger where tenant_slug='tenant-a'")).rows).toHaveLength(3);
  } finally {
    await db.close();
  }
});

test("purge is bounded, tenant-scoped, dry-run by default, and keeps recent-month budget rows", async () => {
  const db = await database();
  try {
    const preview = await db.query<{ result: Record<string, unknown> }>(purge, ["tenant-a", false, 1]);
    expect(preview.rows[0].result).toMatchObject({ auditCandidates: 1, auditDeleted: 0, budgetCandidates: 1, budgetDeleted: 0, applied: false });
    const first = await db.query<{ result: Record<string, unknown> }>(purge, ["tenant-a", true, 1]);
    expect(first.rows[0].result).toMatchObject({ auditCandidates: 1, auditDeleted: 1, budgetCandidates: 1, budgetDeleted: 1, applied: true });
    expect((await db.query("select id from client_runtime_audit_events where tenant_slug='tenant-b'")).rows).toHaveLength(1);
    expect((await db.query("select amount_micros from client_runtime_budget_ledger where tenant_slug='tenant-a' order by amount_micros")).rows.map((row) => row.amount_micros)).toEqual([200,300]);
    const receipt = await db.query<{ event_type: string; metadata: { auditDeleted: number; budgetDeleted: number } }>(
      "select event_type,metadata from client_runtime_audit_events where event_type='tenant.runtime_audit_budget.retention_purged'");
    expect(receipt.rows).toHaveLength(1);
    expect(receipt.rows[0]).toMatchObject({ event_type: "tenant.runtime_audit_budget.retention_purged", metadata: { auditDeleted: 1, budgetDeleted: 1 } });
    await expect(db.query(purge, ["tenant-a", true, 1001])).rejects.toThrow(/client_runtime_audit_budget_retention_invalid_input/);
    await expect(db.query(purge, ["tenant-missing", false, 100])).rejects.toThrow(/client_runtime_audit_budget_retention_tenant_not_found/);
  } finally {
    await db.close();
  }
});

test("service-role purge is the only purge caller and insert timestamps cannot be backdated", async () => {
  const db = await database();
  try {
    const privileges = await db.query<{ anon: boolean; member: boolean; service: boolean }>(`
      select has_function_privilege('anon','public.purge_expired_client_runtime_audit_and_budget(text,boolean,integer)','EXECUTE') as anon,
        has_function_privilege('authenticated','public.purge_expired_client_runtime_audit_and_budget(text,boolean,integer)','EXECUTE') as member,
        has_function_privilege('service_role','public.purge_expired_client_runtime_audit_and_budget(text,boolean,integer)','EXECUTE') as service`);
    expect(privileges.rows[0]).toEqual({ anon: false, member: false, service: true });
    const inserted = await db.query<{ fresh: boolean }>(`insert into client_runtime_audit_events(tenant_slug,event_type,created_at)
      values('tenant-a','tenant.audit.new',now()-interval '100 days') returning created_at>now()-interval '1 minute' as fresh`);
    expect(inserted.rows[0].fresh).toBe(true);
    await expect(db.query("update client_runtime_audit_events set created_at=created_at-interval '1 day' where event_type='tenant.audit.new'"))
      .rejects.toThrow(/client_runtime_audit_retention_immutable/);
    await expect(db.query("update client_runtime_budget_ledger set created_at=created_at-interval '1 day' where id=2"))
      .rejects.toThrow(/client_runtime_budget_retention_immutable/);
  } finally {
    await db.close();
  }
});
