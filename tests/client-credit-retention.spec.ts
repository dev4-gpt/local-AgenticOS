const purge = "select public.purge_expired_client_credit_records($1,$2,$3) as result";

test("credit retention drains bounded child batches before deleting their reservation", async () => {
  const db = await database({ extraExpiredReservationEvents: 2 });
  try {
    for (let remaining = 2; remaining >= 0; remaining--) {
      const result = await db.query<{ result: { deleted: Record<string, number> } }>(purge, ["tenant-a", true, 1]);
      expect(result.rows[0].result.deleted.reservationEvents).toBe(1);
      expect(result.rows[0].result.deleted.reservations).toBe(remaining === 0 ? 1 : 0);
      expect((await db.query("select id from client_credit_reservation_events where reservation_id=$1", [oldReservationId])).rows)
        .toHaveLength(remaining);
      expect((await db.query("select id from client_credit_reservations where id=$1", [oldReservationId])).rows)
        .toHaveLength(remaining === 0 ? 0 : 1);
    }
    expect((await db.query("select id from client_credit_reservation_events where tenant_slug='tenant-b'")).rows).toHaveLength(1);
  } finally { await db.close(); }
});

test("credit retention cannot cascade through a child outside the requested tenant", async () => {
  const db = await database({ foreignTenantEvent: true });
  try {
    const result = await db.query<{ result: { deleted: Record<string, number> } }>(purge, ["tenant-a", true, 500]);
    expect(result.rows[0].result.deleted.reservations).toBe(0);
    expect((await db.query("select id from client_credit_reservation_events where reservation_id=$1 and tenant_slug='tenant-b'", [oldReservationId])).rows)
      .toHaveLength(1);
    expect((await db.query("select id from client_credit_reservations where id=$1", [oldReservationId])).rows).toHaveLength(1);
    await db.query(purge, ["tenant-b", true, 500]);
    await db.query(purge, ["tenant-a", true, 500]);
    expect((await db.query("select id from client_credit_reservations where id=$1", [oldReservationId])).rows).toHaveLength(0);
  } finally { await db.close(); }
});

test("managed-credit detail stays through day 35, then purges child-first without crossing tenants", async () => {
  const db = await database();
  try {
    const preview = await db.query<{ result: Record<string, unknown> }>(purge, ["tenant-a", false, 500]);
    expect(preview.rows[0].result).toMatchObject({
      retentionDays: 28, recoveryDays: 7, purgeAfterDays: 35, applied: false,
      candidates: { transactions: 1, reservationEvents: 1, executionClaims: 1, reservations: 1, purchasePlanAllocations: 1, purchasePlans: 1, zeroBalanceBudgets: 1 },
    });
    const applied = await db.query<{ result: Record<string, unknown> }>(purge, ["tenant-a", true, 500]);
    expect(applied.rows[0].result).toMatchObject({
      applied: true,
      deleted: { transactions: 1, reservationEvents: 1, executionClaims: 1, reservations: 1, purchasePlanAllocations: 1, purchasePlans: 1, zeroBalanceBudgetsScrubbed: 1 },
      remainingCandidates: { transactions: 0, reservationEvents: 0, executionClaims: 0, reservations: 0, purchasePlanAllocations: 0, purchasePlans: 0, zeroBalanceBudgets: 0 },
    });
    expect((await db.query("select idempotency_key from client_credit_transactions where tenant_slug='tenant-a'")).rows.map((row) => row.idempotency_key)).toEqual(["active-key"]);
    expect((await db.query("select id from client_credit_purchase_plans where tenant_slug='tenant-a'")).rows).toHaveLength(1);
    expect((await db.query("select id from client_credit_purchase_plans where tenant_slug='tenant-b'")).rows).toHaveLength(1);
    expect((await db.query("select id from client_credit_reservations where tenant_slug='tenant-a'")).rows).toHaveLength(1);
    expect((await db.query("select id from client_credit_reservations where tenant_slug='tenant-b'")).rows).toHaveLength(1);
    const shorterTenantPreview = await db.query<{ result: Record<string, unknown> }>(purge, ["tenant-b", false, 500]);
    expect(shorterTenantPreview.rows[0].result).toMatchObject({ retentionDays: 28, purgeAfterDays: 35, candidates: { transactions: 1 } });
    expect((await db.query("select id from client_credit_transactions where tenant_slug='tenant-b' and idempotency_key='tenant-b-recent-key'")).rows).toHaveLength(1);
  } finally { await db.close(); }
});

test("wallet and provider balances survive while nonzero; expired replay keys cannot be reused", async () => {
  const db = await database();
  try {
    await db.query(purge, ["tenant-a", true, 500]);
    const account = await db.query("select balance_micros,reserved_micros from client_credit_accounts where tenant_slug='tenant-a'");
    expect(account.rows[0]).toEqual({ balance_micros: 1000000, reserved_micros: 200000 });
    const budget = await db.query("select purchased_micros,reserved_micros,spent_micros from client_credit_budgets where tenant_slug='tenant-a' and catalog_id='live'");
    expect(budget.rows[0]).toEqual({ purchased_micros: 2000000, reserved_micros: 200000, spent_micros: 1200000 });
    await expect(db.exec(`insert into client_credit_transactions(tenant_slug,idempotency_key,kind,amount_micros,balance_after_micros)
      values ('tenant-a','old-key','settlement',100,100)`)).rejects.toThrow(/client_credit_replay_key_retired/);
    await expect(db.exec(`insert into client_credit_reservations(id,tenant_slug,idempotency_key,status,expires_at)
      values ('00000000-0000-4000-8000-000000000204','tenant-a','old-reservation-key','reserved',now()+interval '1 hour')`))
      .rejects.toThrow(/client_credit_replay_key_retired/);
    const tombstone = await db.query<{ count: number; hasTenant: boolean }>(`
      select count(*)::int as count,
        exists(select 1 from information_schema.columns where table_name='credit_replay_key_tombstones' and column_name='tenant_slug') as "hasTenant"
      from credit_replay_key_tombstones`);
    expect(tombstone.rows[0]).toEqual({ count: 2, hasTenant: false });
  } finally { await db.close(); }
});

test("expired snapshots reveal remaining provider balance, purge is bounded and service-only", async () => {
  const db = await database();
  try {
    await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub','${ownerId}',false)`);
    const snapshot = await db.query<{ purchased_micros: number; reserved_micros: number; spent_micros: number; available_micros: number }>(
      "select purchased_micros,reserved_micros,spent_micros,available_micros from client_credit_budget_snapshot('tenant-a') where catalog_id='live'");
    expect(snapshot.rows[0]).toEqual({ purchased_micros: 800000, reserved_micros: 200000, spent_micros: 0, available_micros: 600000 });
    await db.exec("reset role");
    const privileges = await db.query<{ authenticated: boolean; service: boolean }>(`
      select has_function_privilege('authenticated','public.purge_expired_client_credit_records(text,boolean,integer)','execute') as authenticated,
        has_function_privilege('service_role','public.purge_expired_client_credit_records(text,boolean,integer)','execute') as service`);
    expect(privileges.rows[0]).toEqual({ authenticated: false, service: true });
    await expect(db.query(purge, ["tenant-a", false, 1001])).rejects.toThrow(/client_credit_retention_invalid_input/);
    await db.exec(`create function reject_credit_retention_audit() returns trigger language plpgsql as $$ begin raise exception 'audit_unavailable'; end; $$;
      create trigger reject_credit_retention_audit before insert on client_runtime_audit_events for each row execute function reject_credit_retention_audit()`);
    await expect(db.query(purge, ["tenant-a", true, 500])).rejects.toThrow(/audit_unavailable/);
    expect((await db.query("select idempotency_key from client_credit_transactions where tenant_slug='tenant-a' and idempotency_key='old-key'")).rows).toHaveLength(1);
  } finally { await db.close(); }
});

test("financial event dispositions allow managed-credit review without retaining tenant linkage", async () => {
  const db = await database();
  try {
    await db.exec(`insert into stripe_financial_event_dispositions(event_id,event_type,payload_hash,financial_scope,disposition,recorded_by,reason)
      values ('evt-late-refund','charge.refunded',repeat('a',64),'managed_credit','review_required','stripe-webhook','Linkage expired; operator review required')`);
    expect((await db.query("select financial_scope,disposition from stripe_financial_event_dispositions where event_id='evt-late-refund'")).rows)
      .toEqual([{ financial_scope: "managed_credit", disposition: "review_required" }]);
    await expect(db.exec(`insert into stripe_financial_event_dispositions(event_id,event_type,payload_hash,financial_scope,disposition,recorded_by,reason)
      values ('evt-wrong-scope','charge.refunded',repeat('b',64),'unknown','review_required','stripe-webhook','invalid')`))
      .rejects.toThrow(/stripe_financial_event_dispositions_financial_scope_check/);
  } finally { await db.close(); }
});

test("credit ledger timestamps are server assigned and immutable", async () => {
  const db = await database();
  try {
    const inserted = await db.query<{ recent: boolean }>(`insert into client_credit_transactions(tenant_slug,idempotency_key,kind,amount_micros,balance_after_micros,created_at)
      values ('tenant-a','new-key','settlement',100,100,now()-interval '90 days') returning created_at>now()-interval '1 minute' as recent`);
    expect(inserted.rows[0].recent).toBe(true);
    await expect(db.exec("update client_credit_transactions set created_at=created_at-interval '1 day' where idempotency_key='new-key'"))
      .rejects.toThrow(/client_credit_record_timestamp_immutable/);
  } finally { await db.close(); }
});
