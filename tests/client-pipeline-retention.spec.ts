import { readFileSync } from "node:fs";
import { PGlite } from "@electric-sql/pglite";
import { expect, test } from "@playwright/test";

const workerToken = "worker-token-for-pipeline-retention-test";

async function database() {
  const db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated; create role service_role;
    create schema auth; create schema extensions;
    create function auth.uid() returns uuid language sql stable as $$ select '00000000-0000-4000-8000-000000000001'::uuid $$;
    create function extensions.digest(text, text) returns bytea language sql immutable as $$ select decode(md5($1), 'hex') $$;
    create table client_tenants (
      slug text primary key, retention_days integer not null, status text not null default 'active', worker_token_hash text
    );
    create table client_runtime_audit_events (
      id bigint generated by default as identity primary key,
      tenant_slug text not null, event_type text not null, metadata jsonb not null
    );
    create table client_runtime_artifacts (id uuid primary key);
    create table client_runtime_jobs (id uuid primary key);
    create table client_pipeline_items (
      id uuid primary key,
      tenant_slug text not null references client_tenants(slug) on delete cascade,
      created_by uuid not null,
      slug text not null,
      title text not null,
      stage text not null default 'inbox',
      route text,
      confidence numeric,
      tags text[] not null default '{}'::text[],
      idea text not null,
      classification text,
      plan text,
      tasks text,
      pinned boolean not null default false,
      build_artifact_id uuid references client_runtime_artifacts(id) on delete set null,
      build_preview_html text,
      execution_state text,
      execution_job_id uuid references client_runtime_jobs(id) on delete set null,
      execution_error text,
      decided_by uuid,
      decided_at timestamptz,
      created_at timestamptz not null default now(),
      updated_at timestamptz not null default now(),
      unique (tenant_slug, slug)
    );
    insert into client_tenants values
      ('tenant-a', 28, 'active', encode(extensions.digest('${workerToken}', 'sha256'), 'hex')),
      ('tenant-b', 14, 'active', encode(extensions.digest('${workerToken}', 'sha256'), 'hex'));
    insert into client_runtime_artifacts values ('00000000-0000-4000-8000-000000000101');
    insert into client_runtime_jobs values ('00000000-0000-4000-8000-000000000201');
    insert into client_pipeline_items (id,tenant_slug,created_by,slug,title,idea,build_artifact_id,execution_job_id,created_at,updated_at) values
      ('00000000-0000-4000-8000-000000000001','tenant-a','00000000-0000-4000-8000-000000000001','old-due','Old due','private expired idea','00000000-0000-4000-8000-000000000101','00000000-0000-4000-8000-000000000201',now()-interval '40 days',now()-interval '40 days'),
      ('00000000-0000-4000-8000-000000000002','tenant-a','00000000-0000-4000-8000-000000000001','recovery','Recovery','still recoverable',null,null,now()-interval '32 days',now()-interval '32 days'),
      ('00000000-0000-4000-8000-000000000003','tenant-b','00000000-0000-4000-8000-000000000001','expired-b','Expired B','other tenant',null,null,now()-interval '20 days',now()-interval '20 days'),
      ('00000000-0000-4000-8000-000000000004','tenant-b','00000000-0000-4000-8000-000000000001','active-b','Active B','other active',null,null,now()-interval '13 days',now()-interval '13 days'),
      ('00000000-0000-4000-8000-000000000006','tenant-a','00000000-0000-4000-8000-000000000001','active-a','Active A','recent',null,null,now()-interval '2 days',now()-interval '2 days');
    create function client_member(text) returns boolean language sql stable security definer as $$
      select exists(select 1 from client_tenants where slug=$1 and status='active')
    $$;
    grant execute on function client_member(text) to authenticated;
    alter table client_pipeline_items enable row level security;
    create policy client_pipeline_items_member_select on client_pipeline_items
      for select to authenticated using (client_member(tenant_slug));
    create policy client_pipeline_items_member_insert on client_pipeline_items
      for insert to authenticated with check (client_member(tenant_slug));
    create policy client_pipeline_items_member_update on client_pipeline_items
      for update to authenticated using (client_member(tenant_slug)) with check (client_member(tenant_slug));
    create policy client_pipeline_items_member_delete on client_pipeline_items
      for delete to authenticated using (client_member(tenant_slug));
    grant select, insert, update, delete on client_pipeline_items to authenticated;
  `);
  const migration = readFileSync("product-experience/supabase-client-pipeline-retention-28.sql", "utf8");
  await db.exec(migration);
  await db.exec(migration);
  return db;
}

const purge = "select public.purge_expired_client_pipeline_items($1, $2, $3) as result";

test("Pipeline reads and updates stop at each tenant's fixed item expiry", async () => {
  const db = await database();
  try {
    await db.exec("set role authenticated");
    expect((await db.query("select id from client_pipeline_items where tenant_slug='tenant-a'")).rows.map((row) => row.id))
      .toEqual(["00000000-0000-4000-8000-000000000006"]);
    expect((await db.query("select id from client_pipeline_items where tenant_slug='tenant-b'")).rows.map((row) => row.id))
      .toEqual(["00000000-0000-4000-8000-000000000004"]);
    const blocked = await db.query(`update client_pipeline_items set title='resurrected' where id='00000000-0000-4000-8000-000000000001' returning id`);
    expect(blocked.rows).toHaveLength(0);
    const blockedDelete = await db.query(`delete from client_pipeline_items where id='00000000-0000-4000-8000-000000000001' returning id`);
    expect(blockedDelete.rows).toHaveLength(0);
  } finally { await db.close(); }
});

test("new Pipeline items cannot be backdated or extend an existing expiry", async () => {
  const db = await database();
  try {
    await db.exec("set role authenticated");
    await db.query(`insert into client_pipeline_items (id,tenant_slug,created_by,slug,title,idea,created_at) values
      ('00000000-0000-4000-8000-000000000005','tenant-a','00000000-0000-4000-8000-000000000001','new','New','new idea',now()-interval '90 days')`);
    const inserted = await db.query<{ created: boolean; within_limit: boolean }>(`
      select created_at > now()-interval '1 minute' as created,
        retention_expires_at <= created_at+interval '28 days' as within_limit
      from client_pipeline_items where id='00000000-0000-4000-8000-000000000005'
    `);
    expect(inserted.rows[0]).toEqual({ created: true, within_limit: true });
    await expect(db.query(`update client_pipeline_items set retention_expires_at=now()+interval '200 days'
      where id='00000000-0000-4000-8000-000000000005'`)).rejects.toThrow(/client_pipeline_retention_immutable/);
  } finally { await db.close(); }
});

test("worker writes ignore expired items and purge waits through recovery then deletes in bounded batches", async () => {
  const db = await database();
  try {
    const worker = await db.query<{ result: boolean }>(
      "select public.update_client_pipeline_item_worker($1,$2,$3,$4::jsonb) as result",
      ["tenant-a", workerToken, "00000000-0000-4000-8000-000000000201", JSON.stringify({ title: "worker resurrection" })],
    );
    expect(worker.rows[0].result).toBe(false);
    await db.exec("delete from client_runtime_artifacts where id='00000000-0000-4000-8000-000000000101'");
    await db.exec("delete from client_runtime_jobs where id='00000000-0000-4000-8000-000000000201'");
    expect((await db.query("select build_artifact_id,execution_job_id from client_pipeline_items where id='00000000-0000-4000-8000-000000000001'")).rows[0])
      .toEqual({ build_artifact_id: null, execution_job_id: null });

    const preview = await db.query<{ result: Record<string, unknown> }>(purge, ["tenant-a", false, 1]);
    expect(preview.rows[0].result).toMatchObject({ expiredCandidates: 2, purgeDueCandidates: 1, deleted: 0, applied: false });
    const applied = await db.query<{ result: Record<string, unknown> }>(purge, ["tenant-a", true, 1]);
    expect(applied.rows[0].result).toMatchObject({ deleted: 1, remainingPurgeDue: 0, recoveryDays: 7 });
    expect((await db.query("select build_artifact_id, execution_job_id from client_pipeline_items where id='00000000-0000-4000-8000-000000000001'")).rows).toHaveLength(0);
    expect((await db.query("select id from client_pipeline_items where id='00000000-0000-4000-8000-000000000002'")).rows).toHaveLength(1);
    expect((await db.query("select id from client_pipeline_items where tenant_slug='tenant-b'")).rows).toHaveLength(2);
    expect((await db.query("select event_type,metadata from client_runtime_audit_events")).rows[0]).toMatchObject({
      event_type: "tenant.pipeline.retention_purged", metadata: { deleted: 1, retentionDays: 28 },
    });
  } finally { await db.close(); }
});

test("Pipeline purge is service-role-only, validates scope, and rolls back if audit recording fails", async () => {
  const db = await database();
  try {
    const privileges = await db.query<{ member: boolean; operator: boolean }>(`
      select has_function_privilege('authenticated','public.purge_expired_client_pipeline_items(text,boolean,integer)','EXECUTE') as member,
        has_function_privilege('service_role','public.purge_expired_client_pipeline_items(text,boolean,integer)','EXECUTE') as operator
    `);
    expect(privileges.rows[0]).toEqual({ member: false, operator: true });
    await expect(db.query(purge, ["missing-tenant", false, 10])).rejects.toThrow(/client_pipeline_retention_tenant_not_found/);
    await expect(db.query(purge, ["tenant-a", false, 501])).rejects.toThrow(/client_pipeline_retention_invalid_input/);
    await db.exec(`
      create function reject_pipeline_retention_audit() returns trigger language plpgsql as $$
      begin raise exception 'audit_unavailable'; end; $$;
      create trigger reject_pipeline_retention_audit before insert on client_runtime_audit_events
        for each row execute function reject_pipeline_retention_audit();
    `);
    await expect(db.query(purge, ["tenant-a", true, 100])).rejects.toThrow(/audit_unavailable/);
    expect((await db.query("select id from client_pipeline_items where id='00000000-0000-4000-8000-000000000001'")).rows).toHaveLength(1);
  } finally { await db.close(); }
});
