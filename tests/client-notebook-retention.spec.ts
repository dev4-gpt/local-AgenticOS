import { readFileSync } from "node:fs";
import { PGlite } from "@electric-sql/pglite";
import { expect, test } from "@playwright/test";

async function database() {
  const db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated; create role service_role;
    create schema auth; create schema extensions;
    create function auth.role() returns text language sql stable as $$ select current_setting('request.jwt.claim.role', true) $$;
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
    create table client_tenants (slug text primary key, retention_days integer not null);
    create table client_runtime_audit_events (
      id bigint generated by default as identity primary key,
      tenant_slug text not null, event_type text not null, metadata jsonb not null
    );
    create table client_notebooks (
      id uuid primary key, tenant_slug text not null references client_tenants(slug) on delete cascade,
      created_by uuid not null, title text not null, summary text not null default '',
      status text not null default 'active', created_at timestamptz not null default now(),
      updated_at timestamptz not null default now()
    );
    create table client_runtime_records (
      id uuid primary key, tenant_slug text not null references client_tenants(slug) on delete cascade,
      notebook_id uuid references client_notebooks(id) on delete set null, content text not null
    );
    create table client_notebook_sources (
      id uuid primary key, tenant_slug text not null references client_tenants(slug) on delete cascade,
      notebook_id uuid references client_notebooks(id) on delete set null, title text not null
    );
    insert into client_tenants values ('tenant-a', 28), ('tenant-b', 28), ('tenant-short', 14);
    insert into client_notebooks values
      ('00000000-0000-4000-8000-000000000001', 'tenant-a', '00000000-0000-4000-8000-000000000101', 'Expired', '', 'active', now() - interval '36 days', now() - interval '36 days'),
      ('00000000-0000-4000-8000-000000000002', 'tenant-a', '00000000-0000-4000-8000-000000000101', 'Current', '', 'active', now() - interval '27 days', now() - interval '27 days'),
      ('00000000-0000-4000-8000-000000000003', 'tenant-b', '00000000-0000-4000-8000-000000000102', 'Other tenant', '', 'active', now() - interval '40 days', now() - interval '40 days'),
      ('00000000-0000-4000-8000-000000000004', 'tenant-short', '00000000-0000-4000-8000-000000000103', 'Short policy expired', '', 'active', now() - interval '22 days', now() - interval '22 days');
    insert into client_runtime_records values
      ('00000000-0000-4000-8000-000000000011', 'tenant-a', '00000000-0000-4000-8000-000000000001', 'live record');
    insert into client_notebook_sources values
      ('00000000-0000-4000-8000-000000000021', 'tenant-a', '00000000-0000-4000-8000-000000000001', 'live source');
    create function client_member(text) returns boolean language sql stable as $$
      select $1 in ('tenant-a', 'tenant-b', 'tenant-short')
    $$;
    create function client_tenant_retention_days(text) returns integer language sql stable security definer as $$
      select retention_days from client_tenants where slug = $1 and client_member($1)
    $$;
    grant execute on function client_tenant_retention_days(text) to authenticated, service_role;
    grant select, insert, update, delete on client_notebooks to authenticated;
    grant insert on client_runtime_records, client_notebook_sources to authenticated;
    alter table client_notebooks enable row level security;
  `);
  await db.exec(readFileSync("product-experience/supabase-client-notebook-retention-28.sql", "utf8"));
  await db.exec(readFileSync("product-experience/supabase-client-notebook-retention-28.sql", "utf8"));
  return db;
}

const purge = "select public.purge_expired_client_notebooks($1, $2, $3) as result";

test("expired notebook metadata is unreadable and member-created timestamps cannot be backdated", async () => {
  const db = await database();
  try {
    await db.exec(`set role authenticated; select set_config('request.jwt.claim.role', 'authenticated', false); select set_config('request.jwt.claim.sub', '00000000-0000-4000-8000-000000000101', false);`);
    const visible = await db.query<{ title: string }>("select title from client_notebooks where tenant_slug='tenant-a'");
    expect(visible.rows.map((row) => row.title)).toEqual(["Current"]);
    expect((await db.query("select id from client_notebooks where tenant_slug='tenant-short'")).rows).toHaveLength(0);
    await db.query(`insert into client_notebooks (id, tenant_slug, created_by, title, created_at) values
      ('00000000-0000-4000-8000-000000000005', 'tenant-a', '00000000-0000-4000-8000-000000000101', 'New', now() - interval '90 days')`);
    const inserted = await db.query<{ recent: boolean }>("select created_at > now() - interval '1 minute' as recent from client_notebooks where id='00000000-0000-4000-8000-000000000005'");
    expect(inserted.rows[0].recent).toBe(true);
    await db.query(`insert into client_runtime_records values
      ('00000000-0000-4000-8000-000000000012', 'tenant-a', '00000000-0000-4000-8000-000000000002', 'active notebook link')`);
    await db.query(`insert into client_notebook_sources values
      ('00000000-0000-4000-8000-000000000022', 'tenant-a', '00000000-0000-4000-8000-000000000002', 'active notebook link')`);
    await expect(db.query(`insert into client_runtime_records values
      ('00000000-0000-4000-8000-000000000013', 'tenant-a', '00000000-0000-4000-8000-000000000001', 'cannot relink')`))
      .rejects.toThrow(/client_notebook_reference_expired_or_foreign/);
    await expect(db.query(`insert into client_notebook_sources values
      ('00000000-0000-4000-8000-000000000023', 'tenant-a', '00000000-0000-4000-8000-000000000001', 'cannot relink')`))
      .rejects.toThrow(/client_notebook_reference_expired_or_foreign/);
  } finally {
    await db.close();
  }
});

test("notebook cleanup is bounded and detaches, rather than deletes, live content", async () => {
  const db = await database();
  try {
    const preview = await db.query<{ result: Record<string, unknown> }>(purge, ["tenant-a", false, 1]);
    expect(preview.rows[0].result).toMatchObject({ candidates: 1, deleted: 0, remainingCandidates: 1, applied: false });
    const result = await db.query<{ result: Record<string, unknown> }>(purge, ["tenant-a", true, 1]);
    expect(result.rows[0].result).toMatchObject({ candidates: 1, deleted: 1, remainingCandidates: 0, applied: true });
    expect((await db.query("select id from client_notebooks where tenant_slug='tenant-b'")).rows).toHaveLength(1);
    expect((await db.query("select notebook_id, content from client_runtime_records")).rows).toEqual([{ notebook_id: null, content: "live record" }]);
    expect((await db.query("select notebook_id, title from client_notebook_sources")).rows).toEqual([{ notebook_id: null, title: "live source" }]);
    expect((await db.query("select event_type from client_runtime_audit_events")).rows).toEqual([{ event_type: "tenant.notebooks.retention_purged" }]);
  } finally {
    await db.close();
  }
});

test("notebook purge is service-role-only and rolls back when audit evidence cannot be written", async () => {
  const db = await database();
  try {
    const privileges = await db.query<{ member: boolean; operator: boolean }>(`
      select has_function_privilege('authenticated', 'public.purge_expired_client_notebooks(text,boolean,integer)', 'EXECUTE') as member,
        has_function_privilege('service_role', 'public.purge_expired_client_notebooks(text,boolean,integer)', 'EXECUTE') as operator
    `);
    expect(privileges.rows[0]).toEqual({ member: false, operator: true });
    await expect(db.query(purge, ["tenant-a", false, 501])).rejects.toThrow(/client_notebook_container_retention_invalid_input/);
    await db.exec(`
      create function reject_notebook_retention_audit() returns trigger language plpgsql as $$
      begin raise exception 'audit_unavailable'; end; $$;
      create trigger reject_notebook_retention_audit before insert on client_runtime_audit_events
        for each row execute function reject_notebook_retention_audit();
    `);
    await expect(db.query(purge, ["tenant-a", true, 100])).rejects.toThrow(/audit_unavailable/);
    expect((await db.query("select id from client_notebooks where tenant_slug='tenant-a'")).rows).toHaveLength(2);
    expect((await db.query("select notebook_id from client_runtime_records")).rows[0].notebook_id).not.toBeNull();
  } finally {
    await db.close();
  }
});
