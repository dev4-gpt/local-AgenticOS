import { readFileSync } from "node:fs";
import { expect, test } from "@playwright/test";
import { PGlite } from "@electric-sql/pglite";

async function sourceRetentionDatabase() {
  const db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated; create role service_role;
    create schema extensions; create schema auth;
    create function auth.role() returns text language sql stable as $$
      select current_setting('request.jwt.claim.role', true)
    $$;
    create table client_tenants (slug text primary key, retention_days integer not null);
    create table client_notebook_sources (
      id uuid primary key, tenant_slug text not null references client_tenants(slug),
      created_at timestamptz not null, retention_expires_at timestamptz,
      created_by text not null default 'member', status text not null default 'registered'
    );
    create table client_notebook_chunks (
      id uuid primary key, tenant_slug text not null references client_tenants(slug),
      source_id uuid not null references client_notebook_sources(id) on delete cascade,
      content text not null, created_at timestamptz not null
    );
    create table client_runtime_audit_events (
      id bigint generated by default as identity primary key, tenant_slug text not null,
      event_type text not null, metadata jsonb not null
    );
    insert into client_tenants values ('tenant-a', 28), ('tenant-b', 28), ('tenant-short', 14), ('tenant-invalid', 29);
    insert into client_notebook_sources values
      ('00000000-0000-4000-8000-000000000001', 'tenant-a', now() - interval '36 days', now() - interval '8 days'),
      ('00000000-0000-4000-8000-000000000002', 'tenant-a', now() - interval '30 days', now() - interval '8 days'),
      ('00000000-0000-4000-8000-000000000003', 'tenant-a', now() - interval '29 days', null),
      ('00000000-0000-4000-8000-000000000004', 'tenant-a', now() - interval '29 days', now() + interval '1 day'),
      ('00000000-0000-4000-8000-000000000005', 'tenant-a', now() - interval '10 days', now() - interval '1 day'),
      ('00000000-0000-4000-8000-000000000006', 'tenant-b', now() - interval '29 days', now() - interval '1 day'),
      ('00000000-0000-4000-8000-000000000007', 'tenant-short', now() - interval '22 days', now() - interval '8 days'),
      ('00000000-0000-4000-8000-000000000008', 'tenant-a', now() - interval '29 days', now() - interval '8 days');
    insert into client_notebook_chunks values
      ('00000000-0000-4000-8000-000000000011', 'tenant-a', '00000000-0000-4000-8000-000000000001', 'old chunk', now() - interval '36 days'),
      ('00000000-0000-4000-8000-000000000012', 'tenant-a', '00000000-0000-4000-8000-000000000003', 'legacy chunk', now() - interval '29 days'),
      ('00000000-0000-4000-8000-000000000013', 'tenant-b', '00000000-0000-4000-8000-000000000006', 'other tenant', now() - interval '29 days'),
      ('00000000-0000-4000-8000-000000000014', 'tenant-a', '00000000-0000-4000-8000-000000000008', 'newer chunk', now() - interval '1 day');
  `);
  const migration = readFileSync("product-experience/supabase-client-notebook-source-retention.sql", "utf8");
  await db.exec(migration);
  await db.exec(migration);
  return db;
}

const call = "select public.purge_expired_client_notebook_sources($1,$2,$3) as result";

test("source retention is tenant-scoped, batched and cascades only eligible chunks", async () => {
  const db = await sourceRetentionDatabase();
  try {
    const preview = await db.query<{ result: Record<string, unknown> }>(call, ["tenant-a", false, 1]);
    expect(preview.rows[0].result).toMatchObject({ candidates: 2, deleted: 0, remainingCandidates: 2,
      legacyMissingExpiry: 1, legacyExtendedExpiry: 1, deferredNewerChunks: 1, inRecovery: 1,
      recoveryDays: 7, purgeAfterDays: 35, applied: false });
    expect((await db.query("select id from client_runtime_audit_events")).rows).toHaveLength(0);

    const first = await db.query<{ result: Record<string, unknown> }>(call, ["tenant-a", true, 1]);
    expect(first.rows[0].result).toMatchObject({ deleted: 1, remainingCandidates: 1 });
    const second = await db.query<{ result: Record<string, unknown> }>(call, ["tenant-a", true, 1]);
    expect(second.rows[0].result).toMatchObject({ deleted: 1, remainingCandidates: 0 });
    const remaining = await db.query<{ id: string }>("select id from client_notebook_sources where tenant_slug='tenant-a' order by id");
    expect(remaining.rows.map((row) => row.id)).toEqual([
      "00000000-0000-4000-8000-000000000003",
      "00000000-0000-4000-8000-000000000004",
      "00000000-0000-4000-8000-000000000005",
      "00000000-0000-4000-8000-000000000008",
    ]);
    expect((await db.query("select id from client_notebook_chunks where tenant_slug='tenant-a'")).rows).toHaveLength(2);
    expect((await db.query("select id from client_notebook_sources where tenant_slug='tenant-b'")).rows).toHaveLength(1);
    const audit = await db.query<{ event_type: string; metadata: { deleted: number } }>("select event_type, metadata from client_runtime_audit_events order by id");
    expect(audit.rows).toHaveLength(2);
    expect(audit.rows[0]).toMatchObject({ event_type: "tenant.notebook_sources.retention_purged", metadata: { deleted: 1 } });
  } finally {
    await db.close();
  }
});

test("source retention rejects unconfigured tenants and rolls back when audit fails", async () => {
  const db = await sourceRetentionDatabase();
  try {
    const privileges = await db.query<{ anonymous: boolean; member: boolean; operator: boolean }>(`
      select has_function_privilege('anon', 'public.purge_expired_client_notebook_sources(text,boolean,integer)', 'EXECUTE') as anonymous,
        has_function_privilege('authenticated', 'public.purge_expired_client_notebook_sources(text,boolean,integer)', 'EXECUTE') as member,
        has_function_privilege('service_role', 'public.purge_expired_client_notebook_sources(text,boolean,integer)', 'EXECUTE') as operator
    `);
    expect(privileges.rows[0]).toEqual({ anonymous: false, member: false, operator: true });
    expect((await db.query(call, ["tenant-short", false, 1])).rows[0].result).toMatchObject({ retentionDays: 14, candidates: 1, recoveryDays: 7, purgeAfterDays: 21, applied: false });
    await expect(db.query(call, ["tenant-invalid", false, 1])).rejects.toThrow(/client_notebook_retention_tenant_not_configured/);
    await expect(db.query(call, ["tenant-a", true, 101])).rejects.toThrow(/client_notebook_retention_invalid_input/);
    await db.exec(`
      create function reject_notebook_retention_audit() returns trigger language plpgsql as $$
      begin raise exception 'audit_unavailable'; end; $$;
      create trigger reject_notebook_retention_audit before insert on client_runtime_audit_events
        for each row execute function reject_notebook_retention_audit();
    `);
    await expect(db.query(call, ["tenant-a", true, 1])).rejects.toThrow(/audit_unavailable/);
    expect((await db.query("select id from client_notebook_sources where tenant_slug='tenant-a'")).rows).toHaveLength(6);
    expect((await db.query("select id from client_notebook_chunks where tenant_slug='tenant-a'")).rows).toHaveLength(3);
  } finally {
    await db.close();
  }
});

test("source stays recoverable until seven full days after its active expiry", async () => {
  const db = await sourceRetentionDatabase();
  try {
    await db.exec("select set_config('request.jwt.claim.role', 'service_role', false)");
    await db.exec(`
      insert into client_notebook_sources (id, tenant_slug, created_at, retention_expires_at) values
        ('00000000-0000-4000-8000-000000000021', 'tenant-a', now() - interval '35 days', now() - interval '6 days 23 hours'),
        ('00000000-0000-4000-8000-000000000022', 'tenant-a', now() - interval '36 days', now() - interval '8 days');
    `);
    const preview = await db.query<{ result: Record<string, unknown> }>(call, ["tenant-a", false, 100]);
    expect(preview.rows[0].result).toMatchObject({ candidates: 3, inRecovery: 2, recoveryDays: 7 });
    const apply = await db.query<{ result: Record<string, unknown> }>(call, ["tenant-a", true, 100]);
    expect(apply.rows[0].result).toMatchObject({ deleted: 3, remainingCandidates: 0 });
    const retained = await db.query<{ id: string }>(`select id from client_notebook_sources where id in
      ('00000000-0000-4000-8000-000000000021','00000000-0000-4000-8000-000000000022') order by id`);
    expect(retained.rows.map((row) => row.id)).toEqual(["00000000-0000-4000-8000-000000000021"]);
  } finally {
    await db.close();
  }
});

test("member writes cannot backdate, extend, or mutate source retention fields", async () => {
  const db = await sourceRetentionDatabase();
  try {
    await db.exec("select set_config('request.jwt.claim.role', 'authenticated', false)");
    await db.exec(`
      insert into client_notebook_sources (id, tenant_slug, created_at, retention_expires_at)
      values ('00000000-0000-4000-8000-000000000009', 'tenant-a', now() - interval '90 days', now() + interval '90 days');
    `);
    const inserted = await db.query<{ created_at: string; retention_expires_at: string }>(`
      select created_at, retention_expires_at from client_notebook_sources
      where id='00000000-0000-4000-8000-000000000009'
    `);
    expect(Date.parse(inserted.rows[0].created_at)).toBeGreaterThan(Date.now() - 60_000);
    expect(Date.parse(inserted.rows[0].retention_expires_at) - Date.parse(inserted.rows[0].created_at))
      .toBeLessThanOrEqual(28 * 24 * 60 * 60 * 1000);
    await expect(db.exec(`update client_notebook_sources set created_at=now() + interval '1 day'
      where id='00000000-0000-4000-8000-000000000009'`)).rejects.toThrow(/client_notebook_retention_immutable/);
    await expect(db.exec(`update client_notebook_sources set retention_expires_at=now() + interval '90 days'
      where id='00000000-0000-4000-8000-000000000009'`)).rejects.toThrow(/client_notebook_retention_immutable/);
    await db.exec(`update client_notebook_sources set status='ready'
      where id='00000000-0000-4000-8000-000000000009'`);
    await expect(db.exec(`insert into client_notebook_sources (id, tenant_slug, created_at, retention_expires_at)
      values ('00000000-0000-4000-8000-000000000010', 'tenant-a', now(), null)`)).rejects.toThrow(/client_notebook_retention_invalid/);
    await db.exec("select set_config('request.jwt.claim.role', 'service_role', false)");
    await db.exec(`insert into client_notebook_sources (id, tenant_slug, created_at, retention_expires_at)
      values ('00000000-0000-4000-8000-000000000010', 'tenant-a', now() - interval '90 days', null)`);
    const restored = await db.query<{ retention_expires_at: string | null }>(`
      select retention_expires_at from client_notebook_sources where id='00000000-0000-4000-8000-000000000010'
    `);
    expect(restored.rows[0].retention_expires_at).toBeNull();
  } finally {
    await db.close();
  }
});
