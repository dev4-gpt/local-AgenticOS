import { readFileSync } from "node:fs";
import { PGlite } from "@electric-sql/pglite";
import { expect, test } from "@playwright/test";

async function database() {
  const db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated; create role service_role;
    create schema extensions;
    create table client_tenants (slug text primary key, retention_days integer not null);
    create table client_runtime_audit_events (
      id bigint generated by default as identity primary key,
      tenant_slug text not null, event_type text not null, metadata jsonb not null
    );
    create table client_research_runs (
      id uuid primary key, tenant_slug text not null references client_tenants(slug) on delete cascade,
      created_at timestamptz not null default now()
    );
    create table client_research_records (
      id uuid primary key, tenant_slug text not null references client_tenants(slug) on delete cascade,
      research_run_id uuid not null references client_research_runs(id) on delete cascade,
      retrieved_at timestamptz not null
    );
    create table client_research_citations (
      id uuid primary key, tenant_slug text not null references client_tenants(slug) on delete cascade,
      research_run_id uuid not null references client_research_runs(id) on delete cascade,
      research_record_id uuid not null references client_research_records(id) on delete cascade,
      retrieved_at timestamptz not null
    );
    create table client_research_worker_failures (
      id uuid primary key, tenant_slug text not null references client_tenants(slug) on delete cascade,
      created_at timestamptz not null default now()
    );
    insert into client_tenants values ('tenant-a', 28), ('tenant-b', 28), ('tenant-short', 14);
    insert into client_research_runs values
      ('00000000-0000-4000-8000-000000000001', 'tenant-a', now() - interval '36 days'),
      ('00000000-0000-4000-8000-000000000002', 'tenant-a', now() - interval '27 days'),
      ('00000000-0000-4000-8000-000000000003', 'tenant-b', now() - interval '40 days'),
      ('00000000-0000-4000-8000-000000000004', 'tenant-short', now() - interval '22 days');
    insert into client_research_records values
      ('00000000-0000-4000-8000-000000000011', 'tenant-a', '00000000-0000-4000-8000-000000000001', now() - interval '36 days'),
      ('00000000-0000-4000-8000-000000000012', 'tenant-a', '00000000-0000-4000-8000-000000000001', now() - interval '36 days'),
      ('00000000-0000-4000-8000-000000000013', 'tenant-a', '00000000-0000-4000-8000-000000000002', now() + interval '90 days'),
      ('00000000-0000-4000-8000-000000000014', 'tenant-b', '00000000-0000-4000-8000-000000000003', now() - interval '40 days');
    insert into client_research_citations values
      ('00000000-0000-4000-8000-000000000021', 'tenant-a', '00000000-0000-4000-8000-000000000001', '00000000-0000-4000-8000-000000000011', now() - interval '36 days'),
      ('00000000-0000-4000-8000-000000000022', 'tenant-a', '00000000-0000-4000-8000-000000000001', '00000000-0000-4000-8000-000000000012', now() - interval '29 days');
    insert into client_research_worker_failures values
      ('00000000-0000-4000-8000-000000000031', 'tenant-a', now() - interval '36 days'),
      ('00000000-0000-4000-8000-000000000032', 'tenant-b', now() - interval '40 days');
    create function client_member(text) returns boolean language sql stable as $$
      select $1 in ('tenant-a', 'tenant-b', 'tenant-short')
    $$;
    create function client_tenant_retention_days(text) returns integer language sql stable security definer as $$
      select retention_days from client_tenants where slug = $1 and client_member($1)
    $$;
    grant execute on function client_tenant_retention_days(text) to authenticated, service_role;
    grant select on client_research_runs, client_research_records,
      client_research_citations, client_research_worker_failures to authenticated;
    alter table client_research_runs enable row level security;
    alter table client_research_records enable row level security;
    alter table client_research_citations enable row level security;
    alter table client_research_worker_failures enable row level security;
  `);
  await db.exec(readFileSync("product-experience/supabase-client-research-retention-28.sql", "utf8"));
  await db.exec(readFileSync("product-experience/supabase-client-research-retention-28.sql", "utf8"));
  return db;
}

const purge = "select public.purge_expired_client_research($1, $2, $3) as result";

test("research payloads become unreadable by item age and honor tenant-specific limits", async () => {
  const db = await database();
  try {
    await db.exec("set role authenticated");
    expect((await db.query("select id from client_research_runs where tenant_slug='tenant-a'")).rows).toHaveLength(1);
    expect((await db.query("select id from client_research_records where tenant_slug='tenant-a'")).rows).toHaveLength(1);
    expect((await db.query("select id from client_research_citations where tenant_slug='tenant-a'")).rows).toHaveLength(0);
    expect((await db.query("select id from client_research_worker_failures where tenant_slug='tenant-a'")).rows).toHaveLength(0);
    expect((await db.query("select id from client_research_runs where tenant_slug='tenant-b'")).rows).toHaveLength(0);
    expect((await db.query("select id from client_research_runs where tenant_slug='tenant-short'")).rows).toHaveLength(0);
    expect((await db.query("select created_at <= now() as safe from client_research_records where id='00000000-0000-4000-8000-000000000013'")).rows[0].safe).toBe(true);
    expect((await db.query("select public.client_tenant_retention_days('not-a-member') as days")).rows[0].days).toBeNull();
  } finally {
    await db.close();
  }
});

test("bounded research purge deletes children first and defers parents with younger children", async () => {
  const db = await database();
  try {
    const preview = await db.query<{ result: Record<string, unknown> }>(purge, ["tenant-a", false, 1]);
    expect(preview.rows[0].result).toMatchObject({
      candidates: { runs: 1, records: 2, citations: 1, workerFailures: 1 },
      deleted: { runs: 0, records: 0, citations: 0, workerFailures: 0 }, applied: false,
    });
    expect((await db.query("select id from client_runtime_audit_events")).rows).toHaveLength(0);

    const first = await db.query<{ result: Record<string, unknown> }>(purge, ["tenant-a", true, 1]);
    expect(first.rows[0].result.deleted).toEqual({ runs: 0, records: 1, citations: 1, workerFailures: 1 });
    expect(first.rows[0].result.remaining).toMatchObject({ runs: 1, records: 1, citations: 0, workerFailures: 0 });
    expect((await db.query("select id from client_research_citations where id='00000000-0000-4000-8000-000000000022'")).rows).toHaveLength(1);
    expect((await db.query("select id from client_research_records where id='00000000-0000-4000-8000-000000000012'")).rows).toHaveLength(1);
    expect((await db.query("select id from client_research_runs where tenant_slug='tenant-b'")).rows).toHaveLength(1);

    await db.exec("update client_research_citations set created_at = now() - interval '36 days' where id='00000000-0000-4000-8000-000000000022'");
    const second = await db.query<{ result: Record<string, unknown> }>(purge, ["tenant-a", true, 1]);
    expect(second.rows[0].result.deleted).toEqual({ runs: 1, records: 1, citations: 1, workerFailures: 0 });
    expect((await db.query("select id from client_research_runs where tenant_slug='tenant-a'")).rows).toHaveLength(1);
    expect((await db.query("select id from client_research_records where tenant_slug='tenant-a'")).rows).toHaveLength(1);
    expect((await db.query("select id from client_runtime_audit_events")).rows).toHaveLength(2);
  } finally {
    await db.close();
  }
});

test("research retention is service-role-only, bounded, and atomic with audit evidence", async () => {
  const db = await database();
  try {
    const privileges = await db.query<{ member: boolean; operator: boolean }>(`
      select has_function_privilege('authenticated', 'public.purge_expired_client_research(text,boolean,integer)', 'EXECUTE') as member,
        has_function_privilege('service_role', 'public.purge_expired_client_research(text,boolean,integer)', 'EXECUTE') as operator
    `);
    expect(privileges.rows[0]).toEqual({ member: false, operator: true });
    await expect(db.query(purge, ["tenant-a", false, 1001])).rejects.toThrow(/client_research_retention_invalid_input/);
    await expect(db.query(purge, ["missing-tenant", false, 10])).rejects.toThrow(/client_research_retention_tenant_not_found/);
    await db.exec(`
      create function reject_research_retention_audit() returns trigger language plpgsql as $$
      begin raise exception 'audit_unavailable'; end; $$;
      create trigger reject_research_retention_audit before insert on client_runtime_audit_events
        for each row execute function reject_research_retention_audit();
    `);
    await expect(db.query(purge, ["tenant-a", true, 100])).rejects.toThrow(/audit_unavailable/);
    expect((await db.query("select id from client_research_runs where tenant_slug='tenant-a'")).rows).toHaveLength(2);
    expect((await db.query("select id from client_research_records where tenant_slug='tenant-a'")).rows).toHaveLength(3);
    expect((await db.query("select id from client_research_citations where tenant_slug='tenant-a'")).rows).toHaveLength(2);
    expect((await db.query("select id from client_research_worker_failures where tenant_slug='tenant-a'")).rows).toHaveLength(1);
  } finally {
    await db.close();
  }
});
