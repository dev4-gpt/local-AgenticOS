import { expect, test } from "@playwright/test";
import { spawn } from "node:child_process";
import { createHash, randomBytes } from "node:crypto";
import { readFileSync } from "node:fs";

// Real simultaneous requests against a real PostgreSQL. Skipped unless ADAPTER_BUDGET_TEST_DB_CONTAINER names a
// running local Postgres container (for example the local Supabase database container). Optional:
// ADAPTER_BUDGET_TEST_DB_USER (default "postgres").
// Each run creates its own throwaway database with stand-in tables, applies the real adapter SQL, runs many
// separate psql connections at the same time, and removes the database. No real data, tenant or credential is used.
const CONTAINER = process.env.ADAPTER_BUDGET_TEST_DB_CONTAINER;
const DB_USER = process.env.ADAPTER_BUDGET_TEST_DB_USER || "postgres";
const HOST_SQL = readFileSync("product-experience/supabase-client-adapter-host.sql", "utf8");
const BUDGET_SQL = readFileSync("product-experience/supabase-client-adapter-budget.sql", "utf8");
const WORKER = "test-worker-token-aaaaaaaaaaaaaaaaaaaa";
const OWNER = "00000000-0000-4000-8000-0000000000a1";
const sha = (text: string) => createHash("sha256").update(text).digest("hex");

function psql(database: string, input: string): Promise<{ code: number | null; out: string; err: string }> {
  return new Promise((resolve) => {
    const child = spawn("docker", ["exec", "-i", CONTAINER!, "psql", "-U", DB_USER, "-X", "-q", "-t", "-A", "-v", "ON_ERROR_STOP=1", "-d", database, "-f", "-"]);
    let out = "";
    let err = "";
    child.stdout.on("data", (d) => { out += d; });
    child.stderr.on("data", (d) => { err += d; });
    child.on("close", (code) => resolve({ code, out: out.trim(), err: err.trim() }));
    child.stdin.end(input);
  });
}

const FIXTURE = `
  do $$ begin
    if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon; end if;
    if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated; end if;
    if not exists (select 1 from pg_roles where rolname = 'service_role') then create role service_role bypassrls; end if;
  end $$;
  create schema extensions; create extension pgcrypto with schema extensions;
  create schema auth;
  create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
  create table auth.users(id uuid primary key);
  create table public.client_tenants(slug text primary key, status text not null default 'active', worker_token_hash text);
  create table public.client_memberships(
    tenant_slug text not null references public.client_tenants(slug) on delete cascade,
    user_id uuid not null references auth.users(id), role text not null, status text not null default 'active',
    primary key (tenant_slug, user_id));
  create function public.client_member(p_tenant_slug text) returns boolean language sql stable security definer set search_path = public as $$
    select exists (select 1 from public.client_memberships where tenant_slug = p_tenant_slug and user_id = auth.uid() and status = 'active') $$;
  create table public.client_runtime_budget_ledger (
    id bigint generated by default as identity primary key,
    tenant_slug text not null references public.client_tenants(slug) on delete cascade,
    job_id uuid, provider text not null, model text,
    amount_micros bigint not null check (amount_micros >= 0),
    usage_metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now());
  grant usage on schema public, auth, extensions to anon, authenticated, service_role;
  grant execute on function public.client_member(text) to authenticated;
  insert into auth.users values ('${OWNER}');
  insert into public.client_tenants(slug, worker_token_hash) values ('tenant-a', '${sha(WORKER)}');
  insert into public.client_memberships values ('tenant-a', '${OWNER}', 'owner', 'active');
`;

const reserveSql = (adapter: string, task: string, key: string, amount: number, tenantCap: number) =>
  `set role anon; select public.client_adapter_budget_reserve('tenant-a','${WORKER}','${adapter}','${task}','${key}',${amount},'provider-x','model-x',${tenantCap});`;

async function withDatabase(run: (db: string) => Promise<void>) {
  const db = `adapter_budget_test_${randomBytes(4).toString("hex")}`;
  const created = await psql("postgres", `create database ${db} template template0;`);
  expect(created.code, created.err).toBe(0);
  try {
    const setup = await psql(db, FIXTURE + HOST_SQL + BUDGET_SQL + `
      insert into public.client_adapter_registry (tenant_slug, adapter_id, display_name, contract_version, manifest_sha256, state, created_by)
      values ('tenant-a','forge','Forge','h1','${"a".repeat(64)}','enabled','${OWNER}'),
             ('tenant-a','knowledge','Knowledge','h1','${"a".repeat(64)}','enabled','${OWNER}');`);
    expect(setup.code, setup.err).toBe(0);
    await run(db);
  } finally {
    await psql("postgres", `drop database if exists ${db} with (force);`);
  }
}

const ledgerTotal = async (db: string) => Number((await psql(db, "select coalesce(sum(amount_micros),0) from public.client_runtime_budget_ledger;")).out);
const ledgerRows = async (db: string) => Number((await psql(db, "select count(*) from public.client_runtime_budget_ledger;")).out);

test.describe("simultaneous budget requests against a real Postgres", () => {
  test.skip(!CONTAINER, "set ADAPTER_BUDGET_TEST_DB_CONTAINER to a running local Postgres container to run this");
  test.setTimeout(180_000);

  test("20 requests at once against a cap that fits 3 reserve exactly 3 and never pass the cap", async () => {
    await withDatabase(async (db) => {
      await psql(db, "update public.client_adapter_registry set budget_cap_micros = 1000, budget_period = 'total' where adapter_id = 'forge';");
      const results = await Promise.all(Array.from({ length: 20 }, (_, i) => psql(db, reserveSql("forge", `task-${i}`, `reserve-key-${i}`, 300, 1_000_000))));
      expect(results.every((r) => r.code === 0), results.map((r) => r.err).join("|")).toBe(true);
      const answers = results.map((r) => r.out);
      expect(answers.filter((a) => a === "reserved")).toHaveLength(3);
      expect(answers.filter((a) => a === "adapter_cap_exceeded")).toHaveLength(17);
      expect(await ledgerTotal(db)).toBe(900);
    });
  });

  test("two adapters racing for the tenant monthly cap together reserve exactly what fits", async () => {
    await withDatabase(async (db) => {
      const jobs = Array.from({ length: 24 }, (_, i) => psql(db, reserveSql(i % 2 ? "forge" : "knowledge", `task-${i}`, `reserve-key-${i}`, 300, 1000)));
      const answers = (await Promise.all(jobs)).map((r) => r.out);
      expect(answers.filter((a) => a === "reserved")).toHaveLength(3);
      expect(answers.filter((a) => a === "tenant_cap_exceeded")).toHaveLength(21);
      expect(await ledgerTotal(db)).toBe(900);
    });
  });

  test("10 identical retries at once charge exactly once", async () => {
    await withDatabase(async (db) => {
      const answers = (await Promise.all(Array.from({ length: 10 }, () => psql(db, reserveSql("forge", "task-same", "reserve-key-same", 500, 1_000_000))))).map((r) => r.out);
      expect(answers.filter((a) => a === "reserved")).toHaveLength(1);
      expect(answers.filter((a) => a === "already_reserved")).toHaveLength(9);
      expect(await ledgerRows(db)).toBe(1);
      expect(await ledgerTotal(db)).toBe(500);
    });
  });

  test("settling and releasing at the same time as new reservations never lets spending pass the cap", async () => {
    await withDatabase(async (db) => {
      await psql(db, "update public.client_adapter_registry set budget_cap_micros = 1000, budget_period = 'total' where adapter_id = 'forge';");
      for (let i = 0; i < 3; i++) {
        const r = await psql(db, reserveSql("forge", `base-${i}`, `reserve-key-base-${i}`, 300, 1_000_000));
        expect(r.out).toBe("reserved");
      }
      const closes = [0, 1, 2].map((i) => psql(db, `set role anon; select public.client_adapter_budget_release('tenant-a','${WORKER}','forge','base-${i}','release-key-base-${i}');`));
      const opens = Array.from({ length: 12 }, (_, i) => psql(db, reserveSql("forge", `new-${i}`, `reserve-key-new-${i}`, 300, 1_000_000)));
      const answers = (await Promise.all([...closes, ...opens])).map((r) => r.out);
      expect(answers.filter((a) => a === "released")).toHaveLength(3);
      expect(await ledgerTotal(db)).toBeLessThanOrEqual(1000);
    });
  });
});
