import { readFileSync } from "node:fs";
import { PGlite } from "@electric-sql/pglite";
import { expect, test } from "@playwright/test";

async function database() {
  const db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated; create role service_role;
    create schema auth;
    create function auth.uid() returns uuid language sql stable as $$
      select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
    $$;
    create table client_tenants (slug text primary key, retention_days integer not null);
    create table client_runtime_audit_events (
      id bigint generated by default as identity primary key,
      tenant_slug text not null, event_type text not null, metadata jsonb not null
    );
    create table client_runtime_jobs (
      id uuid primary key, tenant_slug text not null references client_tenants(slug) on delete cascade,
      requested_by uuid, capability text not null, status text not null,
      input_metadata jsonb not null default '{}'::jsonb,
      output_metadata jsonb not null default '{}'::jsonb,
      created_at timestamptz not null default now()
    );
    insert into client_tenants values ('tenant-a', 28), ('tenant-b', 14), ('tenant-invalid', 0);
    insert into client_runtime_jobs (id, tenant_slug, capability, status, created_at) values
      ('00000000-0000-4000-8000-000000000001', 'tenant-a', 'test', 'succeeded', now() - interval '28 days 1 second'),
      ('00000000-0000-4000-8000-000000000002', 'tenant-a', 'test', 'succeeded', now() - interval '20 days'),
      ('00000000-0000-4000-8000-000000000003', 'tenant-a', 'test', 'succeeded', now() - interval '35 days'),
      ('00000000-0000-4000-8000-000000000004', 'tenant-b', 'test', 'succeeded', now() - interval '22 days'),
      ('00000000-0000-4000-8000-000000000005', 'tenant-invalid', 'test', 'succeeded', now() - interval '1 day');
    create function client_member(text) returns boolean language sql stable as $$
      select $1 in ('tenant-a', 'tenant-b', 'tenant-invalid')
    $$;
    create function client_tenant_retention_days(text) returns integer
      language sql stable security definer as $$
        select retention_days from client_tenants where slug = $1 and client_member($1)
      $$;
    grant execute on function client_tenant_retention_days(text) to authenticated, service_role;
    alter table client_runtime_jobs enable row level security;
    create policy client_jobs_member_select on client_runtime_jobs
      for select to authenticated using (client_member(tenant_slug));
    grant select on client_runtime_jobs to authenticated;
  `);
  await db.exec(readFileSync("product-experience/supabase-client-runtime-job-retention-28.sql", "utf8"));
  await db.exec(readFileSync("product-experience/supabase-client-runtime-job-retention-28.sql", "utf8"));
  return db;
}

const purge = "select public.purge_expired_client_runtime_jobs($1, $2, $3) as result";

test("job records become unreadable at active expiry, scoped by tenant retention", async () => {
  const db = await database();
  try {
    await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub', '00000000-0000-4000-8000-000000000101', false);`);
    expect((await db.query("select id from client_runtime_jobs where tenant_slug='tenant-a' order by id")).rows.map((row) => row.id))
      .toEqual(["00000000-0000-4000-8000-000000000002"]);
    expect((await db.query("select id from client_runtime_jobs where tenant_slug='tenant-b'")).rows).toHaveLength(0);
    expect((await db.query("select id from client_runtime_jobs where tenant_slug='tenant-invalid'")).rows).toHaveLength(0);
  } finally { await db.close(); }
});

test("bounded purge waits until active expiry plus recovery and records audit evidence", async () => {
  const db = await database();
  try {
    const preview = await db.query<{ result: Record<string, unknown> }>(purge, ["tenant-a", false, 1]);
    expect(preview.rows[0].result).toMatchObject({ candidates: 1, deleted: 0, remainingCandidates: 1, applied: false });
    expect((await db.query("select id from client_runtime_audit_events")).rows).toHaveLength(0);
    const applied = await db.query<{ result: Record<string, unknown> }>(purge, ["tenant-a", true, 1]);
    expect(applied.rows[0].result).toMatchObject({ candidates: 1, deleted: 1, remainingCandidates: 0, applied: true });
    expect((await db.query("select id from client_runtime_jobs where tenant_slug='tenant-b'")).rows).toHaveLength(1);
    expect((await db.query("select event_type, metadata from client_runtime_audit_events")).rows[0]).toMatchObject({
      event_type: "tenant.runtime_jobs.retention_purged",
      metadata: { deleted: 1, retentionDays: 28, recoveryDays: 7, purgeAfterDays: 35 },
    });
  } finally { await db.close(); }
});

test("job timestamps cannot be backdated and purge is service-role-only and audit-atomic", async () => {
  const db = await database();
  try {
    await db.query(`insert into client_runtime_jobs (id, tenant_slug, capability, status, created_at) values
      ('00000000-0000-4000-8000-000000000020', 'tenant-a', 'test', 'succeeded', now() - interval '90 days')`);
    const created = await db.query<{ recent: boolean }>("select created_at > now() - interval '1 minute' as recent from client_runtime_jobs where id='00000000-0000-4000-8000-000000000020'");
    expect(created.rows[0].recent).toBe(true);
    await expect(db.query("update client_runtime_jobs set created_at=now() - interval '90 days' where id='00000000-0000-4000-8000-000000000020'"))
      .rejects.toThrow(/client_runtime_job_retention_immutable/);
    const privileges = await db.query<{ member: boolean; operator: boolean }>(`
      select has_function_privilege('authenticated', 'public.purge_expired_client_runtime_jobs(text,boolean,integer)', 'EXECUTE') as member,
        has_function_privilege('service_role', 'public.purge_expired_client_runtime_jobs(text,boolean,integer)', 'EXECUTE') as operator
    `);
    expect(privileges.rows[0]).toEqual({ member: false, operator: true });
    await expect(db.query(purge, ["tenant-a", false, 1001])).rejects.toThrow(/client_runtime_job_retention_invalid_input/);
    await expect(db.query(purge, ["missing-tenant", false, 10])).rejects.toThrow(/client_runtime_job_retention_tenant_not_found/);
    await expect(db.query(purge, ["tenant-invalid", false, 10])).rejects.toThrow(/client_runtime_job_retention_tenant_not_configured/);
    await db.exec(`
      create function reject_job_retention_audit() returns trigger language plpgsql as $$
      begin raise exception 'audit_unavailable'; end; $$;
      create trigger reject_job_retention_audit before insert on client_runtime_audit_events
        for each row execute function reject_job_retention_audit();
    `);
    await expect(db.query(purge, ["tenant-a", true, 100])).rejects.toThrow(/audit_unavailable/);
    expect((await db.query("select id from client_runtime_jobs where tenant_slug='tenant-a' and created_at <= now() - interval '35 days'")).rows).toHaveLength(1);
  } finally { await db.close(); }
});
