import { readFileSync } from "node:fs";
import { PGlite } from "@electric-sql/pglite";
import { expect, test } from "@playwright/test";

async function database() {
  const db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated; create role service_role;
    create table client_tenants (slug text primary key, retention_days integer not null);
    create table client_runtime_audit_events (
      id bigint generated by default as identity primary key,
      tenant_slug text not null, event_type text not null, metadata jsonb not null
    );
    create table client_room_conversations (
      id uuid primary key, tenant_slug text not null references client_tenants(slug) on delete cascade,
      title text not null default 'New chat', status text not null default 'active',
      created_at timestamptz not null default now(), updated_at timestamptz not null default now()
    );
    create table client_room_messages (
      id uuid primary key, tenant_slug text not null references client_tenants(slug) on delete cascade,
      conversation_id uuid not null references client_room_conversations(id) on delete cascade,
      content text not null, created_at timestamptz not null default now()
    );
    create table client_room_rounds (
      id uuid primary key, tenant_slug text not null references client_tenants(slug) on delete cascade,
      conversation_id uuid not null references client_room_conversations(id) on delete cascade,
      status text not null default 'queued', created_at timestamptz not null default now()
    );
    insert into client_tenants values ('tenant-a', 28), ('tenant-b', 14), ('tenant-invalid', 0);
    insert into client_room_conversations (id, tenant_slug, title, created_at, updated_at) values
      ('00000000-0000-4000-8000-000000000010', 'tenant-a', 'Expired and empty after cleanup', now() - interval '36 days', now() - interval '36 days'),
      ('00000000-0000-4000-8000-000000000020', 'tenant-a', 'Expired with recent child', now() - interval '40 days', now() - interval '36 days'),
      ('00000000-0000-4000-8000-000000000030', 'tenant-a', 'Recently active', now() - interval '60 days', now() - interval '2 days'),
      ('00000000-0000-4000-8000-000000000040', 'tenant-b', 'Shorter tenant retention', now() - interval '60 days', now() - interval '16 days');
    insert into client_room_messages (id, tenant_slug, conversation_id, content, created_at) values
      ('00000000-0000-4000-8000-000000000101', 'tenant-a', '00000000-0000-4000-8000-000000000010', 'expired child', now() - interval '36 days'),
      ('00000000-0000-4000-8000-000000000102', 'tenant-a', '00000000-0000-4000-8000-000000000020', 'recent child blocks parent purge', now() - interval '2 days'),
      ('00000000-0000-4000-8000-000000000103', 'tenant-a', '00000000-0000-4000-8000-000000000030', 'expired child of active conversation', now() - interval '36 days'),
      ('00000000-0000-4000-8000-000000000104', 'tenant-b', '00000000-0000-4000-8000-000000000040', 'in recovery window', now() - interval '16 days');
    insert into client_room_rounds (id, tenant_slug, conversation_id, status, created_at) values
      ('00000000-0000-4000-8000-000000000201', 'tenant-a', '00000000-0000-4000-8000-000000000010', 'succeeded', now() - interval '36 days'),
      ('00000000-0000-4000-8000-000000000203', 'tenant-a', '00000000-0000-4000-8000-000000000030', 'succeeded', now() - interval '36 days');
    create function client_member(text) returns boolean language sql stable as $$
      select $1 in ('tenant-a', 'tenant-b', 'tenant-invalid')
    $$;
    create function client_tenant_retention_days(text) returns integer
      language sql stable security definer as $$
        select retention_days from client_tenants where slug = $1 and client_member($1)
      $$;
    grant execute on function client_tenant_retention_days(text) to authenticated, service_role;
    alter table client_room_conversations enable row level security;
    alter table client_room_messages enable row level security;
    alter table client_room_rounds enable row level security;
    create policy client_room_conversations_member_select on client_room_conversations
      for select to authenticated using (client_member(tenant_slug));
    create policy client_room_messages_member_select on client_room_messages
      for select to authenticated using (client_member(tenant_slug));
    create policy client_room_rounds_member_select on client_room_rounds
      for select to authenticated using (client_member(tenant_slug));
    create policy client_room_conversations_member_update on client_room_conversations
      for update to authenticated using (client_member(tenant_slug)) with check (client_member(tenant_slug));
    create policy client_room_messages_member_update on client_room_messages
      for update to authenticated using (client_member(tenant_slug)) with check (client_member(tenant_slug));
    create policy client_room_rounds_member_update on client_room_rounds
      for update to authenticated using (client_member(tenant_slug)) with check (client_member(tenant_slug));
    create policy client_room_conversations_member_insert on client_room_conversations
      for insert to authenticated with check (client_member(tenant_slug));
    create policy client_room_messages_member_insert on client_room_messages
      for insert to authenticated with check (client_member(tenant_slug));
    create policy client_room_rounds_member_insert on client_room_rounds
      for insert to authenticated with check (client_member(tenant_slug));
    grant select, insert, update, delete on client_room_conversations, client_room_messages, client_room_rounds to authenticated;
  `);
  await db.exec(readFileSync("product-experience/supabase-client-room-retention-28.sql", "utf8"));
  await db.exec(readFileSync("product-experience/supabase-client-room-retention-28.sql", "utf8"));
  return db;
}

const purge = "select public.purge_expired_client_room_records($1, $2, $3) as result";

test("room reads expire by item age and tenant-specific retention without resetting old message clocks", async () => {
  const db = await database();
  try {
    await db.exec("set role authenticated");
    expect((await db.query("select id from client_room_conversations where tenant_slug='tenant-a' order by id")).rows.map((row) => row.id))
      .toEqual(["00000000-0000-4000-8000-000000000030"]);
    expect((await db.query("select id from client_room_messages where tenant_slug='tenant-a' order by id")).rows.map((row) => row.id))
      .toEqual(["00000000-0000-4000-8000-000000000102"]);
    expect((await db.query("select id from client_room_messages where tenant_slug='tenant-b'")).rows).toHaveLength(0);
    const resurrection = await db.query("update client_room_conversations set status='archived' where id='00000000-0000-4000-8000-000000000020' returning id");
    expect(resurrection.rows).toHaveLength(0);
  } finally { await db.close(); }
});

test("new room writes cannot backdate and cannot append to an expired conversation", async () => {
  const db = await database();
  try {
    await db.exec("set role authenticated");
    await db.query(`insert into client_room_conversations (id, tenant_slug, title, created_at, updated_at) values
      ('00000000-0000-4000-8000-000000000050', 'tenant-a', 'new', now() - interval '90 days', now() - interval '90 days')`);
    const created = await db.query<{ recent: boolean }>("select created_at > now() - interval '1 minute' as recent from client_room_conversations where id='00000000-0000-4000-8000-000000000050'");
    expect(created.rows[0].recent).toBe(true);
    await expect(db.query(`insert into client_room_messages (id, tenant_slug, conversation_id, content) values
      ('00000000-0000-4000-8000-000000000051', 'tenant-a', '00000000-0000-4000-8000-000000000020', 'must reject')`))
      .rejects.toThrow(/client_room_conversation_expired_or_foreign/);
    await db.query(`insert into client_room_messages (id, tenant_slug, conversation_id, content, created_at) values
      ('00000000-0000-4000-8000-000000000052', 'tenant-a', '00000000-0000-4000-8000-000000000050', 'new', now() - interval '90 days')`);
    const messageCreated = await db.query<{ recent: boolean }>("select created_at > now() - interval '1 minute' as recent from client_room_messages where id='00000000-0000-4000-8000-000000000052'");
    expect(messageCreated.rows[0].recent).toBe(true);
  } finally { await db.close(); }
});

test("room purge is child-first, bounded, tenant-scoped, and defers a parent with a recoverable child", async () => {
  const db = await database();
  try {
    const preview = await db.query<{ result: Record<string, any> }>(purge, ["tenant-a", false, 1]);
    expect(preview.rows[0].result).toMatchObject({
      candidates: { messages: 2, rounds: 2, conversations: 2 },
      deleted: { messages: 0, rounds: 0, conversations: 0 }, applied: false,
    });
    const first = await db.query<{ result: Record<string, any> }>(purge, ["tenant-a", true, 1]);
    expect(first.rows[0].result.deleted).toEqual({ messages: 1, rounds: 1, conversations: 1 });
    expect((await db.query("select id from client_room_messages where id='00000000-0000-4000-8000-000000000102'")).rows).toHaveLength(1);
    expect((await db.query("select id from client_room_conversations where id='00000000-0000-4000-8000-000000000020'")).rows).toHaveLength(1);
    const second = await db.query<{ result: Record<string, any> }>(purge, ["tenant-a", true, 10]);
    expect(second.rows[0].result.deleted).toEqual({ messages: 1, rounds: 1, conversations: 0 });
    expect((await db.query("select id from client_room_conversations where tenant_slug='tenant-b'")).rows).toHaveLength(1);
    expect((await db.query("select event_type from client_runtime_audit_events")).rows).toHaveLength(2);
  } finally { await db.close(); }
});

test("room purge is service-role-only and rolls back if its audit cannot be written", async () => {
  const db = await database();
  try {
    const privileges = await db.query<{ member: boolean; operator: boolean }>(`
      select has_function_privilege('authenticated', 'public.purge_expired_client_room_records(text,boolean,integer)', 'EXECUTE') as member,
        has_function_privilege('service_role', 'public.purge_expired_client_room_records(text,boolean,integer)', 'EXECUTE') as operator
    `);
    expect(privileges.rows[0]).toEqual({ member: false, operator: true });
    await expect(db.query(purge, ["tenant-a", false, 1001])).rejects.toThrow(/client_room_retention_invalid_input/);
    await expect(db.query(purge, ["missing-tenant", false, 10])).rejects.toThrow(/client_room_retention_tenant_not_found/);
    await expect(db.query(purge, ["tenant-invalid", false, 10])).rejects.toThrow(/client_room_retention_tenant_not_configured/);
    await db.exec(`
      create function reject_room_retention_audit() returns trigger language plpgsql as $$
      begin raise exception 'audit_unavailable'; end; $$;
      create trigger reject_room_retention_audit before insert on client_runtime_audit_events
        for each row execute function reject_room_retention_audit();
    `);
    await expect(db.query(purge, ["tenant-a", true, 100])).rejects.toThrow(/audit_unavailable/);
    expect((await db.query("select id from client_room_conversations where id='00000000-0000-4000-8000-000000000010'")).rows).toHaveLength(1);
    expect((await db.query("select id from client_room_messages where id='00000000-0000-4000-8000-000000000101'")).rows).toHaveLength(1);
  } finally { await db.close(); }
});
