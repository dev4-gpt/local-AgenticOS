// Real PostgreSQL (PGlite) tests for product-experience/supabase-client-adapter-model-grants.sql (ADR-020).
// Tenants, users and tokens are made up inside each test; nothing real is used.
const HOST_SQL = readFileSync("product-experience/supabase-client-adapter-host.sql", "utf8");
const BUDGET_SQL = readFileSync("product-experience/supabase-client-adapter-budget.sql", "utf8");
const GRANTS_SQL = readFileSync("product-experience/supabase-client-adapter-model-grants.sql", "utf8");
const OWNER = "00000000-0000-4000-8000-0000000000a1";
const WORKER = "test-worker-token-aaaaaaaaaaaaaaaaaaaa";
const MODEL = "groq:openai/gpt-oss-120b";
const sha = (text: string) => createHash("sha256").update(text).digest("hex");

async function freshDb() {
  const db = new PGlite({ extensions: { pgcrypto } });
  await db.exec(`
    create schema extensions; create extension pgcrypto with schema extensions;
    create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth;
    create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    create table auth.users(id uuid primary key);
    create table public.client_tenants(slug text primary key, status text not null default 'active', worker_token_hash text);
    create table public.client_memberships(
      tenant_slug text not null references public.client_tenants(slug) on delete cascade,
      user_id uuid not null references auth.users(id), role text not null, status text not null default 'active',
      primary key (tenant_slug, user_id));
    create function public.client_member(p_tenant_slug text) returns boolean language sql stable security definer set search_path = public as $$
      select exists (select 1 from public.client_memberships where tenant_slug = p_tenant_slug and user_id = auth.uid() and status = 'active') $$;
    create table public.client_runtime_budget_ledger (
      id bigint generated by default as identity primary key,
      tenant_slug text not null references public.client_tenants(slug) on delete cascade,
      job_id uuid, provider text not null, model text,
      amount_micros bigint not null check (amount_micros >= 0),
      usage_metadata jsonb not null default '{}'::jsonb,
      created_at timestamptz not null default now());
    grant usage on schema public, auth, extensions to anon, authenticated, service_role;
    grant execute on function public.client_member(text) to authenticated;
    insert into auth.users values ('${OWNER}');
    insert into public.client_tenants(slug, worker_token_hash) values ('tenant-a', '${sha(WORKER)}'), ('tenant-b', '${sha(WORKER)}');
    insert into public.client_memberships values ('tenant-a', '${OWNER}', 'owner', 'active'), ('tenant-b', '${OWNER}', 'owner', 'active');
  `);
  await db.exec(HOST_SQL);
  await db.exec(BUDGET_SQL);
  await db.exec(GRANTS_SQL);
  await db.exec(GRANTS_SQL); // safe to repeat
  await db.query("select set_config('request.jwt.claim.sub',$1,false)", [OWNER]);
  await db.exec("set role authenticated");
  for (const [tenant, adapter] of [["tenant-a", "forge"], ["tenant-a", "knowledge"], ["tenant-b", "forge"]]) {
    await db.query(
      "insert into public.client_adapter_registry (tenant_slug, adapter_id, display_name, contract_version, manifest_sha256) values ($1,$2,$2,'h1',$3)",
      [tenant, adapter, "a".repeat(64)],
    );
  }
  await db.exec("reset role");
  await db.exec("update public.client_adapter_registry set state = 'enabled'");
  return db;
}

type Open = { tenant?: string; token?: string; adapter?: string; task?: string; grant?: string; allowed?: string[]; maxCalls?: number; maxTokens?: number; expiresIn?: string };
async function open(db: PGlite, o: Open = {}) {
  await db.exec("reset role; set role anon");
  const r = await db.query<{ s: string }>(
    `select public.client_adapter_model_grant_open($1,$2,$3,$4,$5::uuid,$6::text[],$7,$8, now() + $9::interval) as s`,
    [o.tenant ?? "tenant-a", o.token ?? WORKER, o.adapter ?? "forge", o.task ?? "task-1", o.grant ?? GRANT, o.allowed ?? [MODEL], o.maxCalls ?? 3, o.maxTokens ?? 1000, o.expiresIn ?? "10 minutes"],
  );
  return r.rows[0].s;
}

type Begin = { tenant?: string; token?: string; adapter?: string; task?: string; grant?: string; provider?: string; model?: string; tokens?: number; perAdapter?: number; perTenant?: number };
async function begin(db: PGlite, o: Begin = {}) {
  await db.exec("reset role; set role anon");
  const r = await db.query<{ s: { status: string; seq?: number } }>(
    "select public.client_adapter_model_call_begin($1,$2,$3,$4,$5::uuid,$6,$7,$8,$9,$10) as s",
    [o.tenant ?? "tenant-a", o.token ?? WORKER, o.adapter ?? "forge", o.task ?? "task-1", o.grant ?? GRANT, o.provider ?? "groq", o.model ?? "openai/gpt-oss-120b", o.tokens ?? 100, o.perAdapter ?? 30, o.perTenant ?? 60],
  );
  return r.rows[0].s;
}

async function finish(db: PGlite, seq: number, actual: number, o: { tenant?: string; token?: string; grant?: string } = {}) {
  await db.exec("reset role; set role anon");
  return (await db.query<{ s: string }>("select public.client_adapter_model_call_finish($1,$2,$3::uuid,$4,$5) as s", [o.tenant ?? "tenant-a", o.token ?? WORKER, o.grant ?? GRANT, seq, actual])).rows[0].s;
}

async function bind(db: PGlite, adapterTask: string, o: { tenant?: string; token?: string; grant?: string } = {}) {
  await db.exec("reset role; set role anon");
  return (await db.query<{ s: string }>("select public.client_adapter_model_grant_bind($1,$2,$3::uuid,$4) as s", [o.tenant ?? "tenant-a", o.token ?? WORKER, o.grant ?? GRANT, adapterTask])).rows[0].s;
}

async function close(db: PGlite, task = "wf-task-1", adapter = "forge", tenant = "tenant-a") {
  await db.exec("reset role; set role service_role");
  return (await db.query<{ s: string }>("select public.client_adapter_model_grant_close($1,$2,$3) as s", [tenant, adapter, task])).rows[0].s;
}

async function grantRow(db: PGlite, grant = GRANT) {
  await db.exec("reset role");
  return (await db.query<{ calls_used: number; tokens_used: string | number; closed_at: string | null }>("select calls_used, tokens_used, closed_at from public.client_adapter_model_grants where grant_id = $1", [grant])).rows[0];
}

const GRANT = "11111111-1111-4111-8111-111111111111";

test("a grant opens once per task; the same grant id repeats harmlessly", async () => {
  const db = await freshDb();
  expect(await open(db)).toBe("opened");
  expect(await open(db)).toBe("already_open");
  expect(await open(db, { grant: randomUUID() })).toBe("task_has_grant");
  // the same grant id cannot be reused for another task
  expect(await open(db, { task: "task-2" })).toBe("task_has_grant");
  expect(await open(db, { task: "task-2", grant: randomUUID() })).toBe("opened");
});

test("opening needs the tenant's worker token and a ready adapter", async () => {
  const db = await freshDb();
  expect(await open(db, { token: "wrong-worker-token-bbbbbbbbbbbbbbbbbb" })).toBe("refused");
  expect(await open(db, { token: "short" })).toBe("refused");
  expect(await open(db, { tenant: "tenant-zz" })).toBe("refused");
  expect(await open(db, { adapter: "unknown-adapter" })).toBe("adapter_not_ready");
  for (const state of ["disabled", "suspended"]) {
    await db.exec("reset role");
    await db.query("update public.client_adapter_registry set state = $1 where adapter_id = 'forge' and tenant_slug = 'tenant-a'", [state]);
    expect(await open(db)).toBe("adapter_not_ready");
  }
  await db.exec("reset role");
  await db.exec("update public.client_adapter_registry set state = 'preview' where adapter_id = 'forge'");
  expect(await open(db)).toBe("opened");
});

test("opening refuses bad limits, lists and lifetimes", async () => {
  const db = await freshDb();
  const bad: Open[] = [
    { maxCalls: 0 }, { maxCalls: 101 }, { maxTokens: 0 }, { maxTokens: 1_000_001 },
    { allowed: [] }, { allowed: Array.from({ length: 21 }, (_, i) => `groq:m${i}`) }, { allowed: ["no-colon"] }, { allowed: ["Groq:model"] }, { allowed: ["groq:has space"] },
    { expiresIn: "-1 second" }, { expiresIn: "0 seconds" }, { expiresIn: "17 minutes" },
    { task: "" }, { task: "t".repeat(121) }, { task: "bad/task" }, { adapter: "X" },
  ];
  for (const change of bad) expect(await open(db, change), JSON.stringify(change)).toBe("invalid");
  expect(await open(db, { maxCalls: 100, maxTokens: 1_000_000, expiresIn: "15 minutes", task: "t".repeat(120) })).toBe("opened");
});

test("each call is counted in order and held against the grant's token limit until finished", async () => {
  const db = await freshDb();
  await open(db, { maxCalls: 3, maxTokens: 1000 });
  expect(await begin(db, { tokens: 600 })).toEqual({ status: "ok", seq: 1 });
  expect(await begin(db, { tokens: 500 })).toEqual({ status: "token_limit" }); // 600 held + 500 > 1000
  expect(await finish(db, 1, 200)).toBe("finished");
  expect(Number((await grantRow(db)).tokens_used)).toBe(200);
  expect(await begin(db, { tokens: 800 })).toEqual({ status: "ok", seq: 2 }); // 200 + 800 = 1000 exactly fits
  expect(await finish(db, 2, 0)).toBe("finished");
  expect(await begin(db, { tokens: 1 })).toEqual({ status: "ok", seq: 3 });
  expect(await begin(db, { tokens: 1 })).toEqual({ status: "call_limit" });
  const row = await grantRow(db);
  expect(row.calls_used).toBe(3);
});

test("a refused call is not counted", async () => {
  const db = await freshDb();
  await open(db, { maxCalls: 2 });
  expect((await begin(db, { model: "other-model" })).status).toBe("model_not_allowed");
  expect((await begin(db, { tokens: 5000 })).status).toBe("token_limit");
  expect((await grantRow(db)).calls_used).toBe(0);
  expect(await begin(db)).toEqual({ status: "ok", seq: 1 });
});

test("finishing is once per call; a repeat with another number is a conflict", async () => {
  const db = await freshDb();
  await open(db);
  await begin(db, { tokens: 300 });
  expect(await finish(db, 1, 120)).toBe("finished");
  expect(await finish(db, 1, 120)).toBe("already_finished");
  expect(await finish(db, 1, 999)).toBe("conflict");
  expect(Number((await grantRow(db)).tokens_used)).toBe(120);
  expect(await finish(db, 2, 1)).toBe("not_found");
  expect(await finish(db, 1, 1, { grant: randomUUID() })).toBe("not_found");
  expect(await finish(db, 1, 1, { tenant: "tenant-b" })).toBe("not_found");
  expect(await finish(db, 1, -1)).toBe("invalid");
  expect(await finish(db, 1, 1_000_001)).toBe("invalid");
  expect(await finish(db, 1, 1, { token: "wrong-worker-token-bbbbbbbbbbbbbbbbbb" })).toBe("refused");
});

test("a call is refused for the wrong task, adapter or tenant, a closed or expired grant, or a stopped adapter", async () => {
  const db = await freshDb();
  await open(db);
  expect((await begin(db, { task: "task-9" })).status).toBe("grant_not_found");
  expect((await begin(db, { adapter: "knowledge" })).status).toBe("grant_not_found");
  expect((await begin(db, { tenant: "tenant-b" })).status).toBe("grant_not_found");
  expect((await begin(db, { grant: randomUUID() })).status).toBe("grant_not_found");
  expect((await begin(db, { token: "wrong-worker-token-bbbbbbbbbbbbbbbbbb" })).status).toBe("refused");
  expect((await begin(db, { tokens: 0 })).status).toBe("invalid");
  expect((await begin(db, { perAdapter: 0 })).status).toBe("invalid");
  expect((await begin(db, { perTenant: 601 })).status).toBe("invalid");

  await db.exec("reset role");
  await db.exec("update public.client_adapter_registry set state = 'suspended' where tenant_slug = 'tenant-a' and adapter_id = 'forge'");
  expect((await begin(db)).status).toBe("adapter_not_ready");
  await db.exec("reset role");
  await db.exec("update public.client_adapter_registry set state = 'enabled'");

  await db.exec(`update public.client_adapter_model_grants set expires_at = now() - interval '1 second' where grant_id = '${GRANT}'`);
  expect((await begin(db)).status).toBe("grant_expired");
  await db.exec("reset role");
  await db.exec(`update public.client_adapter_model_grants set expires_at = now() + interval '5 minutes' where grant_id = '${GRANT}'`);

  expect(await close(db)).toBe("not_found"); // not bound yet: the grant ends when it expires
  expect(await bind(db, "wf-task-1")).toBe("bound");
  expect(await close(db, "wf-task-1", "knowledge")).toBe("not_found");
  expect(await close(db, "wf-task-1", "forge", "tenant-b")).toBe("not_found");
  expect(await close(db)).toBe("closed");
  expect(await close(db)).toBe("already_closed");
  expect(await close(db, "task-9")).toBe("not_found");
  expect((await begin(db)).status).toBe("grant_closed");
});

test("the adapter's task id is recorded once and must be unique for that adapter", async () => {
  const db = await freshDb();
  await open(db);
  const other = "33333333-3333-4333-8333-333333333333";
  await open(db, { task: "task-2", grant: other });
  expect(await bind(db, "bad/id")).toBe("invalid");
  expect(await bind(db, "wf-1", { token: "wrong-worker-token-bbbbbbbbbbbbbbbbbb" })).toBe("refused");
  expect(await bind(db, "wf-1", { tenant: "tenant-b" })).toBe("not_found");
  expect(await bind(db, "wf-1", { grant: randomUUID() })).toBe("not_found");
  expect(await bind(db, "wf-1")).toBe("bound");
  expect(await bind(db, "wf-1")).toBe("already_bound");
  expect(await bind(db, "wf-2")).toBe("conflict");
  expect(await bind(db, "wf-1", { grant: other })).toBe("conflict");
  expect(await bind(db, "wf-2", { grant: other })).toBe("bound");
});

test("per-minute limits count the adapter's calls and the whole client's calls", async () => {
  const db = await freshDb();
  await open(db, { maxCalls: 10, maxTokens: 100_000 });
  await open(db, { adapter: "knowledge", grant: "22222222-2222-4222-8222-222222222222", maxCalls: 10, maxTokens: 100_000 });
  expect((await begin(db, { perAdapter: 2 })).status).toBe("ok");
  expect((await begin(db, { perAdapter: 2 })).status).toBe("ok");
  expect((await begin(db, { perAdapter: 2 })).status).toBe("adapter_rate_limited");
  // the other adapter has its own limit, but the client's limit counts both
  const other = { adapter: "knowledge", grant: "22222222-2222-4222-8222-222222222222" };
  expect((await begin(db, { ...other, perAdapter: 2, perTenant: 3 })).status).toBe("ok");
  expect((await begin(db, { ...other, perAdapter: 2, perTenant: 3 })).status).toBe("tenant_rate_limited");
  // calls older than a minute no longer count
  await db.exec("reset role");
  await db.exec("update public.client_adapter_model_calls set created_at = now() - interval '61 seconds'");
  expect((await begin(db, { perAdapter: 2, perTenant: 3 })).status).toBe("ok");
});

test("rows are hidden from members and anon; only the defined functions touch them", async () => {
  const db = await freshDb();
  await open(db);
  await begin(db);
  for (const role of ["anon", "authenticated"]) {
    await db.exec(`reset role; set role ${role}`);
    await expect(db.query("select * from public.client_adapter_model_grants")).rejects.toThrow(/permission denied/);
    await expect(db.query("select * from public.client_adapter_model_calls")).rejects.toThrow(/permission denied/);
    await expect(db.query("select public.client_adapter_model_grant_close('tenant-a','forge','task-1')")).rejects.toThrow(/permission denied/);
    await expect(db.query("select public.client_adapter_purge_model_grants()")).rejects.toThrow(/permission denied/);
  }
  await db.exec("reset role; set role authenticated");
  await expect(db.query(`select public.client_adapter_model_call_begin('tenant-a','${WORKER}','forge','task-1','${GRANT}'::uuid,'groq','openai/gpt-oss-120b',1,30,60)`)).rejects.toThrow(/permission denied/);
  await expect(db.query(`select public.client_adapter_model_grant_bind('tenant-a','${WORKER}','${GRANT}'::uuid,'wf-1')`)).rejects.toThrow(/permission denied/);
  await expect(db.query(`select public.client_adapter_model_grant_open('tenant-a','${WORKER}','forge','task-7','${randomUUID()}'::uuid,array['${MODEL}'],1,1,now() + interval '1 minute')`)).rejects.toThrow(/permission denied/);
});

test("the purge removes grants and their calls 35 days after opening, bounded and safe to repeat", async () => {
  const db = await freshDb();
  for (let i = 1; i <= 3; i += 1) {
    const grant = randomUUID();
    await open(db, { task: `task-${i}`, grant });
    await begin(db, { task: `task-${i}`, grant });
  }
  await db.exec("reset role");
  await db.exec("update public.client_adapter_model_grants set created_at = now() - interval '36 days' where task_id in ('task-1','task-2')");
  await db.exec("update public.client_adapter_model_grants set created_at = now() - interval '34 days' where task_id = 'task-3'");
  await db.exec("set role service_role");
  expect((await db.query<{ n: number }>("select public.client_adapter_purge_model_grants(1) as n")).rows[0].n).toBe(1);
  expect((await db.query<{ n: number }>("select public.client_adapter_purge_model_grants() as n")).rows[0].n).toBe(1);
  expect((await db.query<{ n: number }>("select public.client_adapter_purge_model_grants() as n")).rows[0].n).toBe(0);
  await db.exec("reset role");
  expect((await db.query<{ n: number }>("select count(*)::int as n from public.client_adapter_model_grants")).rows[0].n).toBe(1);
  expect((await db.query<{ n: number }>("select count(*)::int as n from public.client_adapter_model_calls")).rows[0].n).toBe(1);
});

