import { readFileSync } from "node:fs";
import { PGlite } from "@electric-sql/pglite";
import { expect, test } from "@playwright/test";

const expiredSwarm = "00000000-0000-4000-8000-000000000001";
const activeSwarm = "00000000-0000-4000-8000-000000000002";
const oldAgent = "00000000-0000-4000-8000-000000000011";
const recentAgent = "00000000-0000-4000-8000-000000000012";

async function database() {
  const db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated; create role service_role;
    create table public.client_tenants(slug text primary key,retention_days integer not null,status text not null default 'active');
    create table public.client_runtime_audit_events(id bigint generated by default as identity primary key,tenant_slug text not null,event_type text not null,metadata jsonb not null);
    create table public.client_runtime_jobs(id uuid primary key);
    create table public.client_runtime_artifacts(id uuid primary key);
    create table public.client_ruflo_swarms(
      id uuid primary key,tenant_slug text not null references public.client_tenants(slug) on delete cascade,created_by uuid not null,
      objective text not null,topology text not null default 'hierarchical',preset text not null default 'seo',status text not null default 'queued',
      job_id uuid references public.client_runtime_jobs(id) on delete set null,provider text,model text,agent_count integer not null default 0,
      completed_count integer not null default 0,failed_count integer not null default 0,report text,
      report_artifact_id uuid references public.client_runtime_artifacts(id) on delete set null,cost_micros bigint not null default 0,error_code text,
      created_at timestamptz not null default now(),updated_at timestamptz not null default now());
    create table public.client_ruflo_agents(
      id uuid primary key,tenant_slug text not null references public.client_tenants(slug) on delete cascade,
      swarm_id uuid not null references public.client_ruflo_swarms(id) on delete cascade,agent_type text not null,name text not null,
      task text not null default '',position integer not null default 0,status text not null default 'idle',output text,error_code text,
      cost_micros bigint not null default 0,started_at timestamptz,finished_at timestamptz,created_at timestamptz not null default now(),
      unique(tenant_slug,swarm_id,name));
    insert into public.client_tenants values ('tenant-a',28,'active'),('tenant-b',14,'active');
    insert into public.client_ruflo_swarms(id,tenant_slug,created_by,objective,created_at,updated_at) values
      ('${expiredSwarm}','tenant-a','00000000-0000-4000-8000-000000000020','expired parent',now()-interval '40 days',now()-interval '40 days'),
      ('${activeSwarm}','tenant-a','00000000-0000-4000-8000-000000000020','active parent',now()-interval '2 days',now()-interval '2 days');
    insert into public.client_ruflo_agents(id,tenant_slug,swarm_id,agent_type,name,created_at) values
      ('${oldAgent}','tenant-a','${expiredSwarm}','worker','old',now()-interval '40 days'),
      ('${recentAgent}','tenant-a','${expiredSwarm}','worker','recent-child',now()-interval '10 days');
    create function public.client_member(text) returns boolean language sql stable security definer as $$
      select exists(select 1 from public.client_tenants where slug=$1 and status='active')
    $$;
    grant execute on function public.client_member(text) to authenticated;
    alter table public.client_ruflo_swarms enable row level security;
    alter table public.client_ruflo_agents enable row level security;
    create policy client_ruflo_swarms_member_select on public.client_ruflo_swarms for select to authenticated using(client_member(tenant_slug));
    create policy client_ruflo_agents_member_select on public.client_ruflo_agents for select to authenticated using(client_member(tenant_slug));
    create policy client_ruflo_swarms_member_insert on public.client_ruflo_swarms for insert to authenticated with check(client_member(tenant_slug));
    create policy client_ruflo_agents_member_insert on public.client_ruflo_agents for insert to authenticated with check(client_member(tenant_slug));
    create policy client_ruflo_swarms_member_update on public.client_ruflo_swarms for update to authenticated using(client_member(tenant_slug)) with check(client_member(tenant_slug));
    create policy client_ruflo_agents_member_update on public.client_ruflo_agents for update to authenticated using(client_member(tenant_slug)) with check(client_member(tenant_slug));
    create policy client_ruflo_swarms_member_delete on public.client_ruflo_swarms for delete to authenticated using(client_member(tenant_slug));
    create policy client_ruflo_agents_member_delete on public.client_ruflo_agents for delete to authenticated using(client_member(tenant_slug));
    grant select,insert,update,delete on public.client_ruflo_swarms,public.client_ruflo_agents to authenticated;
  `);
  const migration = readFileSync("product-experience/supabase-client-ruflo-retention-28.sql", "utf8");
  await db.exec(migration);
  await db.exec(migration);
  return db;
}

test("Ruflo expiry backfill hides expired rows and stays idempotent", async () => {
  const db = await database();
  try {
    await db.exec("set role authenticated");
    expect((await db.query("select id from public.client_ruflo_swarms order by id")).rows.map((row) => row.id)).toEqual([activeSwarm]);
    expect((await db.query("select id from public.client_ruflo_agents")).rows.map((row) => row.id)).toEqual([recentAgent]);
    const lateWrite = await db.query("update public.client_ruflo_agents set output='late worker output' where id=$1", [oldAgent]);
    expect(lateWrite.rowCount).toBe(0);
  } finally { await db.close(); }
});

test("new Ruflo records get a fixed tenant expiry and cannot attach to an expired swarm", async () => {
  const db = await database();
  try {
    await db.exec("set role authenticated");
    await db.query(`insert into public.client_ruflo_agents(id,tenant_slug,swarm_id,agent_type,name,retention_expires_at)
      values ('00000000-0000-4000-8000-000000000013','tenant-a',$1,'worker','fresh',now()+interval '90 days')`, [activeSwarm]);
    const inserted = await db.query<{ valid: boolean }>(`select retention_expires_at<=created_at+interval '28 days' valid
      from public.client_ruflo_agents where name='fresh'`);
    expect(inserted.rows[0]?.valid).toBe(true);
    await expect(db.query(`insert into public.client_ruflo_agents(id,tenant_slug,swarm_id,agent_type,name)
      values ('00000000-0000-4000-8000-000000000014','tenant-a',$1,'worker','orphan')`, [expiredSwarm]))
      .rejects.toThrow(/ruflo_swarm_expired_or_foreign/);
    await expect(db.query(`update public.client_ruflo_agents set retention_expires_at=now()+interval '90 days' where name='fresh'`))
      .rejects.toThrow(/ruflo_retention_immutable/);
  } finally { await db.close(); }
});

test("bounded purge removes due agents first and defers a parent with a younger child", async () => {
  const db = await database();
  try {
    const preview = await db.query<{ result: { deleted: { agents: number; swarms: number } } }>(
      "select public.purge_expired_client_ruflo_records('tenant-a',false,1) result");
    expect(preview.rows[0]?.result.deleted).toEqual({ agents: 0, swarms: 0 });
    const applied = await db.query<{ result: { deleted: { agents: number; swarms: number } } }>(
      "select public.purge_expired_client_ruflo_records('tenant-a',true,1) result");
    expect(applied.rows[0]?.result.deleted).toEqual({ agents: 1, swarms: 0 });
    const remaining = await db.query("select id from public.client_ruflo_swarms where id=$1", [expiredSwarm]);
    expect(remaining.rows).toHaveLength(1);
    const audit = await db.query("select event_type,metadata from public.client_runtime_audit_events");
    expect(audit.rows).toHaveLength(1);
    expect(audit.rows[0]?.event_type).toBe("tenant.ruflo.retention_purged");
  } finally { await db.close(); }
});

test("purge is service-role-only and rolls back content removal if audit recording fails", async () => {
  const db = await database();
  try {
    const privileges = await db.query<{ member: boolean; anonymous: boolean; service: boolean }>(`
      select has_function_privilege('authenticated','public.purge_expired_client_ruflo_records(text,boolean,integer)','execute') member,
        has_function_privilege('anon','public.purge_expired_client_ruflo_records(text,boolean,integer)','execute') anonymous,
        has_function_privilege('service_role','public.purge_expired_client_ruflo_records(text,boolean,integer)','execute') service
    `);
    expect(privileges.rows[0]).toEqual({ member: false, anonymous: false, service: true });
    await db.exec(`
      create function public.reject_ruflo_audit() returns trigger language plpgsql as $$
      begin raise exception 'audit unavailable'; end $$;
      create trigger reject_ruflo_audit before insert on public.client_runtime_audit_events
        for each row execute function public.reject_ruflo_audit();
    `);
    await expect(db.query("select public.purge_expired_client_ruflo_records('tenant-a',true,1)"))
      .rejects.toThrow(/audit unavailable/);
    expect((await db.query("select id from public.client_ruflo_agents where id=$1", [oldAgent])).rows).toHaveLength(1);
    expect((await db.query("select id from public.client_runtime_audit_events")).rows).toHaveLength(0);
  } finally { await db.close(); }
});
