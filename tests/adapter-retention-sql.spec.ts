test("expired rows disappear from members straight away but stay in the table for the recovery days", async () => {
  const db = await freshDb();
  try {
    await register(db, "tenant-a", "forge");
    const chain = await addSharedChain(db, "forge", "shared fact", "idem-key-s1");
    await addProvenance(db, chain.sharedId, "forge");
    await asUser(db, USER.memberA);
    expect((await db.query("select 1 from public.client_adapter_memory_items where namespace = 'shared'")).rows).toHaveLength(1);
    await asUser(db, USER.adminA);
    expect((await db.query("select 1 from public.client_adapter_memory_items")).rows).toHaveLength(2);
    expect((await db.query("select 1 from public.client_adapter_memory_promotions")).rows).toHaveLength(1);
    expect((await db.query("select 1 from public.client_adapter_memory_provenance")).rows).toHaveLength(2); // the source note and the shared note

    await age(db, 29); // expired one day ago, inside the seven recovery days
    await asUser(db, USER.memberA);
    expect((await db.query("select 1 from public.client_adapter_memory_items")).rows).toHaveLength(0);
    await asUser(db, USER.adminA);
    for (const table of TABLES.slice(0, 3)) expect((await db.query(`select 1 from public.${table}`)).rows, table).toHaveLength(0);
    expect(await count(db, "client_adapter_memory_items")).toBe(2);
    // nothing is due yet, so a purge removes and erases nothing
    const result = await purge(db);
    expect(result.expiredOrPurgeDue.items).toBe(0);
    expect(result.notesErased).toBe(0);
    expect(await count(db, "client_adapter_memory_items", "status = 'active'")).toBe(2);
  } finally {
    await db.close();
  }
});

