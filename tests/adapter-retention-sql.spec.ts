test("seven days after expiry the purge erases notes and removes rows; a dry run changes nothing", async () => {
  const db = await freshDb();
  try {
    await register(db, "tenant-a", "forge");
    const chain = await addSharedChain(db, "forge", "secret client detail", "idem-key-p1");
    await addProvenance(db, chain.sharedId, "forge");
    await asService(db);
    await db.query("insert into public.client_adapter_approvals (tenant_slug, adapter_id, action_kind, action_hash, destination, policy_version, requested_by, expires_at) values ('tenant-a','forge','publish',$1,'dest','p1',$2, now() + interval '90 days')", [H("1"), USER.memberA]);
    await db.query("insert into public.client_adapter_budget_events (tenant_slug, adapter_id, task_id, kind, amount_micros, provider, idempotency_key) values ('tenant-a','forge','t1','reserve',5,'p','idem-key-b1')");
    await age(db, 36); // expired 8 days ago

    const dry = await purge(db, "tenant-a", false);
    expect(dry.applied).toBe(false);
    expect(dry.expiredOrPurgeDue).toMatchObject({ items: 2, promotions: 1, provenance: 2, approvals: 1, budgetEvents: 1 });
    expect(await count(db, "client_adapter_memory_items")).toBe(2);
    expect(await count(db, "client_adapter_memory_items", "content = 'secret client detail'")).toBe(2);

    const done = await purge(db);
    expect(done.applied).toBe(true);
    expect(done.deleted).toMatchObject({ provenance: 2, budgetEvents: 1, approvals: 1, sharedNotes: 1, promotions: 1, privateNotes: 1 });
    for (const table of TABLES) expect(await count(db, table), table).toBe(0);
    await asOwner(db);
    const audit = await db.query<{ metadata: Record<string, any> }>("select metadata from public.client_runtime_audit_events where event_type = 'tenant.adapter.retention_purged'");
    expect(audit.rows).toHaveLength(1);
    expect(audit.rows[0].metadata).toMatchObject({ retentionDays: 28, recoveryDays: 7, purgeAfterDays: 35 });
    // the shared note's removal was announced to adapters
    const events = await db.query<{ event_type: string; payload: Record<string, unknown> }>("select event_type, payload from public.client_adapter_outbox where event_type = 'memory.tombstoned'");
    expect(events.rows).toHaveLength(1);
    expect(events.rows[0].payload).toMatchObject({ item_id: chain.sharedId, reason: "retention_expired" });
  } finally {
    await db.close();
  }
});

test("a private note and its promotion are erased when due even while a newer shared note still points at them, and removed once it goes", async () => {
  const db = await freshDb();
  try {
    await register(db, "tenant-a", "forge");
    const chain = await addSharedChain(db, "forge", "chain content", "idem-key-c1");
    await age(db, 36, [chain.privateId, chain.promotionId]); // those two are due; the shared note is not
    const first = await purge(db);
    expect(first.notesErased).toBe(1);
    expect(first.promotionNotesCleared).toBe(1);
    expect(first.deleted).toMatchObject({ sharedNotes: 0, promotions: 0, privateNotes: 0 });
    await asOwner(db);
    const priv = await db.query<{ content: string; status: string }>("select content, status from public.client_adapter_memory_items where id = $1", [chain.privateId]);
    expect(priv.rows[0]).toEqual({ content: "[tombstoned]", status: "tombstoned" });
    const promo = await db.query<{ decision_note: string | null }>("select decision_note from public.client_adapter_memory_promotions where id = $1", [chain.promotionId]);
    expect(promo.rows[0].decision_note).toBeNull();
    expect(await count(db, "client_adapter_memory_items", `id = '${chain.sharedId}' and content = 'chain content'`)).toBe(1);

    await age(db, 36, [chain.sharedId]); // now the shared note is due too
    const second = await purge(db);
    expect(second.deleted).toMatchObject({ sharedNotes: 1, promotions: 1, privateNotes: 1 });
    expect(await count(db, "client_adapter_memory_items")).toBe(0);
    expect(await count(db, "client_adapter_memory_promotions")).toBe(0);
  } finally {
    await db.close();
  }
});

