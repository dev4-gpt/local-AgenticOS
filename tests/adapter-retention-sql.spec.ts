import { expect, test } from "@playwright/test";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { PGlite } from "@electric-sql/pglite";
import { pgcrypto } from "@electric-sql/pglite/contrib/pgcrypto";

// Real PostgreSQL (PGlite) tests for product-experience/supabase-client-adapter-retention-28.sql.
// Users, tenants and rows are created inside each test; nothing real is used. "Time passing" is simulated by moving
// the stored dates back with the table triggers switched off, because the expiry is immutable for everyone else.
const HOST_SQL = readFileSync("product-experience/supabase-client-adapter-host.sql", "utf8");
const TOKEN_SQL = readFileSync("product-experience/supabase-client-adapter-token-uses.sql", "utf8");
const RETENTION_SQL = readFileSync("product-experience/supabase-client-adapter-retention-28.sql", "utf8");
const USER = {
  ownerA: "00000000-0000-4000-8000-0000000000a1",
  adminA: "00000000-0000-4000-8000-0000000000a2",
  memberA: "00000000-0000-4000-8000-0000000000a3",
  ownerB: "00000000-0000-4000-8000-0000000000b1",
};
const H = (c: string) => c.repeat(64);
const sha = (text: string) => createHash("sha256").update(text).digest("hex");
const TABLES = ["client_adapter_memory_items", "client_adapter_memory_promotions", "client_adapter_memory_provenance", "client_adapter_approvals", "client_adapter_budget_events"];

const BASE = `
  do $$ begin
    if not exists (select 1 from pg_roles where rolname='anon') then create role anon; end if;
    if not exists (select 1 from pg_roles where rolname='authenticated') then create role authenticated; end if;
    if not exists (select 1 from pg_roles where rolname='service_role') then create role service_role bypassrls; end if;
  end $$;
  create schema extensions; create extension pgcrypto with schema extensions;
  create schema auth;
  create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
  create table auth.users(id uuid primary key);
  create table public.client_tenants(slug text primary key, status text not null default 'active', worker_token_hash text, retention_days integer default 28);
  create table public.client_memberships(
    tenant_slug text not null references public.client_tenants(slug) on delete cascade,
    user_id uuid not null references auth.users(id), role text not null, status text not null default 'active',
    primary key (tenant_slug, user_id));
  create function public.client_member(p_tenant_slug text) returns boolean language sql stable security definer set search_path = public as $$
    select exists (select 1 from public.client_memberships where tenant_slug = p_tenant_slug and user_id = auth.uid() and status = 'active') $$;
  create table public.client_runtime_audit_events(id bigint generated by default as identity primary key, tenant_slug text not null, event_type text not null, metadata jsonb not null default '{}'::jsonb, created_at timestamptz not null default now());
  grant usage on schema public, auth, extensions to anon, authenticated, service_role;
  grant execute on function public.client_member(text) to authenticated;
  insert into auth.users values ('${USER.ownerA}'), ('${USER.adminA}'), ('${USER.memberA}'), ('${USER.ownerB}');
  insert into public.client_tenants(slug, worker_token_hash, retention_days) values ('tenant-a', '${sha("w".repeat(30))}', 28), ('tenant-b', '${sha("w".repeat(30))}', 28), ('tenant-c', null, 7);
  insert into public.client_memberships values
    ('tenant-a', '${USER.ownerA}', 'owner', 'active'), ('tenant-a', '${USER.adminA}', 'admin', 'active'),
    ('tenant-a', '${USER.memberA}', 'member', 'active'), ('tenant-b', '${USER.ownerB}', 'owner', 'active');
`;

async function baseDb() {
  const db = new PGlite({ extensions: { pgcrypto } });
  await db.exec(BASE);
  await db.exec(HOST_SQL);
  await db.exec(TOKEN_SQL);
  return db;
}
async function freshDb() {
  const db = await baseDb();
  await db.exec(RETENTION_SQL);
  await db.exec(RETENTION_SQL); // safe to repeat
  return db;
}

const asUser = async (db: PGlite, id: string) => {
  await db.exec("reset role");
  await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]);
  await db.exec("set role authenticated");
};
const asService = (db: PGlite) => db.exec("reset role; set role service_role");
const asAnon = (db: PGlite) => db.exec("reset role; set role anon");
const asOwner = (db: PGlite) => db.exec("reset role");

async function register(db: PGlite, tenant: string, adapter: string, user = USER.ownerA) {
  await db.exec("reset role");
  await db.exec(`insert into public.client_adapter_registry (tenant_slug, adapter_id, display_name, contract_version, manifest_sha256, created_by, state)
    values ('${tenant}','${adapter}','${adapter}','h1','${H("a")}','${user}','enabled')`);
}

async function addPrivate(db: PGlite, adapter: string, content: string, key: string, tenant = "tenant-a") {
  await asService(db);
  const r = await db.query<{ id: string }>(
    "insert into public.client_adapter_memory_items (tenant_slug, namespace, origin_adapter_id, content, content_sha256, idempotency_key) values ($1,$2,$3,$4,$5,$6) returning id",
    [tenant, `adapter:${adapter}`, adapter, content, sha(content), key],
  );
  return r.rows[0].id;
}
async function addProvenance(db: PGlite, itemId: string, adapter: string, tenant = "tenant-a") {
  await asService(db);
  await db.query(
    "insert into public.client_adapter_memory_provenance (tenant_slug, item_id, adapter_id, adapter_version, agent_principal, source_task_id, confidence) values ($1,$2,$3,'1','agent','task-1',0.5)",
    [tenant, itemId, adapter],
  );
}
/** private note -> promotion -> approved by a different admin -> shared note */
async function addSharedChain(db: PGlite, adapter: string, content: string, key: string) {
  const privateId = await addPrivate(db, adapter, content, key);
  await asService(db);
  await addProvenance(db, privateId, adapter);
  await asService(db);
  const scan = JSON.stringify({ scanner: "memory-scan-h1", content_sha256: sha(content), verdict: "clean", findings: [], scanned_chars: content.length });
  const promo = await db.query<{ id: string }>(
    "insert into public.client_adapter_memory_promotions (tenant_slug, source_item_id, origin_adapter_id, content_sha256, requested_by, scan_result) values ('tenant-a',$1,$2,$3,$4,$5::jsonb) returning id",
    [privateId, adapter, sha(content), USER.memberA, scan],
  );
  const promotionId = promo.rows[0].id;
  await asUser(db, USER.adminA);
  await db.query("update public.client_adapter_memory_promotions set status='approved', reviewed_by=auth.uid(), reviewed_at=now(), approved_content_sha256=$2, decision_note='looked fine', approved_sensitivity='ordinary' where id=$1", [promotionId, sha(content)]);
  await asService(db);
  const shared = await db.query<{ id: string }>(
    "insert into public.client_adapter_memory_items (tenant_slug, namespace, origin_adapter_id, content, content_sha256, trust_level, promotion_id, idempotency_key) values ('tenant-a','shared',$1,$2,$3,'reviewed',$4,$5) returning id",
    [adapter, content, sha(content), promotionId, `${key}-shared`],
  );
  return { privateId, promotionId, sharedId: shared.rows[0].id };
}

/** Moves stored dates back as if `days` had passed. Optionally only for rows with these ids. */
async function age(db: PGlite, days: number, ids?: string[]) {
  await asOwner(db);
  for (const table of TABLES) {
    await db.exec(`alter table public.${table} disable trigger user`);
    const where = ids ? `where id in (${ids.map((id) => `'${id}'`).join(",")})` : "";
    await db.exec(`update public.${table} set created_at = created_at - interval '${days} days', retention_expires_at = retention_expires_at - interval '${days} days' ${where}`);
    await db.exec(`alter table public.${table} enable trigger user`);
  }
}
async function count(db: PGlite, table: string, where = "true") {
  await asOwner(db);
  return Number((await db.query<{ n: string }>(`select count(*) as n from public.${table} where ${where}`)).rows[0].n);
}
async function purge(db: PGlite, tenant = "tenant-a", apply = true, batch = 100) {
  await asService(db);
  const r = await db.query<{ r: Record<string, any> }>("select public.purge_expired_client_adapter_records($1,$2,$3) as r", [tenant, apply, batch]);
  return r.rows[0].r;
}

test("the expiry is set at insert from the tenant's days, ignores the caller, and cannot change afterwards", async () => {
  const db = await freshDb();
  try {
    await register(db, "tenant-a", "forge");
    await register(db, "tenant-c", "forge");
    const a = await addPrivate(db, "forge", "note a", "idem-key-a1");
    const c = await addPrivate(db, "forge", "note c", "idem-key-c1", "tenant-c");
    await asOwner(db);
    const rows = await db.query<{ id: string; days: number }>("select id, round(extract(epoch from (retention_expires_at - created_at)) / 86400)::int as days from public.client_adapter_memory_items");
    expect(Object.fromEntries(rows.rows.map((r) => [r.id, r.days]))).toEqual({ [a]: 28, [c]: 7 });
    await asService(db);
    const forced = await db.query<{ days: number }>(
      "insert into public.client_adapter_memory_items (tenant_slug, namespace, origin_adapter_id, content, content_sha256, idempotency_key, retention_expires_at) values ('tenant-a','adapter:forge','forge','x',$1,'idem-key-a2', now() + interval '400 days') returning round(extract(epoch from (retention_expires_at - created_at)) / 86400)::int as days",
      [sha("x")],
    );
    expect(forced.rows[0].days).toBe(28);
    await expect(db.query("update public.client_adapter_memory_items set retention_expires_at = now() + interval '90 days' where id = $1", [a])).rejects.toThrow(/adapter_retention_immutable/);
  } finally {
    await db.close();
  }
});

