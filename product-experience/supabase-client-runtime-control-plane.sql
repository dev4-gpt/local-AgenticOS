-- Apply after the deployment-request and public-rate-limit migrations.
-- This is the low-cost control plane for single-tenant Cloud Run editions.
-- Raw provider values never belong in these tables; keep them in Secret Manager.

create table if not exists public.client_tenants (
  slug text primary key check (slug ~ '^[a-z][a-z0-9-]{2,40}$'),
  name text not null,
  status text not null default 'active' check (status in ('active', 'suspended', 'offboarding', 'deleted')),
  retention_days integer not null default 30 check (retention_days between 1 and 3650),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.client_memberships (
  tenant_slug text not null references public.client_tenants(slug) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'member' check (role in ('owner', 'admin', 'member', 'viewer')),
  status text not null default 'active' check (status in ('active', 'suspended', 'revoked')),
  created_at timestamptz not null default now(),
  primary key (tenant_slug, user_id)
);

create or replace function public.client_member(p_tenant_slug text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.client_memberships
    where tenant_slug = p_tenant_slug
      and user_id = auth.uid()
      and status = 'active'
  );
$$;

grant execute on function public.client_member(text) to authenticated;

create table if not exists public.client_runtime_requests (
  id uuid primary key default gen_random_uuid(),
  tenant_slug text not null references public.client_tenants(slug) on delete cascade,
  submitted_by uuid not null default auth.uid() references auth.users(id),
  request_type text not null check (request_type in ('command', 'context', 'orchestrate', 'create', 'deliver')),
  title text not null check (length(title) between 3 and 180),
  details text not null check (length(details) between 10 and 10000),
  fields jsonb not null default '{}'::jsonb,
  status text not null default 'pending_approval' check (status in ('pending_approval', 'approved', 'rejected', 'running', 'complete', 'failed', 'cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.client_runtime_audit_events (
  id bigint generated by default as identity primary key,
  tenant_slug text not null references public.client_tenants(slug) on delete cascade,
  actor_id uuid references auth.users(id),
  event_type text not null check (length(event_type) between 3 and 100),
  request_id text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.client_runtime_jobs (
  id uuid primary key default gen_random_uuid(),
  tenant_slug text not null references public.client_tenants(slug) on delete cascade,
  requested_by uuid not null default auth.uid() references auth.users(id),
  capability text not null,
  provider text,
  model text,
  idempotency_key text not null,
  status text not null default 'queued' check (status in ('queued', 'running', 'succeeded', 'failed', 'cancelled')),
  attempt_count integer not null default 0 check (attempt_count between 0 and 10),
  input_metadata jsonb not null default '{}'::jsonb,
  output_metadata jsonb not null default '{}'::jsonb,
  error_code text,
  created_at timestamptz not null default now(),
  started_at timestamptz,
  finished_at timestamptz,
  unique (tenant_slug, idempotency_key)
);

create table if not exists public.client_runtime_artifacts (
  id uuid primary key default gen_random_uuid(),
  tenant_slug text not null references public.client_tenants(slug) on delete cascade,
  job_id uuid references public.client_runtime_jobs(id) on delete set null,
  object_key text not null,
  content_type text not null,
  byte_size bigint not null default 0 check (byte_size >= 0),
  retention_expires_at timestamptz,
  created_at timestamptz not null default now(),
  unique (tenant_slug, object_key)
);

create table if not exists public.client_runtime_budget_ledger (
  id bigint generated by default as identity primary key,
  tenant_slug text not null references public.client_tenants(slug) on delete cascade,
  job_id uuid references public.client_runtime_jobs(id) on delete set null,
  provider text not null,
  model text,
  amount_micros bigint not null check (amount_micros >= 0),
  usage_metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists client_memberships_user_idx on public.client_memberships (user_id, status);
create index if not exists client_requests_tenant_created_idx on public.client_runtime_requests (tenant_slug, created_at desc);
create index if not exists client_audit_tenant_created_idx on public.client_runtime_audit_events (tenant_slug, created_at desc);
create index if not exists client_jobs_tenant_status_idx on public.client_runtime_jobs (tenant_slug, status, created_at desc);
create index if not exists client_artifacts_retention_idx on public.client_runtime_artifacts (tenant_slug, retention_expires_at);
create index if not exists client_budget_tenant_created_idx on public.client_runtime_budget_ledger (tenant_slug, created_at desc);

alter table public.client_tenants enable row level security;
alter table public.client_memberships enable row level security;
alter table public.client_runtime_requests enable row level security;
alter table public.client_runtime_audit_events enable row level security;
alter table public.client_runtime_jobs enable row level security;
alter table public.client_runtime_artifacts enable row level security;
alter table public.client_runtime_budget_ledger enable row level security;

drop policy if exists client_tenants_member_select on public.client_tenants;
create policy client_tenants_member_select on public.client_tenants
  for select to authenticated using (public.client_member(slug));

drop policy if exists client_memberships_self_select on public.client_memberships;
create policy client_memberships_self_select on public.client_memberships
  for select to authenticated using (user_id = auth.uid());

drop policy if exists client_requests_member_select on public.client_runtime_requests;
create policy client_requests_member_select on public.client_runtime_requests
  for select to authenticated using (public.client_member(tenant_slug));
drop policy if exists client_requests_member_insert on public.client_runtime_requests;
create policy client_requests_member_insert on public.client_runtime_requests
  for insert to authenticated with check (public.client_member(tenant_slug) and submitted_by = auth.uid());

drop policy if exists client_audit_member_select on public.client_runtime_audit_events;
create policy client_audit_member_select on public.client_runtime_audit_events
  for select to authenticated using (public.client_member(tenant_slug));
drop policy if exists client_audit_member_insert on public.client_runtime_audit_events;
create policy client_audit_member_insert on public.client_runtime_audit_events
  for insert to authenticated with check (public.client_member(tenant_slug) and actor_id = auth.uid());

drop policy if exists client_jobs_member_select on public.client_runtime_jobs;
create policy client_jobs_member_select on public.client_runtime_jobs
  for select to authenticated using (public.client_member(tenant_slug));
drop policy if exists client_artifacts_member_select on public.client_runtime_artifacts;
create policy client_artifacts_member_select on public.client_runtime_artifacts
  for select to authenticated using (public.client_member(tenant_slug));
drop policy if exists client_budget_member_select on public.client_runtime_budget_ledger;
create policy client_budget_member_select on public.client_runtime_budget_ledger
  for select to authenticated using (public.client_member(tenant_slug));

-- Clients cannot delete, approve, spend, or mutate jobs directly. Operator
-- actions use the service role or a reviewed server-side worker.
revoke all on all tables in schema public from anon;
grant select, insert on public.client_runtime_requests to authenticated;
grant select, insert on public.client_runtime_audit_events to authenticated;
grant select on public.client_tenants, public.client_memberships,
  public.client_runtime_jobs, public.client_runtime_artifacts,
  public.client_runtime_budget_ledger to authenticated;
grant usage, select on sequence public.client_runtime_audit_events_id_seq,
  public.client_runtime_budget_ledger_id_seq to authenticated;
