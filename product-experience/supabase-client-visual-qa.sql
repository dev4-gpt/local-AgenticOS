-- Apply after supabase-client-runtime-hosted-capabilities.sql.
-- Visual-QA reports are tenant artifacts, written only by the worker RPC.

create table if not exists public.client_visual_qa_reports (
  id uuid primary key default gen_random_uuid(),
  tenant_slug text not null references public.client_tenants(slug) on delete cascade,
  artifact_id uuid not null references public.client_runtime_artifacts(id) on delete cascade,
  job_id uuid references public.client_runtime_jobs(id) on delete set null,
  worker text not null check (length(worker) between 2 and 80),
  frames_sampled integer not null check (frames_sampled between 0 and 120),
  runtime_ms integer not null check (runtime_ms >= 0),
  status text not null check (status in ('passed', 'review', 'failed')),
  warnings jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  unique (tenant_slug, artifact_id, job_id)
);

create table if not exists public.client_visual_qa_findings (
  id bigint generated by default as identity primary key,
  tenant_slug text not null references public.client_tenants(slug) on delete cascade,
  report_id uuid not null references public.client_visual_qa_reports(id) on delete cascade,
  code text not null,
  severity text not null check (severity in ('info', 'warning', 'error')),
  frame integer not null check (frame >= 0),
  confidence numeric not null check (confidence >= 0 and confidence <= 1),
  message text not null check (length(message) between 1 and 1000)
);

create index if not exists client_visual_qa_reports_tenant_created_idx
  on public.client_visual_qa_reports (tenant_slug, created_at desc);
create index if not exists client_visual_qa_findings_report_idx
  on public.client_visual_qa_findings (tenant_slug, report_id);

alter table public.client_visual_qa_reports enable row level security;
alter table public.client_visual_qa_findings enable row level security;

drop policy if exists client_visual_qa_reports_member_select on public.client_visual_qa_reports;
create policy client_visual_qa_reports_member_select on public.client_visual_qa_reports
  for select to authenticated using (public.client_member(tenant_slug));
drop policy if exists client_visual_qa_findings_member_select on public.client_visual_qa_findings;
create policy client_visual_qa_findings_member_select on public.client_visual_qa_findings
  for select to authenticated using (public.client_member(tenant_slug));

revoke all on public.client_visual_qa_reports, public.client_visual_qa_findings from anon;
grant select on public.client_visual_qa_reports, public.client_visual_qa_findings to authenticated;

create or replace function public.record_client_visual_qa_report_worker(
  p_tenant_slug text,
  p_artifact_id uuid,
  p_job_id uuid,
  p_worker_token text,
  p_worker text,
  p_frames_sampled integer,
  p_runtime_ms integer,
  p_status text,
  p_warnings jsonb,
  p_findings jsonb
)
returns uuid
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_report_id uuid;
  finding jsonb;
begin
  if p_worker_token is null or length(p_worker_token) < 24
     or not exists (
       select 1 from public.client_tenants
       where slug = p_tenant_slug and status = 'active'
         and worker_token_hash = encode(digest(p_worker_token, 'sha256'), 'hex')
     )
     or not exists (select 1 from public.client_runtime_artifacts where id = p_artifact_id and tenant_slug = p_tenant_slug)
     or p_frames_sampled < 0 or p_frames_sampled > 120
     or p_runtime_ms < 0
     or p_status not in ('passed', 'review', 'failed')
     or jsonb_typeof(p_findings) <> 'array' then
    return null;
  end if;

  insert into public.client_visual_qa_reports
    (tenant_slug, artifact_id, job_id, worker, frames_sampled, runtime_ms, status, warnings)
  values
    (p_tenant_slug, p_artifact_id, p_job_id, left(p_worker, 80), p_frames_sampled, p_runtime_ms, p_status, coalesce(p_warnings, '[]'::jsonb))
  on conflict (tenant_slug, artifact_id, job_id) do update
    set worker = excluded.worker, frames_sampled = excluded.frames_sampled,
        runtime_ms = excluded.runtime_ms, status = excluded.status,
        warnings = excluded.warnings
  returning id into v_report_id;

  delete from public.client_visual_qa_findings where client_visual_qa_findings.report_id = v_report_id and client_visual_qa_findings.tenant_slug = p_tenant_slug;
  for finding in select value from jsonb_array_elements(p_findings)
  loop
    if jsonb_typeof(finding) <> 'object'
       or length(coalesce(finding->>'code', '')) < 1
       or finding->>'severity' not in ('info', 'warning', 'error')
       or (finding->>'frame') !~ '^[0-9]{1,3}$'
       or (finding->>'confidence') !~ '^(0([.][0-9]+)?|1([.]0+)?)$'
       or (finding->>'frame')::integer < 0
       or (finding->>'confidence')::numeric < 0
       or (finding->>'confidence')::numeric > 1
       or length(coalesce(finding->>'message', '')) < 1 then
      return null;
    end if;
    insert into public.client_visual_qa_findings
      (tenant_slug, report_id, code, severity, frame, confidence, message)
    values
      (p_tenant_slug, v_report_id, left(finding->>'code', 80), finding->>'severity', (finding->>'frame')::integer, (finding->>'confidence')::numeric, left(finding->>'message', 1000));
  end loop;
  return v_report_id;
exception when others then
  return null;
end;
$$;

revoke all on function public.record_client_visual_qa_report_worker(text, uuid, uuid, text, text, integer, integer, text, jsonb, jsonb) from public, authenticated;
grant execute on function public.record_client_visual_qa_report_worker(text, uuid, uuid, text, text, integer, integer, text, jsonb, jsonb) to anon;
