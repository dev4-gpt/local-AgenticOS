-- Apply after supabase-client-pipeline.sql.
-- Hosted task boards: Kanban and Agent Kanban. Local Kanban is backed by the
-- Hermes CLI over a SQLite database and Agent Kanban is a browser-only board;
-- neither exists in Cloud Run, so both become tenant rows here. One table with
-- a board discriminator keeps their shared shape in one place while letting
-- each board keep its own stage vocabulary.

create table if not exists public.client_board_tasks (
  id uuid primary key default gen_random_uuid(),
  tenant_slug text not null references public.client_tenants(slug) on delete cascade,
  created_by uuid not null default auth.uid() references auth.users(id),
  board text not null check (board in ('kanban', 'agent-kanban')),
  title text not null check (length(title) between 1 and 240),
  body text not null default '' check (length(body) <= 20000),
  -- Kanban uses triage..archived; Agent Kanban uses queued..rejected. The
  -- union is constrained here and each board filters to its own set in code.
  status text not null default 'triage' check (status in (
    'triage', 'todo', 'ready', 'running', 'blocked', 'done', 'archived',
    'queued', 'building', 'reviewing', 'rejected'
  )),
  assignee text check (length(assignee) <= 80),
  priority integer not null default 2 check (priority between 0 and 4),
  labels text[] not null default '{}'::text[] check (cardinality(labels) <= 12),
  -- Agent Kanban cards ship an artifact through the shared execution lane.
  build_artifact_id uuid references public.client_runtime_artifacts(id) on delete set null,
  build_preview_html text check (length(build_preview_html) <= 40000),
  execution_state text check (execution_state in ('queued', 'running', 'succeeded', 'failed', 'cancelled')),
  execution_job_id uuid references public.client_runtime_jobs(id) on delete set null,
  execution_error text check (length(execution_error) <= 120),
  result text check (length(result) <= 20000),
  started_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.client_board_comments (
  id uuid primary key default gen_random_uuid(),
  tenant_slug text not null references public.client_tenants(slug) on delete cascade,
  task_id uuid not null references public.client_board_tasks(id) on delete cascade,
  created_by uuid references auth.users(id),
  author text check (length(author) <= 80),
  body text not null check (length(body) between 1 and 10000),
  created_at timestamptz not null default now()
);

-- The local board keeps an event trail per task; this is its tenant equivalent.
create table if not exists public.client_board_events (
  id bigint generated by default as identity primary key,
  tenant_slug text not null references public.client_tenants(slug) on delete cascade,
  task_id uuid not null references public.client_board_tasks(id) on delete cascade,
  kind text not null check (length(kind) between 1 and 60),
  detail text not null default '' check (length(detail) <= 2000),
  created_at timestamptz not null default now()
);

create index if not exists client_board_tasks_tenant_board_idx
  on public.client_board_tasks (tenant_slug, board, status, priority desc, created_at desc);
create index if not exists client_board_tasks_job_idx
  on public.client_board_tasks (execution_job_id) where execution_job_id is not null;
create index if not exists client_board_comments_task_idx
  on public.client_board_comments (tenant_slug, task_id, created_at);
create index if not exists client_board_events_task_idx
  on public.client_board_events (tenant_slug, task_id, created_at desc);

alter table public.client_board_tasks enable row level security;
alter table public.client_board_comments enable row level security;
alter table public.client_board_events enable row level security;

do $$
declare
  board_table text;
begin
  foreach board_table in array array[
    'client_board_tasks',
    'client_board_comments',
    'client_board_events'
  ]
  loop
    execute format('drop policy if exists %1$s_member_select on public.%1$s', board_table);
    execute format(
      'create policy %1$s_member_select on public.%1$s for select to authenticated using (public.client_member(tenant_slug))',
      board_table
    );
    execute format('drop policy if exists %1$s_member_insert on public.%1$s', board_table);
    execute format(
      'create policy %1$s_member_insert on public.%1$s for insert to authenticated with check (public.client_member(tenant_slug))',
      board_table
    );
    execute format('drop policy if exists %1$s_member_update on public.%1$s', board_table);
    execute format(
      'create policy %1$s_member_update on public.%1$s for update to authenticated using (public.client_member(tenant_slug)) with check (public.client_member(tenant_slug))',
      board_table
    );
    execute format('drop policy if exists %1$s_member_delete on public.%1$s', board_table);
    execute format(
      'create policy %1$s_member_delete on public.%1$s for delete to authenticated using (public.client_member(tenant_slug))',
      board_table
    );
  end loop;
end
$$;

grant select, insert, update, delete on public.client_board_tasks to authenticated;
grant select, insert, update, delete on public.client_board_comments to authenticated;
grant select, insert, update, delete on public.client_board_events to authenticated;
grant usage, select on sequence public.client_board_events_id_seq to authenticated;

-- Worker-only reconciliation for an Agent Kanban card's build.
drop function if exists public.update_client_board_task_worker(text, text, uuid, jsonb);

create or replace function public.update_client_board_task_worker(
  p_tenant_slug text,
  p_worker_token text,
  p_job_id uuid,
  p_patch jsonb
)
returns boolean
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  next_status text;
  next_execution text;
  target uuid;
begin
  if p_worker_token is null
     or length(p_worker_token) < 24
     or p_patch is null
     or jsonb_typeof(p_patch) <> 'object'
     or pg_column_size(p_patch) > 262144
     or not exists (
       select 1 from public.client_tenants
       where slug = p_tenant_slug
         and status = 'active'
         and worker_token_hash = encode(digest(p_worker_token, 'sha256'), 'hex')
     ) then
    return false;
  end if;

  next_status := p_patch->>'status';
  next_execution := p_patch->>'execution_state';
  if next_status is not null and next_status not in (
       'triage', 'todo', 'ready', 'running', 'blocked', 'done', 'archived',
       'queued', 'building', 'reviewing', 'rejected') then
    return false;
  end if;
  if next_execution is not null and next_execution not in ('queued', 'running', 'succeeded', 'failed', 'cancelled') then
    return false;
  end if;

  update public.client_board_tasks
    set status = coalesce(next_status, status),
        execution_state = coalesce(next_execution, execution_state),
        execution_error = case when next_execution in ('succeeded', 'running') then null else coalesce(left(p_patch->>'execution_error', 120), execution_error) end,
        build_artifact_id = coalesce((p_patch->>'build_artifact_id')::uuid, build_artifact_id),
        build_preview_html = coalesce(left(p_patch->>'build_preview_html', 40000), build_preview_html),
        result = coalesce(left(p_patch->>'result', 20000), result),
        started_at = coalesce(started_at, now()),
        completed_at = case when next_execution in ('succeeded', 'failed', 'cancelled') then now() else completed_at end,
        updated_at = now()
  where tenant_slug = p_tenant_slug
    and execution_job_id = p_job_id
  returning id into target;

  if target is null then
    return false;
  end if;

  insert into public.client_board_events (tenant_slug, task_id, kind, detail)
  values (p_tenant_slug, target, coalesce(next_execution, 'updated'), left(coalesce(p_patch->>'execution_error', ''), 2000));

  return true;
end;
$$;

revoke all on function public.update_client_board_task_worker(text, text, uuid, jsonb)
  from public, authenticated;
grant execute on function public.update_client_board_task_worker(text, text, uuid, jsonb)
  to anon;
