-- Veloce AgenticOS v3.3 managed-credit financial lifecycle.
-- Apply after:
--   1. supabase-public-launch-control-plane.sql
--   2. supabase-v31-managed-credit-plans.sql
--   3. supabase-v32-managed-credit-readiness.sql
--
-- This migration records wallet reservations separately from purchases.
-- It does not enable a provider and it never stores provider secrets.

alter table public.client_credit_purchase_plans
  drop constraint if exists client_credit_purchase_plans_status_check;

alter table public.client_credit_purchase_plans
  add constraint client_credit_purchase_plans_status_check
  check (status in ('pending', 'paid', 'expired', 'cancelled', 'refunded'));

alter table public.client_credit_purchase_plans
  add column if not exists reconciliation_status text not null default 'pending',
  add column if not exists failure_reason text,
  add column if not exists refunded_micros bigint not null default 0
    check (refunded_micros >= 0);

alter table public.client_credit_purchase_plans
  drop constraint if exists client_credit_purchase_plans_reconciliation_status_check;

alter table public.client_credit_purchase_plans
  add constraint client_credit_purchase_plans_reconciliation_status_check
  check (reconciliation_status in ('pending', 'matched', 'drift', 'failed'));

create table if not exists public.client_credit_purchase_plan_allocations (
  id bigint generated by default as identity primary key,
  plan_id uuid not null references public.client_credit_purchase_plans(id) on delete cascade,
  tenant_slug text not null references public.client_tenants(slug) on delete cascade,
  catalog_id text not null,
  provider_key text not null,
  allocated_micros bigint not null check (allocated_micros > 0),
  refunded_micros bigint not null default 0 check (refunded_micros >= 0),
