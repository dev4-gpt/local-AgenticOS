create or replace function public.reserve_client_credit(
  p_tenant_slug text,
  p_catalog_id text,
  p_provider_key text,
  p_idempotency_key text,
  p_quoted_amount_micros bigint,
  p_expires_at timestamptz default null,
  p_pricing_snapshot_id text default null,
  p_metadata jsonb default '{}'::jsonb
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  existing_id uuid;
  reservation_id uuid;
  account_balance bigint;
  account_reserved bigint;
  budget_available bigint;
  expires_at_value timestamptz := coalesce(p_expires_at, now() + interval '15 minutes');
begin
  if coalesce(p_tenant_slug, '') = ''
     or coalesce(p_catalog_id, '') = ''
     or coalesce(p_provider_key, '') = ''
     or coalesce(p_idempotency_key, '') = ''
     or p_quoted_amount_micros is null
     or p_quoted_amount_micros <= 0
     or expires_at_value <= now()
     or p_metadata is null
     or jsonb_typeof(p_metadata) <> 'object'
     or pg_column_size(p_metadata) > 8192 then
    return null;
  end if;

  select id
    into existing_id
  from public.client_credit_reservations
  where tenant_slug = p_tenant_slug
    and idempotency_key = p_idempotency_key;

  if existing_id is not null then
    return existing_id;
  end if;

  perform pg_advisory_xact_lock(hashtext(left(p_tenant_slug, 64)));

  insert into public.client_credit_accounts (tenant_slug)
  values (p_tenant_slug)
  on conflict (tenant_slug) do nothing;

  select a.balance_micros, a.reserved_micros
    into account_balance, account_reserved
  from public.client_credit_accounts a
  where a.tenant_slug = p_tenant_slug
  for update;

  select greatest(0, b.purchased_micros - b.reserved_micros - b.spent_micros)
    into budget_available
  from public.client_credit_budgets b
  where b.tenant_slug = p_tenant_slug
    and b.catalog_id = p_catalog_id
    and b.provider_key = p_provider_key
    and b.managed_route_enabled = true
    and b.status = 'active'
  for update;

  if budget_available is null
     or budget_available < p_quoted_amount_micros
     or greatest(0, account_balance - account_reserved) < p_quoted_amount_micros then
    return null;
  end if;

  insert into public.client_credit_reservations (
    tenant_slug,
    catalog_id,
    provider_key,
    idempotency_key,
    quoted_amount_micros,
    reserved_amount_micros,
    pricing_snapshot_id,
    expires_at,
    reconciliation_metadata,
    audit_metadata
  )
  values (
    p_tenant_slug,
    p_catalog_id,
    p_provider_key,
    p_idempotency_key,
    p_quoted_amount_micros,
    p_quoted_amount_micros,
    nullif(p_pricing_snapshot_id, ''),
    expires_at_value,
    jsonb_build_object('state', 'reserved') || p_metadata,
    jsonb_build_object('operation', 'reserve', 'idempotency_key', p_idempotency_key)
  )
  returning id into reservation_id;

  update public.client_credit_accounts
  set reserved_micros = reserved_micros + p_quoted_amount_micros,
      updated_at = now()
  where tenant_slug = p_tenant_slug;

  update public.client_credit_budgets
  set reserved_micros = reserved_micros + p_quoted_amount_micros,
      updated_at = now()
  where tenant_slug = p_tenant_slug
    and catalog_id = p_catalog_id;

  insert into public.client_credit_transactions (
    tenant_slug,
    idempotency_key,
    kind,
    amount_micros,
    balance_after_micros,
    provider,
    pricing_snapshot_id,
    metadata
  )
  values (
    p_tenant_slug,
    'reservation:' || reservation_id,
    'reservation',
    p_quoted_amount_micros,
    account_balance,
    p_provider_key,
    nullif(p_pricing_snapshot_id, ''),
    jsonb_build_object(
      'reservation_id', reservation_id,
      'direction', 'reserved',
      'expires_at', expires_at_value
    ) || p_metadata
  )
  on conflict (tenant_slug, idempotency_key) do nothing;

  insert into public.client_credit_reservation_events (
    reservation_id,
    tenant_slug,
    event_type,
    idempotency_key,
    amount_micros,
    metadata
  )
  values (
    reservation_id,
    p_tenant_slug,
    'reserved',
    'reserve:' || p_idempotency_key,
    p_quoted_amount_micros,
    p_metadata
  )
  on conflict (reservation_id, idempotency_key) do nothing;

  return reservation_id;
end;
$$;

create or replace function public.settle_client_credit(
  p_reservation_id uuid,
  p_actual_amount_micros bigint,
  p_provider_request_id text default null,
  p_idempotency_key text default null,
  p_usage_metadata jsonb default '{}'::jsonb
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  reservation_row public.client_credit_reservations%rowtype;
  new_balance bigint;
  budget_reserved bigint;
  event_key text := coalesce(nullif(p_idempotency_key, ''), 'settle:' || p_reservation_id);
begin
  if p_reservation_id is null
     or p_actual_amount_micros is null
     or p_actual_amount_micros < 0
     or p_usage_metadata is null
     or jsonb_typeof(p_usage_metadata) <> 'object'
     or pg_column_size(p_usage_metadata) > 8192 then
    return false;
  end if;

  select *
    into reservation_row
  from public.client_credit_reservations
  where id = p_reservation_id
  for update;

  if not found then
    return false;
  end if;

  if reservation_row.status = 'settled' then
    return true;
  end if;

  if reservation_row.status <> 'reserved'
     or p_actual_amount_micros > reservation_row.reserved_amount_micros
     or reservation_row.expires_at <= now() then
    return false;
  end if;

  perform pg_advisory_xact_lock(hashtext(left(reservation_row.tenant_slug, 64)));

  select reserved_micros
    into budget_reserved
  from public.client_credit_budgets
  where tenant_slug = reservation_row.tenant_slug
    and catalog_id = reservation_row.catalog_id
  for update;

  if budget_reserved is null
     or budget_reserved < reservation_row.reserved_amount_micros then
    return false;
  end if;

  update public.client_credit_accounts
  set reserved_micros = reserved_micros - reservation_row.reserved_amount_micros,
      balance_micros = balance_micros - p_actual_amount_micros,
      updated_at = now()
  where tenant_slug = reservation_row.tenant_slug
    and reserved_micros >= reservation_row.reserved_amount_micros
    and balance_micros >= p_actual_amount_micros
  returning balance_micros into new_balance;

  if new_balance is null then
    return false;
  end if;

  update public.client_credit_budgets
  set reserved_micros = reserved_micros - reservation_row.reserved_amount_micros,
      spent_micros = spent_micros + p_actual_amount_micros,
      updated_at = now()
  where tenant_slug = reservation_row.tenant_slug
    and catalog_id = reservation_row.catalog_id
    and reserved_micros >= reservation_row.reserved_amount_micros;

  if not found then
    raise exception 'credit_budget_settlement_update_failed';
  end if;

  update public.client_credit_reservations
  set status = 'settled',
      actual_amount_micros = p_actual_amount_micros,
      provider_request_id = nullif(p_provider_request_id, ''),
      settled_at = now(),
      reconciliation_status = 'matched',
      reconciliation_metadata = p_usage_metadata,
      audit_metadata = audit_metadata || jsonb_build_object('operation', 'settle', 'idempotency_key', event_key),
      updated_at = now()
  where id = p_reservation_id;

  insert into public.client_credit_transactions (
    tenant_slug,
    idempotency_key,
    kind,
    amount_micros,
    balance_after_micros,
    provider,
    pricing_snapshot_id,
    metadata
  )
  values (
    reservation_row.tenant_slug,
    event_key,
    'settlement',
    p_actual_amount_micros,
    new_balance,
    reservation_row.provider_key,
    reservation_row.pricing_snapshot_id,
    jsonb_build_object(
      'reservation_id', p_reservation_id,
      'direction', 'spent',
      'provider_request_id', p_provider_request_id
    ) || p_usage_metadata
  )
  on conflict (tenant_slug, idempotency_key) do nothing;

  insert into public.client_credit_reservation_events (
    reservation_id,
    tenant_slug,
    event_type,
    idempotency_key,
    amount_micros,
    provider_request_id,
    metadata
  )
  values (
    p_reservation_id,
    reservation_row.tenant_slug,
    'settled',
    event_key,
    p_actual_amount_micros,
    nullif(p_provider_request_id, ''),
    p_usage_metadata
  )
  on conflict (reservation_id, idempotency_key) do nothing;

  return true;
end;
$$;

create or replace function public.refund_client_credit(
  p_reservation_id uuid,
  p_reason text,
  p_idempotency_key text default null,
  p_metadata jsonb default '{}'::jsonb
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  reservation_row public.client_credit_reservations%rowtype;
  refund_amount bigint := 0;
  new_balance bigint;
  account_reserved bigint;
  budget_reserved bigint;
  budget_spent bigint;
  event_key text := coalesce(nullif(p_idempotency_key, ''), 'refund:' || p_reservation_id);
begin
  if p_reservation_id is null
     or coalesce(nullif(trim(p_reason), ''), '') = ''
     or p_metadata is null
     or jsonb_typeof(p_metadata) <> 'object'
     or pg_column_size(p_metadata) > 8192 then
    return false;
  end if;

  select *
    into reservation_row
  from public.client_credit_reservations
  where id = p_reservation_id
  for update;

  if not found then
    return false;
  end if;

  if reservation_row.status in ('refunded', 'expired') then
    return true;
  end if;

  if reservation_row.status not in ('reserved', 'settled') then
    return false;
  end if;

  perform pg_advisory_xact_lock(hashtext(left(reservation_row.tenant_slug, 64)));

  select reserved_micros
    into account_reserved
  from public.client_credit_accounts
  where tenant_slug = reservation_row.tenant_slug
  for update;

  if account_reserved is null then
    return false;
  end if;

  if reservation_row.status = 'reserved' then
    select reserved_micros
      into budget_reserved
    from public.client_credit_budgets
    where tenant_slug = reservation_row.tenant_slug
      and catalog_id = reservation_row.catalog_id
    for update;

    if budget_reserved is null
       or account_reserved < reservation_row.reserved_amount_micros
       or budget_reserved < reservation_row.reserved_amount_micros then
      return false;
    end if;

    update public.client_credit_accounts
    set reserved_micros = reserved_micros - reservation_row.reserved_amount_micros,
        updated_at = now()
    where tenant_slug = reservation_row.tenant_slug
      and reserved_micros >= reservation_row.reserved_amount_micros
    returning balance_micros into new_balance;

    update public.client_credit_budgets
    set reserved_micros = reserved_micros - reservation_row.reserved_amount_micros,
        updated_at = now()
    where tenant_slug = reservation_row.tenant_slug
      and catalog_id = reservation_row.catalog_id
      and reserved_micros >= reservation_row.reserved_amount_micros;
  else
    refund_amount := reservation_row.actual_amount_micros;

    select spent_micros
      into budget_spent
    from public.client_credit_budgets
    where tenant_slug = reservation_row.tenant_slug
      and catalog_id = reservation_row.catalog_id
    for update;

    if budget_spent is null or budget_spent < refund_amount then
      return false;
    end if;

    update public.client_credit_accounts
    set balance_micros = balance_micros + refund_amount,
        updated_at = now()
    where tenant_slug = reservation_row.tenant_slug
    returning balance_micros into new_balance;

    update public.client_credit_budgets
    set spent_micros = spent_micros - refund_amount,
        updated_at = now()
    where tenant_slug = reservation_row.tenant_slug
      and catalog_id = reservation_row.catalog_id
      and spent_micros >= refund_amount;

    if not found then
      raise exception 'credit_budget_refund_update_failed';
    end if;
  end if;

  if new_balance is null then
    return false;
  end if;

  update public.client_credit_reservations
  set status = 'refunded',
      refunded_amount_micros = refund_amount,
      refunded_at = now(),
      failure_reason = left(p_reason, 1000),
      reconciliation_status = 'matched',
      reconciliation_metadata = p_metadata,
      audit_metadata = audit_metadata || jsonb_build_object('operation', 'refund', 'idempotency_key', event_key),
      updated_at = now()
  where id = p_reservation_id;

  insert into public.client_credit_transactions (
    tenant_slug,
    idempotency_key,
    kind,
    amount_micros,
    balance_after_micros,
    provider,
    pricing_snapshot_id,
    metadata
  )
  values (
    reservation_row.tenant_slug,
    event_key,
    'refund',
    refund_amount,
    new_balance,
    reservation_row.provider_key,
    reservation_row.pricing_snapshot_id,
    jsonb_build_object(
      'reservation_id', p_reservation_id,
      'reason', left(p_reason, 1000),
      'direction', 'returned'
    ) || p_metadata
  )
  on conflict (tenant_slug, idempotency_key) do nothing;

  insert into public.client_credit_reservation_events (
    reservation_id,
    tenant_slug,
    event_type,
    idempotency_key,
    amount_micros,
    failure_reason,
    metadata
  )
  values (
    p_reservation_id,
    reservation_row.tenant_slug,
    'refunded',
    event_key,
    refund_amount,
    left(p_reason, 1000),
    p_metadata
  )
  on conflict (reservation_id, idempotency_key) do nothing;

  return true;
end;
$$;

create or replace function public.expire_client_credit_reservations(
  p_limit integer default 100
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  reservation_row public.client_credit_reservations%rowtype;
  released integer := 0;
  new_balance bigint;
  budget_reserved bigint;
begin
  if p_limit is null or p_limit < 1 or p_limit > 1000 then
    return 0;
  end if;

  for reservation_row in
    select *
    from public.client_credit_reservations
    where status = 'reserved'
      and expires_at <= now()
    order by expires_at
    limit p_limit
    for update skip locked
  loop
    perform pg_advisory_xact_lock(hashtext(left(reservation_row.tenant_slug, 64)));

    select reserved_micros
      into budget_reserved
    from public.client_credit_budgets
    where tenant_slug = reservation_row.tenant_slug
      and catalog_id = reservation_row.catalog_id
    for update;

    if budget_reserved is null
       or budget_reserved < reservation_row.reserved_amount_micros then
      continue;
    end if;

    update public.client_credit_accounts
    set reserved_micros = reserved_micros - reservation_row.reserved_amount_micros,
        updated_at = now()
    where tenant_slug = reservation_row.tenant_slug
      and reserved_micros >= reservation_row.reserved_amount_micros
    returning balance_micros into new_balance;

    update public.client_credit_budgets
    set reserved_micros = reserved_micros - reservation_row.reserved_amount_micros,
        updated_at = now()
    where tenant_slug = reservation_row.tenant_slug
      and catalog_id = reservation_row.catalog_id
      and reserved_micros >= reservation_row.reserved_amount_micros;

    if not found then
      continue;
    end if;

    if new_balance is not null then
      update public.client_credit_reservations
      set status = 'expired',
          failure_reason = 'reservation_expired',
          reconciliation_status = 'matched',
          audit_metadata = audit_metadata || jsonb_build_object('operation', 'expire'),
          updated_at = now()
      where id = reservation_row.id;

      insert into public.client_credit_transactions (
        tenant_slug,
        idempotency_key,
        kind,
        amount_micros,
        balance_after_micros,
        provider,
        pricing_snapshot_id,
        metadata
      )
      values (
        reservation_row.tenant_slug,
        'expiration:' || reservation_row.id,
        'expiration',
        reservation_row.reserved_amount_micros,
        new_balance,
        reservation_row.provider_key,
        reservation_row.pricing_snapshot_id,
        jsonb_build_object('reservation_id', reservation_row.id, 'direction', 'released')
      )
      on conflict (tenant_slug, idempotency_key) do nothing;

      insert into public.client_credit_reservation_events (
        reservation_id,
        tenant_slug,
        event_type,
        idempotency_key,
        amount_micros,
        failure_reason
      )
      values (
        reservation_row.id,
        reservation_row.tenant_slug,
        'expired',
        'expire:' || reservation_row.id,
        reservation_row.reserved_amount_micros,
        'reservation_expired'
      )
      on conflict (reservation_id, idempotency_key) do nothing;

      released := released + 1;
    end if;
  end loop;

  return released;
end;
$$;

create or replace function public.record_client_credit_purchase_lifecycle_event(
  p_plan_id uuid,
  p_event_type text,
  p_stripe_event_id text,
  p_amount_micros bigint default 0,
  p_metadata jsonb default '{}'::jsonb
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  plan_row public.client_credit_purchase_plans%rowtype;
  plan_allocation public.client_credit_purchase_plan_allocations%rowtype;
  refund_amount bigint;
  refund_remaining bigint;
  allocation_refund bigint;
  available bigint;
  new_balance bigint;
begin
  if p_plan_id is null
     or p_event_type not in (
       'checkout.session.expired',
       'payment_intent.payment_failed',
       'charge.refunded',
       'charge.dispute.created'
     )
     or coalesce(nullif(p_stripe_event_id, ''), '') = ''
     or p_amount_micros is null
     or p_amount_micros < 0
     or p_metadata is null
     or jsonb_typeof(p_metadata) <> 'object'
     or pg_column_size(p_metadata) > 8192 then
    return false;
  end if;

  if exists (
    select 1
    from public.client_credit_transactions
    where tenant_slug = (select tenant_slug from public.client_credit_purchase_plans where id = p_plan_id)
      and idempotency_key = 'stripe-event:' || p_stripe_event_id
  ) then
    return true;
  end if;

  select *
    into plan_row
  from public.client_credit_purchase_plans
  where id = p_plan_id
  for update;

  if not found then
    return false;
  end if;

  if p_event_type in ('checkout.session.expired', 'payment_intent.payment_failed') then
    update public.client_credit_purchase_plans
    set status = case when status = 'pending' then
        case when p_event_type = 'checkout.session.expired' then 'expired' else 'cancelled' end
      else status end,
      reconciliation_status = 'matched',
      failure_reason = case when p_event_type = 'payment_intent.payment_failed' then
        coalesce(nullif(p_metadata->>'failure_reason', ''), 'payment_intent_payment_failed')
        else failure_reason end,
      metadata = coalesce(metadata, '{}'::jsonb) || p_metadata,
      updated_at = now()
    where id = p_plan_id;

    insert into public.client_credit_accounts (tenant_slug)
    values (plan_row.tenant_slug)
    on conflict (tenant_slug) do nothing;

    insert into public.client_credit_transactions (
      tenant_slug, idempotency_key, kind, amount_micros, balance_after_micros, stripe_event_id, metadata
    )
    select
      plan_row.tenant_slug,
      'stripe-event:' || p_stripe_event_id,
      'adjustment',
      0,
      coalesce(a.balance_micros, 0),
      p_stripe_event_id,
      jsonb_build_object('event_type', p_event_type, 'plan_id', p_plan_id) || p_metadata
    from public.client_credit_accounts a
    where a.tenant_slug = plan_row.tenant_slug
    on conflict (tenant_slug, idempotency_key) do nothing;

    return true;
  end if;

  update public.client_credit_purchase_plans
  set reconciliation_status = case when p_event_type = 'charge.dispute.created' then 'drift' else reconciliation_status end,
      failure_reason = case when p_event_type = 'charge.dispute.created' then 'charge_dispute_created' else failure_reason end,
      metadata = coalesce(metadata, '{}'::jsonb) || p_metadata,
      updated_at = now()
  where id = p_plan_id;

  if p_event_type = 'charge.dispute.created' then
    insert into public.client_credit_transactions (
      tenant_slug, idempotency_key, kind, amount_micros, balance_after_micros, stripe_event_id, metadata
    )
    select
      plan_row.tenant_slug,
      'stripe-event:' || p_stripe_event_id,
      'adjustment',
      0,
      coalesce(a.balance_micros, 0),
      p_stripe_event_id,
      jsonb_build_object('event_type', p_event_type, 'plan_id', p_plan_id, 'requires_review', true) || p_metadata
    from public.client_credit_accounts a
    where a.tenant_slug = plan_row.tenant_slug
    on conflict (tenant_slug, idempotency_key) do nothing;
    return true;
  end if;

  if plan_row.status <> 'paid' then
    return false;
  end if;

  refund_amount := case when p_amount_micros = 0 then plan_row.total_micros - plan_row.refunded_micros else p_amount_micros end;
  refund_remaining := refund_amount;
  if refund_amount <= 0 or refund_amount > plan_row.total_micros - plan_row.refunded_micros then
    return false;
  end if;

  perform pg_advisory_xact_lock(hashtext(left(plan_row.tenant_slug, 64)));

  select balance_micros
    into new_balance
  from public.client_credit_accounts
  where tenant_slug = plan_row.tenant_slug
  for update;

  if new_balance is null or new_balance < refund_remaining then
    update public.client_credit_purchase_plans
    set reconciliation_status = 'drift',
        failure_reason = 'refund_exceeds_available_wallet',
        metadata = coalesce(metadata, '{}'::jsonb) || p_metadata,
        updated_at = now()
    where id = p_plan_id;
    return false;
  end if;

  for plan_allocation in
    select *
    from public.client_credit_purchase_plan_allocations
    where plan_id = p_plan_id
    order by id
    for update
  loop
    exit when refund_remaining = 0;
    allocation_refund := least(
      refund_remaining,
      greatest(0, plan_allocation.allocated_micros - plan_allocation.refunded_micros)
    );
    if allocation_refund = 0 then
      continue;
    end if;

    select greatest(0, purchased_micros - reserved_micros - spent_micros)
      into available
    from public.client_credit_budgets
    where tenant_slug = plan_row.tenant_slug
      and catalog_id = plan_allocation.catalog_id
      and provider_key = plan_allocation.provider_key;
    for update;

    if available is null or available < allocation_refund then
      raise exception 'refund_exceeds_spendable_allocation';
    end if;

    update public.client_credit_budgets
    set purchased_micros = purchased_micros - allocation_refund,
        updated_at = now()
    where tenant_slug = plan_row.tenant_slug
      and catalog_id = plan_allocation.catalog_id
      and provider_key = plan_allocation.provider_key

    update public.client_credit_purchase_plan_allocations
    set refunded_micros = refunded_micros + allocation_refund,
        updated_at = now()
    where id = plan_allocation.id
      and refunded_micros + allocation_refund <= allocated_micros;

    if not found then
      raise exception 'purchase_plan_allocation_refund_update_failed';
    end if;

    refund_remaining := refund_remaining - allocation_refund;
  end loop;

  if refund_remaining <> 0 then
    raise exception 'refund_allocation_incomplete';
  end if;

  update public.client_credit_accounts
  set balance_micros = balance_micros - refund_amount,
      updated_at = now()
  where tenant_slug = plan_row.tenant_slug
  returning balance_micros into new_balance;

  update public.client_credit_purchase_plans
  set status = case when plan_row.refunded_micros + refund_amount >= plan_row.total_micros
      then 'refunded' else status end,
      refunded_micros = refunded_micros + refund_amount,
      reconciliation_status = 'matched',
      metadata = coalesce(metadata, '{}'::jsonb) || p_metadata,
      updated_at = now()
  where id = p_plan_id;

  insert into public.client_credit_transactions (
    tenant_slug, idempotency_key, kind, amount_micros, balance_after_micros,
    stripe_event_id, metadata
  )
  values (
    plan_row.tenant_slug,
    'stripe-event:' || p_stripe_event_id,
    'refund',
    refund_amount,
    new_balance,
    p_stripe_event_id,
    jsonb_build_object('event_type', p_event_type, 'plan_id', p_plan_id, 'direction', 'returned') || p_metadata
  )
  on conflict (tenant_slug, idempotency_key) do nothing;

  return true;
end;
$$;

