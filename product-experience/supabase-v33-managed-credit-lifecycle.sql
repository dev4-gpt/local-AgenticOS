  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (plan_id, catalog_id),
  check (refunded_micros <= allocated_micros)
);

create index if not exists client_credit_purchase_plan_allocations_tenant_idx
  on public.client_credit_purchase_plan_allocations (tenant_slug, plan_id);

create or replace function public.sync_client_credit_purchase_plan_allocations()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if jsonb_typeof(new.allocations) = 'array' then
    insert into public.client_credit_purchase_plan_allocations (
      plan_id,
      tenant_slug,
      catalog_id,
      provider_key,
      allocated_micros,
      pricing_snapshot_id,
      metadata
    )
    select
      new.id,
      new.tenant_slug,
      item->>'catalog_id',
      item->>'provider_key',
      (item->>'amount_micros')::bigint,
      nullif(item->>'pricing_snapshot_id', ''),
      item
    from jsonb_array_elements(new.allocations) item
    where jsonb_typeof(item) = 'object'
      and coalesce(item->>'catalog_id', '') <> ''
      and coalesce(item->>'provider_key', '') <> ''
      and (item->>'amount_micros') ~ '^[0-9]+$'
      and (item->>'amount_micros')::bigint > 0
    on conflict (plan_id, catalog_id) do nothing;
  end if;
  return new;
end;
$$;

